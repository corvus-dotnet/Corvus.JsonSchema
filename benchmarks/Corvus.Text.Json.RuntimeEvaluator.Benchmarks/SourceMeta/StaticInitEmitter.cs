using System.Globalization;
using System.Text;
using Corvus.Text.Json;
using Corvus.Text.Json.Internal;
using Corvus.Text.Json.RuntimeEvaluator;
using Corvus.Text.Json.RuntimeEvaluator.Compilation;

namespace Corvus.Text.Json.RuntimeEvaluator.Benchmarks.SourceMeta;

/// <summary>
/// Measurement spike for the "emit the node graph as C# static initialisers" shape of ahead-of-time compilation:
/// writes, for each corpus, a C# class whose <c>Build</c> method constructs the compiled node graph with object
/// initialisers (chunked into methods of a fixed number of nodes), so that source size, Roslyn compile time and
/// type-initialisation time can be compared with loading a program image of the same graph.
/// </summary>
public static class StaticInitEmitter
{
    private const int NodesPerMethod = 32;

    public static int Run(string[] args)
    {
        if (args.Length < 1)
        {
            Console.Error.WriteLine("usage: emit <outdir> [names...]");
            return 2;
        }

        string outDir = args[0];
        Directory.CreateDirectory(outDir);
        string[] names = args.Length > 1 ? args[1..] : SourceMetaCases.All.Select(c => c.File).ToArray();
        foreach (string name in names)
        {
            JsonSchemaDialect dialect = SourceMetaCases.All.First(c => c.File == name).Dialect;
            byte[] schema = File.ReadAllBytes(Path.Combine(AppContext.BaseDirectory, "sourcemeta", name + "-schema.json"));
            using JsonSchemaEvaluator evaluator = JsonSchemaEvaluator.Compile(schema, new JsonSchemaEvaluatorOptions { DefaultDialect = dialect, CompileRegularExpressions = false });
            CompiledSchema program = evaluator.Program;
            string className = Identifier(name) + "Program";
            string source = Emit(className, program);
            File.WriteAllText(Path.Combine(outDir, className + ".g.cs"), source);
            File.WriteAllBytes(Path.Combine(outDir, name + ".cjsp"), evaluator.ToProgramImage());
            Console.WriteLine($"{name,-24} {program.Nodes.Length,6} nodes {Encoding.UTF8.GetByteCount(source),9} bytes of C#");
        }

        return 0;
    }

    public static string Identifier(string name)
    {
        var sb = new StringBuilder();
        bool upper = true;
        foreach (char c in name)
        {
            if (char.IsLetterOrDigit(c))
            {
                sb.Append(upper ? char.ToUpperInvariant(c) : c);
                upper = false;
            }
            else
            {
                upper = true;
            }
        }

        return sb.ToString();
    }

    private static string Emit(string className, CompiledSchema program)
    {
        SchemaNode[] nodes = program.Nodes;
        var constants = new List<byte[]>();
        var constantIndex = new Dictionary<(IJsonDocument, int), int>();
        int ConstIndex(in ConstantValue v)
        {
            (IJsonDocument, int) key = (v.Document, v.Index);
            if (!constantIndex.TryGetValue(key, out int i))
            {
                i = constants.Count;
                JsonElement element = Elements.Create<JsonElement>(v.Document, v.Index);
                constants.Add(Encoding.UTF8.GetBytes(element.GetRawText()));
                constantIndex[key] = i;
            }

            return i;
        }

        var body = new StringBuilder();
        int methods = (nodes.Length + NodesPerMethod - 1) / NodesPerMethod;
        for (int m = 0; m < methods; m++)
        {
            body.Append("    private static void Build").Append(m).AppendLine("(SchemaNode[] nodes, ConstantValue[] c, JsonSchemaEvaluatorOptions options)");
            body.AppendLine("    {");
            for (int i = m * NodesPerMethod; i < Math.Min(nodes.Length, (m + 1) * NodesPerMethod); i++)
            {
                EmitNode(body, nodes[i], i, ConstIndex);
            }

            body.AppendLine("    }");
            body.AppendLine();
        }

        var constantsJson = new StringBuilder("[");
        for (int i = 0; i < constants.Count; i++)
        {
            if (i > 0)
            {
                constantsJson.Append(',');
            }

            constantsJson.Append(Encoding.UTF8.GetString(constants[i]));
        }

        constantsJson.Append(']');

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine("using Corvus.Text.Json;");
        sb.AppendLine("using Corvus.Text.Json.Internal;");
        sb.AppendLine("using Corvus.Text.Json.RuntimeEvaluator;");
        sb.AppendLine("using Corvus.Text.Json.RuntimeEvaluator.Compilation;");
        sb.AppendLine();
        sb.AppendLine("namespace Spike;");
        sb.AppendLine();
        sb.Append("internal static class ").AppendLine(className);
        sb.AppendLine("{");
        sb.Append("    public const int NodeCount = ").Append(nodes.Length).AppendLine(";");
        sb.Append("    public const int RootNode = ").Append(program.RootNode).AppendLine(";");
        sb.Append("    public const bool UsesDynamicScope = ").Append(program.UsesDynamicScope ? "true" : "false").AppendLine(";");
        sb.Append("    public const int ResourceCount = ").Append(program.ResourceCount).AppendLine(";");
        sb.Append("    private static ReadOnlySpan<byte> ConstantsJson => ").Append(Utf8Literal(Encoding.UTF8.GetBytes(constantsJson.ToString()))).AppendLine(";");
        sb.AppendLine();
        sb.AppendLine("    public static CompiledSchema Build(JsonSchemaEvaluatorOptions options)");
        sb.AppendLine("    {");
        sb.AppendLine("        ParsedJsonDocument<JsonElement> constantsDocument = ParsedJsonDocument<JsonElement>.Parse(ConstantsJson.ToArray());");
        sb.Append("        var c = new ConstantValue[").Append(constants.Count).AppendLine("];");
        sb.AppendLine("        int ci = 0;");
        sb.AppendLine("        foreach (JsonElement v in constantsDocument.RootElement.EnumerateArray())");
        sb.AppendLine("        {");
        sb.AppendLine("            IJsonDocument d = Elements.Document(v);");
        sb.AppendLine("            int di = Elements.Index(v);");
        sb.AppendLine("            c[ci++] = new ConstantValue(d, di, d.GetJsonTokenType(di));");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        var nodes = new SchemaNode[NodeCount];");
        for (int m = 0; m < methods; m++)
        {
            sb.Append("        Build").Append(m).AppendLine("(nodes, c, options);");
        }

        sb.AppendLine("        var entryPoints = new Dictionary<string, int>(StringComparer.Ordinal)");
        sb.AppendLine("        {");
        foreach (KeyValuePair<string, int> e in program.EntryPoints)
        {
            sb.Append("            [").Append(StringLiteral(e.Key)).Append("] = ").Append(e.Value).AppendLine(",");
        }

        sb.AppendLine("        };");
        sb.AppendLine("        return new CompiledSchema(nodes, RootNode, UsesDynamicScope, ResourceCount, options, entryPoints, constantsDocument);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.Append(body);
        sb.AppendLine("}");
        return sb.ToString();
    }

    private delegate int ConstIndexer(in ConstantValue value);

    private static void EmitNode(StringBuilder sb, SchemaNode n, int index, ConstIndexer constIndex)
    {
        string p = "        ";
        string prefix = "n" + index.ToString(CultureInfo.InvariantCulture);

        // Property entries are shared between the map and the unrolled list, so they get locals.
        PropertyEntry[]? propertyValues = null;
        if (n.Properties is Utf8NameMap<PropertyEntry> properties)
        {
            propertyValues = properties.Values.ToArray();
            for (int i = 0; i < propertyValues.Length; i++)
            {
                PropertyEntry e = propertyValues[i];
                sb.Append(p).Append("var ").Append(prefix).Append('p').Append(i).Append(" = new PropertyEntry { Name = ").Append(Bytes(e.Name))
                  .Append(", Schema = ").Append(ChildRef(e.Schema)).Append(", SeenBit = ").Append(e.SeenBit).Append(", IsRequired = ").Append(Bool(e.IsRequired)).AppendLine(" };");
            }
        }

        sb.Append(p).Append("nodes[").Append(index).AppendLine("] = new SchemaNode");
        sb.Append(p).AppendLine("{");
        string f = p + "    ";
        sb.Append(f).Append("Id = ").Append(n.Id).Append(", ResourceId = ").Append(n.ResourceId).Append(", Dialect = JsonSchemaDialect.").Append(n.Dialect).AppendLine(",");
        sb.Append(f).Append("AlwaysTrue = ").Append(Bool(n.AlwaysTrue)).Append(", AlwaysFalse = ").Append(Bool(n.AlwaysFalse)).Append(", IsTypeOnly = ").Append(Bool(n.IsTypeOnly)).Append(", IsLeaf = ").Append(Bool(n.IsLeaf)).Append(", IsSimpleArray = ").Append(Bool(n.IsSimpleArray)).AppendLine(",");
        sb.Append(f).Append("TracksProperties = ").Append(Bool(n.TracksProperties)).Append(", TracksItems = ").Append(Bool(n.TracksItems)).Append(", MarksProperties = ").Append(Bool(n.MarksProperties)).Append(", MarksItems = ").Append(Bool(n.MarksItems)).AppendLine(",");
        sb.Append(f).Append("HasNumberKeywords = ").Append(Bool(n.HasNumberKeywords)).Append(", HasStringKeywords = ").Append(Bool(n.HasStringKeywords)).Append(", HasObjectKeywords = ").Append(Bool(n.HasObjectKeywords)).Append(", HasArrayKeywords = ").Append(Bool(n.HasArrayKeywords)).Append(", HasInPlaceApplicators = ").Append(Bool(n.HasInPlaceApplicators)).Append(", InPlaceCycle = ").Append(Bool(n.InPlaceCycle)).AppendLine(",");
        sb.Append(f).Append("Flags = (NodeFlags)").Append((uint)n.Flags).Append("u, Plan = NodePlan.").Append(n.Plan).Append(", HasSeenBits = ").Append(Bool(n.HasSeenBits)).AppendLine(",");
        sb.Append(f).Append("SchemaLocation = ").Append(Bytes(n.SchemaLocation)).AppendLine(",");
        sb.Append(f).Append("HasType = ").Append(Bool(n.HasType)).Append(", Type = (TypeMask)").Append((byte)n.Type).Append(", TypeMessage = SchemaCompiler.TypeMessageFor((TypeMask)").Append((byte)n.Type).AppendLine("),");

        sb.Append(f).Append("HasConst = ").Append(Bool(n.HasConst));
        if (n.HasConst)
        {
            sb.Append(", Const = c[").Append(constIndex(n.Const)).Append(']');
        }

        if (n.ConstString is byte[] cs)
        {
            sb.Append(", ConstString = ").Append(Bytes(cs)).Append(", ConstText = ").Append(StringLiteral(n.ConstText!));
        }
        else if (n.ConstNumber is NumberValue cn)
        {
            sb.Append(", ConstNumber = new NumberValue(").Append(Utf8Literal(Encoding.UTF8.GetBytes(cn.Text))).Append("), ConstText = ").Append(StringLiteral(cn.Text));
        }

        sb.AppendLine(",");
        if (n.Enum is ConstantValue[] values)
        {
            sb.Append(f).Append("Enum = new ConstantValue[] { ");
            foreach (ConstantValue v in values)
            {
                sb.Append("c[").Append(constIndex(v)).Append("], ");
            }

            sb.AppendLine("},");
        }

        sb.Append(f).Append("EnumAllStrings = ").Append(Bool(n.EnumAllStrings)).AppendLine(",");
        if (n.EnumStrings is Utf8NameMap<object> enumStrings)
        {
            sb.Append(f).Append("EnumStrings = new Utf8NameMap<object>(new KeyValuePair<byte[], object>[] { ");
            foreach (byte[] key in enumStrings.Keys)
            {
                sb.Append("new(").Append(Bytes(key)).Append(", SchemaCompiler.EnumSentinel), ");
            }

            sb.AppendLine("}),");
        }

        Number(sb, f, "Minimum", n.Minimum);
        Number(sb, f, "Maximum", n.Maximum);
        Number(sb, f, "ExclusiveMinimum", n.ExclusiveMinimum);
        Number(sb, f, "ExclusiveMaximum", n.ExclusiveMaximum);
        if (n.MultipleOf is DivisorValue divisor)
        {
            sb.Append(f).Append("MultipleOf = new DivisorValue(").Append(Utf8Literal(Encoding.UTF8.GetBytes(divisor.Text))).AppendLine("),");
        }

        sb.Append(f).Append("MinLength = ").Append(n.MinLength).Append(", MaxLength = ").Append(n.MaxLength).Append(", Format = (FormatKind)").Append((byte)n.Format).Append(", AssertFormat = ").Append(Bool(n.AssertFormat)).Append(", WarnFormat = ").Append(Bool(n.WarnFormat)).Append(", ElidedTarget = ").Append(n.ElidedTarget).Append(", Content = (ContentKind)").Append((byte)n.Content).Append(", AssertContent = ").Append(Bool(n.AssertContent)).AppendLine(",");
        if (n.Pattern is PatternMatcher pattern)
        {
            sb.Append(f).Append("Pattern = PatternMatcher.Create(").Append(StringLiteral(pattern.Source)).AppendLine(", options),");
        }

        if (propertyValues is not null)
        {
            sb.Append(f).Append("Properties = new Utf8NameMap<PropertyEntry>(new KeyValuePair<byte[], PropertyEntry>[] { ");
            for (int i = 0; i < propertyValues.Length; i++)
            {
                sb.Append("new(").Append(prefix).Append('p').Append(i).Append(".Name, ").Append(prefix).Append('p').Append(i).Append("), ");
            }

            sb.AppendLine("}),");
        }

        if (n.UnrolledProperties is PropertyEntry[] unrolled)
        {
            sb.Append(f).Append("UnrolledProperties = new PropertyEntry[] { ");
            foreach (PropertyEntry e in unrolled)
            {
                sb.Append(prefix).Append('p').Append(Array.IndexOf(propertyValues!, e)).Append(", ");
            }

            sb.AppendLine("},");
        }

        sb.Append(f).Append("SeenBitCount = ").Append(n.SeenBitCount).AppendLine(",");
        if (n.RequiredSeenBits is int[] rsb)
        {
            sb.Append(f).Append("RequiredSeenBits = ").Append(Ints(rsb)).AppendLine(",");
        }

        if (n.RequiredNames is byte[][] rn)
        {
            sb.Append(f).Append("RequiredNames = ").Append(ByteArrays(rn)).AppendLine(",");
        }

        if (n.PatternProperties is PatternPropertyEntry[] pps)
        {
            sb.Append(f).Append("PatternProperties = new PatternPropertyEntry[] { ");
            foreach (PatternPropertyEntry pp in pps)
            {
                sb.Append("new PatternPropertyEntry { Matcher = PatternMatcher.Create(").Append(StringLiteral(pp.Matcher.Source)).Append(", options), Schema = ").Append(ChildRef(pp.Schema)).Append(", Name = ").Append(Bytes(pp.Name)).Append(" }, ");
            }

            sb.AppendLine("},");
        }

        sb.Append(f).Append("AdditionalProperties = ").Append(ChildRef(n.AdditionalProperties)).Append(", PropertyNames = ").Append(ChildRef(n.PropertyNames)).Append(", UnevaluatedProperties = ").Append(ChildRef(n.UnevaluatedProperties)).AppendLine(",");
        sb.Append(f).Append("MinProperties = ").Append(n.MinProperties).Append(", MaxProperties = ").Append(n.MaxProperties).AppendLine(",");
        if (n.Dependencies is DependencyEntry[] deps)
        {
            sb.Append(f).Append("Dependencies = new DependencyEntry[] { ");
            foreach (DependencyEntry d in deps)
            {
                sb.Append("new DependencyEntry { Name = ").Append(Bytes(d.Name)).Append(", NameText = ").Append(StringLiteral(d.NameText)).Append(", SeenBit = ").Append(d.SeenBit)
                  .Append(", RequiredSeenBits = ").Append(Ints(d.RequiredSeenBits)).Append(", RequiredNames = ").Append(ByteArrays(d.RequiredNames)).Append(", Schema = ").Append(ChildRef(d.Schema)).Append(" }, ");
            }

            sb.AppendLine("},");
        }

        if (n.PrefixItems is ChildRef[] prefixItems)
        {
            sb.Append(f).Append("PrefixItems = ").Append(ChildRefs(prefixItems)).AppendLine(",");
        }

        sb.Append(f).Append("Items = ").Append(ChildRef(n.Items)).Append(", Contains = ").Append(ChildRef(n.Contains)).Append(", MinContains = ").Append(n.MinContains).Append(", MaxContains = ").Append(n.MaxContains).Append(", UniqueItems = ").Append(Bool(n.UniqueItems)).Append(", MinItems = ").Append(n.MinItems).Append(", MaxItems = ").Append(n.MaxItems).Append(", UnevaluatedItems = ").Append(ChildRef(n.UnevaluatedItems)).Append(", ContainsMarksEvaluated = ").Append(Bool(n.ContainsMarksEvaluated)).AppendLine(",");
        sb.Append(f).Append("Ref = ").Append(ChildRef(n.Ref)).AppendLine(",");
        if (n.DynamicRef is DynamicRefTarget dr)
        {
            sb.Append(f).Append("DynamicRef = new DynamicRefTarget { Anchor = ").Append(StringLiteral(dr.Anchor)).Append(", FallbackNode = ").Append(dr.FallbackNode).Append(", NodeByResource = ").Append(Ints(dr.NodeByResource)).Append(", PathSegment = ").Append(Bytes(dr.PathSegment)).Append(", IsRecursive = ").Append(Bool(dr.IsRecursive)).AppendLine(" },");
        }

        if (n.AllOf is ChildRef[] allOf)
        {
            sb.Append(f).Append("AllOf = ").Append(ChildRefs(allOf)).AppendLine(",");
        }

        if (n.AnyOf is ChildRef[] anyOf)
        {
            sb.Append(f).Append("AnyOf = ").Append(ChildRefs(anyOf)).AppendLine(",");
        }

        if (n.OneOf is ChildRef[] oneOf)
        {
            sb.Append(f).Append("OneOf = ").Append(ChildRefs(oneOf)).AppendLine(",");
        }

        Discriminator(sb, f, "AnyOfDiscriminator", n.AnyOfDiscriminator);
        Discriminator(sb, f, "OneOfDiscriminator", n.OneOfDiscriminator);
        sb.Append(f).Append("AnyOfTypeUnion = (TypeMask)").Append((byte)n.AnyOfTypeUnion).Append(", OneOfTypeUnion = (TypeMask)").Append((byte)n.OneOfTypeUnion).AppendLine(",");
        sb.Append(f).Append("Not = ").Append(ChildRef(n.Not)).Append(", If = ").Append(ChildRef(n.If)).Append(", Then = ").Append(ChildRef(n.Then)).Append(", Else = ").Append(ChildRef(n.Else)).AppendLine(",");
        if (n.Annotations is AnnotationEntry[] annotations)
        {
            sb.Append(f).Append("Annotations = new AnnotationEntry[] { ");
            foreach (AnnotationEntry a in annotations)
            {
                sb.Append("new AnnotationEntry { Keyword = ").Append(Bytes(a.Keyword)).Append(", RawJson = ").Append(Bytes(a.RawJson)).Append(", StringsOnly = ").Append(Bool(a.StringsOnly)).Append(" }, ");
            }

            sb.AppendLine("},");
        }

        sb.Append(p).AppendLine("};");
    }

    private static void Number(StringBuilder sb, string f, string name, NumberValue? value)
    {
        if (value is not null)
        {
            sb.Append(f).Append(name).Append(" = new NumberValue(").Append(Utf8Literal(Encoding.UTF8.GetBytes(value.Text))).AppendLine("),");
        }
    }

    private static void Discriminator(StringBuilder sb, string f, string name, Discriminator? d)
    {
        if (d is null)
        {
            return;
        }

        sb.Append(f).Append(name).Append(" = new Discriminator { PropertyName = ").Append(Bytes(d.PropertyName)).Append(", KnownValues = new Utf8NameMap<int[]>(new KeyValuePair<byte[], int[]>[] { ");
        byte[][] keys = d.KnownValues.Keys;
        ReadOnlySpan<int[]> values = d.KnownValues.Values;
        for (int i = 0; i < keys.Length; i++)
        {
            sb.Append("new(").Append(Bytes(keys[i])).Append(", ").Append(Ints(values[i])).Append("), ");
        }

        sb.Append("}), UnknownString = ").Append(Ints(d.UnknownString)).Append(", NonString = ").Append(Ints(d.NonString)).Append(", AllRequire = ").Append(Bool(d.AllRequire)).AppendLine(" },");
    }

    private static string ChildRef(in ChildRef c)
    {
        if (!c.IsPresent)
        {
            return "ChildRef.None";
        }

        return "new ChildRef(" + c.Node.ToString(CultureInfo.InvariantCulture) + ", " + Bytes(c.Path) + ") { CollectingPath = " + Bytes(c.CollectingPath) + ", FastNode = " + c.FastNode.ToString(CultureInfo.InvariantCulture) + " }";
    }

    private static string ChildRefs(ChildRef[] refs)
    {
        var sb = new StringBuilder("new ChildRef[] { ");
        foreach (ChildRef c in refs)
        {
            sb.Append(ChildRef(c)).Append(", ");
        }

        return sb.Append('}').ToString();
    }

    private static string Ints(int[] values)
    {
        var sb = new StringBuilder("new int[] { ");
        foreach (int v in values)
        {
            sb.Append(v.ToString(CultureInfo.InvariantCulture)).Append(", ");
        }

        return sb.Append('}').ToString();
    }

    private static string ByteArrays(byte[][] values)
    {
        var sb = new StringBuilder("new byte[][] { ");
        foreach (byte[] v in values)
        {
            sb.Append(Bytes(v)).Append(", ");
        }

        return sb.Append('}').ToString();
    }

    private static string Bool(bool value) => value ? "true" : "false";

    private static string Bytes(byte[]? value)
    {
        if (value is null)
        {
            return "null";
        }

        if (value.Length == 0)
        {
            return "System.Array.Empty<byte>()";
        }

        return Utf8Literal(value) + ".ToArray()";
    }

    /// <summary>Emits a UTF-8 literal (<c>"..."u8</c>) for bytes that are valid UTF-8, else a byte array.</summary>
    private static string Utf8Literal(byte[] value)
    {
        string text;
        try
        {
            text = new UTF8Encoding(false, true).GetString(value);
        }
        catch (DecoderFallbackException)
        {
            var raw = new StringBuilder("new byte[] { ");
            foreach (byte b in value)
            {
                raw.Append(b).Append(", ");
            }

            return raw.Append("}.AsSpan()").ToString();
        }

        return StringLiteral(text) + "u8";
    }

    private static string StringLiteral(string text)
    {
        var sb = new StringBuilder("\"");
        foreach (char c in text)
        {
            switch (c)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default:
                    if (c < 0x20 || c > 0x7E)
                    {
                        sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        sb.Append(c);
                    }

                    break;
            }
        }

        return sb.Append('"').ToString();
    }
}
