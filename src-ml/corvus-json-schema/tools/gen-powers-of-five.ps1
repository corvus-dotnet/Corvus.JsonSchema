<#
.SYNOPSIS
Writes src/powers_of_five.ml: the 128-bit truncated powers of five from 5^-342 to 5^308 that the Eisel-Lemire decimal
to double conversion of the Numbers module reads.

.DESCRIPTION
Each power is normalised (its top bit is set) and written as its high word then its low word. A positive power is
5^q shifted to 128 bits. A negative one is the reciprocal of 5^-q, rounded up, as the fast_float library computes
it (Daniel Lemire, "Number Parsing at a Gigabyte per Second"). The Java port holds the same table
(FastDoubleTable.java), and -Check compares this script's with it and with the file that is there.

OCaml has no unsigned 64-bit literal that every supported compiler reads without boxing, so the table is one string:
each word is eight bytes, least significant first, which String.get_int64_le reads.

.EXAMPLE
pwsh tools/gen-powers-of-five.ps1
pwsh tools/gen-powers-of-five.ps1 -Check
#>
[CmdletBinding()]
param(
    # Compare the table with the Java port's and the file with what would be written, and write nothing.
    [switch] $Check
)

$ErrorActionPreference = "Stop"
$one = [bigint]::One
$two127 = [bigint]::Pow(2, 127)
$two128 = [bigint]::Pow(2, 128)
$mask64 = [bigint]::Pow(2, 64) - 1

$words = [System.Collections.Generic.List[uint64]]::new()
for ($q = -342; $q -le 308; $q++) {
    if ($q -lt 0) {
        $power5 = [bigint]::Pow(5, -$q)
        $z = 0
        while (($one -shl $z) -lt $power5) { $z++ }
        $bits = if ($q -ge -27) { $z + 127 } else { 2 * $z + 128 }
        $c = [bigint]::Divide($one -shl $bits, $power5) + 1
        while ($c -ge $two128) { $c = [bigint]::Divide($c, 2) }
    } else {
        $c = [bigint]::Pow(5, $q)
        while ($c -lt $two127) { $c = $c * 2 }
        while ($c -ge $two128) { $c = [bigint]::Divide($c, 2) }
    }
    $words.Add([uint64]($c -shr 64))
    $words.Add([uint64]($c -band $mask64))
}

$root = Split-Path -Parent $PSScriptRoot
$nl = "`n"
$out = [System.Text.StringBuilder]::new()
[void] $out.Append("(* Generated by tools/gen-powers-of-five.ps1. Do not edit.$nl$nl")
[void] $out.Append("   The 128-bit truncated powers of five from 5^-342 to 5^308, high word then low word, normalised. Each word is$nl")
[void] $out.Append("   eight bytes, least significant first. *)$nl$nl")
[void] $out.Append("[@@@ocamlformat `"disable`"]$nl$nl")
[void] $out.Append("(** The number of 64-bit words in {!table}. *)$nl")
[void] $out.Append("let words = $($words.Count)$nl$nl")
[void] $out.Append("(** The words. Word [i] is the eight bytes from [8 * i]. *)$nl")
[void] $out.Append("let table =$nl  `"")
for ($i = 0; $i -lt $words.Count; $i++) {
    if ($i % 2 -eq 0) { [void] $out.Append("\$nl   ") }
    $bytes = [System.BitConverter]::GetBytes($words[$i])
    if (-not [System.BitConverter]::IsLittleEndian) { [System.Array]::Reverse($bytes) }
    foreach ($b in $bytes) { [void] $out.Append("\x" + $b.ToString("x2")) }
}
[void] $out.Append("`"$nl")
$text = $out.ToString()
$target = Join-Path $root "src/powers_of_five.ml"

if ($Check) {
    $java = Join-Path $root "../../src-java/corvus-json-schema/src/main/java/io/github/corvusdotnet/jsonschema/FastDoubleTable.java"
    $theirs = @([regex]::Matches((Get-Content -Raw $java), "0x([0-9a-fA-F]{16})L") | ForEach-Object { $_.Groups[1].Value.ToUpperInvariant() })
    if ($theirs.Count -ne $words.Count) { throw "The Java table has $($theirs.Count) words and this one $($words.Count)." }
    for ($i = 0; $i -lt $words.Count; $i++) {
        if ($theirs[$i] -ne $words[$i].ToString("X16")) { throw "Word $i differs: Java $($theirs[$i]), here $($words[$i].ToString('X16'))." }
    }
    $current = if (Test-Path $target) { [System.IO.File]::ReadAllText($target) } else { "" }
    if ($current -ne $text) {
        Write-Error "$target is stale: run pwsh tools/gen-powers-of-five.ps1"
        exit 1
    }
    Write-Host "$($words.Count) words, the same as the Java port's table, and $target is current."
    exit 0
}
[System.IO.File]::WriteAllText($target, $text, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $target ($($words.Count) words)."
