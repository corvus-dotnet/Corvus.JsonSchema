<#
.SYNOPSIS
Writes src/Corvus.JsonSchema.PowersOfFive.inc: the 128-bit truncated powers of five from 5^-342 to 5^308 that the
Eisel-Lemire decimal to double conversion of Corvus.JsonSchema.Numbers reads.

.DESCRIPTION
Each power is normalised (its top bit is set) and written as its high word then its low word. A positive power is
5^q shifted to 128 bits. A negative one is the reciprocal of 5^-q, rounded up, as the fast_float library computes
it (Daniel Lemire, "Number Parsing at a Gigabyte per Second"). The Java port holds the same table
(FastDoubleTable.java), and -Check compares this script's with it.

.EXAMPLE
pwsh tools/gen-powers-of-five.ps1
pwsh tools/gen-powers-of-five.ps1 -Check
#>
[CmdletBinding()]
param(
    # Compare the table with the Java port's, and write nothing.
    [switch] $Check
)

$ErrorActionPreference = "Stop"
$one = [bigint]::One
$two127 = [bigint]::Pow(2, 127)
$two128 = [bigint]::Pow(2, 128)
$mask64 = [bigint]::Pow(2, 64) - 1

$words = [System.Collections.Generic.List[string]]::new()
for ($q = -342; $q -le 308; $q++) {
    if ($q -lt 0) {
        $power5 = [bigint]::Pow(5, -$q)
        $z = 0
        while (($one -shl $z) -lt $power5) { $z++ }
        $bits = if ($q -ge -27) { $z + 127 } else { 2 * $z + 128 }
        $c = [bigint]::Divide($one -shl $bits, $power5) + 1
        while ($c -ge $two128) { $c = [bigint]::Divide($c, 2) }
    } else {
        $c = [bigint]::Pow(5, $q)
        while ($c -lt $two127) { $c = $c * 2 }
        while ($c -ge $two128) { $c = [bigint]::Divide($c, 2) }
    }
    $high = [uint64]($c -shr 64)
    $low = [uint64]($c -band $mask64)
    $words.Add($high.ToString("X16"))
    $words.Add($low.ToString("X16"))
}

$root = Split-Path -Parent $PSScriptRoot
if ($Check) {
    $java = Join-Path $root "../../src-java/corvus-json-schema/src/main/java/io/github/corvusdotnet/jsonschema/FastDoubleTable.java"
    $theirs = @([regex]::Matches((Get-Content -Raw $java), "0x([0-9a-fA-F]{16})L") | ForEach-Object { $_.Groups[1].Value.ToUpperInvariant() })
    if ($theirs.Count -ne $words.Count) { throw "The Java table has $($theirs.Count) words and this one $($words.Count)." }
    for ($i = 0; $i -lt $words.Count; $i++) {
        if ($theirs[$i] -ne $words[$i]) { throw "Word $i differs: Java $($theirs[$i]), here $($words[$i])." }
    }
    Write-Host "$($words.Count) words, the same as the Java port's table."
    return
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("{ Generated by tools/gen-powers-of-five.ps1. Do not edit.")
$lines.Add("")
$lines.Add("  The 128-bit truncated powers of five from 5^-342 to 5^308, high word then low word, normalised. }")
$lines.Add("")
$lines.Add("const")
$lines.Add("  PowersOfFive: array[0..$($words.Count - 1)] of UInt64 = (")
for ($i = 0; $i -lt $words.Count; $i += 4) {
    $row = @($words[$i..([math]::Min($i + 3, $words.Count - 1))] | ForEach-Object { "UInt64(`$$_)" }) -join ", "
    $end = if ($i + 4 -ge $words.Count) { ");" } else { "," }
    $lines.Add("    $row$end")
}
$target = Join-Path $root "src/Corvus.JsonSchema.PowersOfFive.inc"
[System.IO.File]::WriteAllText($target, ($lines -join "`n"))
Write-Host "Wrote $target ($($words.Count) words)."
