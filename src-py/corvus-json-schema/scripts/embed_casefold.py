"""Generates src/corvus_json_schema/_casefold.py from the Unicode Character Database, so a case-insensitive group of
a pattern means the same on every version of Python.

    python scripts/embed_casefold.py <directory with CaseFolding.txt, UnicodeData.txt and SpecialCasing.txt>

The files are those of https://www.unicode.org/Public/16.0.0/ucd/ (Unicode 16, which is what V8 13.6 has).
"""

import sys
from collections import defaultdict
from pathlib import Path

here = Path(__file__).resolve().parent
ucd = Path(sys.argv[1])


def rows(name: str) -> list[list[str]]:
    out = []
    for line in (ucd / name).read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if line:
            out.append([field.strip() for field in line.split(";")])
    return out


def classes(canonical: dict[int, int]) -> list[list[int]]:
    """The sets of characters that have one canonical form, where a set has more than one member."""
    by_form: dict[int, set[int]] = defaultdict(set)
    for c, form in canonical.items():
        by_form[form].add(c)
        by_form[form].add(form)
    return sorted(sorted(members) for members in by_form.values() if len(members) > 1)


# With the u flag: simple case folding (the C and S rows of CaseFolding.txt).
version = (ucd / "CaseFolding.txt").read_text(encoding="utf-8").splitlines()[0].lstrip("# ").strip()
folding = {int(r[0], 16): int(r[2], 16) for r in rows("CaseFolding.txt") if r[1] in ("C", "S")}

# Without it: the uppercase form of a UTF-16 code unit when that is one code unit, and never a character outside
# ASCII to one inside it.
several = {int(r[0], 16) for r in rows("SpecialCasing.txt") if len(r) < 5 or not r[4]}
several = {c for c in several if any(len(r[3].split()) != 1 for r in rows("SpecialCasing.txt") if int(r[0], 16) == c)}
upper: dict[int, int] = {}
for r in rows("UnicodeData.txt"):
    c = int(r[0], 16)
    if r[12] and c <= 0xFFFF and c not in several:
        u = int(r[12], 16)
        if u <= 0xFFFF and not (c >= 128 and u < 128):
            upper[c] = u


def literal(members: list[int]) -> str:
    return "".join(chr(c) if c < 128 else f"\\u{c:04x}" if c <= 0xFFFF else f"\\U{c:08x}" for c in members)


def constant(name: str, sets: list[list[int]]) -> str:
    out = f"{name} = (\n"
    line = ""
    for members in sets:
        text = literal(members) + " "
        if len(line) + len(text) > 110:
            out += f'    "{line}"\n'
            line = ""
        line += text
    return out + f'    "{line.rstrip()}"\n)\n'


out = f"# <auto-generated> by scripts/embed_casefold.py from {version}. Do not edit.\n\n"
out += '"""The characters that are equal to another when case is ignored, in sets, with a space after each set.\n\n'
out += "``UNICODE`` is for a pattern with the ``u`` flag (simple case folding) and ``LEGACY`` for one without it (the\n"
out += 'uppercase form of a UTF-16 code unit)."""\n\n'
out += constant("UNICODE", classes(folding)) + "\n" + constant("LEGACY", classes(upper))
(here.parent / "src" / "corvus_json_schema" / "_casefold.py").write_text(out, encoding="utf-8")
print(f"Embedded {len(classes(folding))} and {len(classes(upper))} sets from {version}.")
