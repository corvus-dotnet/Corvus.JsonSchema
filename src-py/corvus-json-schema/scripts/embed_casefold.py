"""Generates src/corvus_json_schema/_casefold.py, so a case-insensitive group of a pattern means the same on every
version of Python and with every release of the regex package.

    python scripts/embed_casefold.py

The data is that of the Go module of this repository: the simple case folding and the simple uppercase mapping of
src-go/corvus-json-schema/internal/ucd/tables_gen.go (Unicode 17.0.0, from the tables of the regress crate), and
the characters whose uppercase form is more than one character, which
src-go/corvus-json-schema/internal/ecmaregex/fold.go lists. Every port of the evaluator reads the same tables.
"""

import re
from collections import defaultdict
from pathlib import Path

here = Path(__file__).resolve().parent
go = here.parents[2] / "src-go" / "corvus-json-schema" / "internal"
source = (go / "ucd" / "tables_gen.go").read_text(encoding="utf-8")
version = re.search(r'const Version = "([0-9.]+)"', source)
assert version is not None


def mapping(name: str) -> dict[int, int]:
    """One of the case tables. A row is the first code point of a range, the amount to add, the length of the range
    and a mask: the amount applies to the code points whose offset in the range has none of the bits of the mask."""
    body = re.search(rf"^var {name} = \[\]caseRange\{{\n(.*?)^\}}", source, re.M | re.S)
    assert body is not None, name
    out: dict[int, int] = {}
    for first, delta, length, mask in re.findall(r"\{(0x[0-9A-Fa-f]+), (-?\d+), (\d+), (\d+)\}", body.group(1)):
        for offset in range(int(length)):
            if offset & int(mask) == 0 and int(delta) != 0:
                out[int(first, 16) + offset] = int(first, 16) + offset + int(delta)
    return out


def classes(canonical: dict[int, int]) -> list[list[int]]:
    """The sets of characters that have one canonical form, where a set has more than one member."""
    by_form: dict[int, set[int]] = defaultdict(set)
    for c, form in canonical.items():
        by_form[form].add(c)
        by_form[form].add(form)
    return sorted(sorted(members) for members in by_form.values() if len(members) > 1)


# With the u flag: simple case folding (the C and S rows of CaseFolding.txt).
folding = mapping("caseFolds")
folding.update({c: c + 32 for c in range(0x41, 0x5B)})

# Without it: the uppercase form of a UTF-16 code unit when that is one code unit, and never a character outside
# ASCII to one inside it. A character whose uppercase form is more than one character is left as it is.
fold_go = (go / "ecmaregex" / "fold.go").read_text(encoding="utf-8")
several_body = re.search(r"var multiUpper = newCharSet\(\[\]rune\{(.*?)\}, false\)", fold_go, re.S)
assert several_body is not None
bounds = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", several_body.group(1))]
several = {c for lo, hi in zip(bounds[::2], bounds[1::2], strict=True) for c in range(lo, hi + 1)}
simple_upper = mapping("upperCases")
simple_upper.update({c: c - 32 for c in range(0x61, 0x7B)})
upper: dict[int, int] = {}
for c, u in simple_upper.items():
    if c <= 0xFFFF and c not in several and u <= 0xFFFF and not (c >= 128 and u < 128):
        upper[c] = u


def literal(members: list[int]) -> str:
    return "".join(chr(c) if c < 128 else f"\\u{c:04x}" if c <= 0xFFFF else f"\\U{c:08x}" for c in members)


def constant(name: str, sets: list[list[int]]) -> str:
    out = f"{name} = (\n"
    line = ""
    for members in sets:
        text = literal(members) + " "
        if len(line) + len(text) > 110:
            out += f'    "{line}"\n'
            line = ""
        line += text
    return out + f'    "{line.rstrip()}"\n)\n'


out = "# <auto-generated> by scripts/embed_casefold.py from the Unicode "
out += f"{version.group(1)} tables of src-go/corvus-json-schema/internal/ucd. Do not edit.\n\n"
out += '"""The characters that are equal to another when case is ignored, in sets, with a space after each set.\n\n'
out += "``UNICODE`` is for a pattern with the ``u`` flag (simple case folding) and ``LEGACY`` for one without it (the\n"
out += 'uppercase form of a UTF-16 code unit)."""\n\n'
out += constant("UNICODE", classes(folding)) + "\n" + constant("LEGACY", classes(upper))
(here.parent / "src" / "corvus_json_schema" / "_casefold.py").write_text(out, encoding="utf-8")
print(f"Embedded {len(classes(folding))} and {len(classes(upper))} sets of Unicode {version.group(1)}.")
