"""Generates src/corvus_json_schema/_metaschemas.py from the metaschemas embedded in Corvus.Text.Json
(src/Corvus.Text.Json/metaschema), so the Python evaluator resolves the same set.

    python scripts/embed_metaschemas.py
"""

import json
from pathlib import Path

here = Path(__file__).resolve().parent
root = here.parents[2] / "src" / "Corvus.Text.Json" / "metaschema"

files = {
    "http://json-schema.org/draft-04/schema": "draft4/schema.json",
    "http://json-schema.org/draft-06/schema": "draft6/schema.json",
    "http://json-schema.org/draft-07/schema": "draft7/schema.json",
    "https://json-schema.org/draft/2019-09/schema": "draft2019-09/schema.json",
    "https://json-schema.org/draft/2020-12/schema": "draft2020-12/schema.json",
}
for draft in ("2019-09", "2020-12"):
    for f in sorted((root / f"draft{draft}" / "meta").glob("*.json")):
        files[f"https://json-schema.org/draft/{draft}/meta/{f.stem}"] = f"draft{draft}/meta/{f.name}"

out = "# <auto-generated> by scripts/embed_metaschemas.py from src/Corvus.Text.Json/metaschema. Do not edit.\n\n"
out += '"""The standard metaschemas, keyed by their canonical URI (no trailing empty fragment)."""\n\n'
out += "METASCHEMAS: dict[str, str] = {\n"
for uri, file in files.items():
    text = json.dumps(json.loads((root / file).read_text(encoding="utf-8")), separators=(",", ":"), ensure_ascii=False)
    out += f"    {json.dumps(uri)}: {text!r},\n"
out += "}\n"
(here.parent / "src" / "corvus_json_schema" / "_metaschemas.py").write_text(out, encoding="utf-8")
print(f"Embedded {len(files)} metaschemas.")
