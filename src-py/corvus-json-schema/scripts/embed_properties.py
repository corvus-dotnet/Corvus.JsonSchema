"""Generates src/corvus_json_schema/_properties.py: the names a ``\\p{...}`` of a pattern may have in ECMA-262, so
that a pattern is read in the same way whatever names the engine that runs it has.

    python scripts/embed_properties.py <directory with PropertyValueAliases.txt and DerivedNormalizationProps.txt>

The files are those of https://www.unicode.org/Public/16.0.0/ucd/ (Unicode 16, which is what V8 13.6 has). ECMA-262
takes the values of General_Category, Script and Script_Extensions from PropertyValueAliases.txt, and lists the
binary properties itself (the table "Binary Unicode property aliases and their canonical property names", copied
below from the 2025 edition).
"""

