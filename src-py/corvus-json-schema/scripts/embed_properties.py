def rows(name: str) -> list[list[str]]:
    out = []
    for line in (ucd / name).read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if line:
            out.append([field.strip() for field in line.split(";")])
    return out


def values(prop: str) -> list[str]:
    """The values of a property, each as its short name and then its other names."""
    out = []
    for r in rows("PropertyValueAliases.txt"):
        if r[0] == prop:
            names = list(dict.fromkeys(r[1:]))
            out.append(" ".join(names))
    return out


def constant(name: str, items: list[str], separator: str) -> str:
    out = f"{name} = (\n"
    line = ""
    for k, item in enumerate(items):
        text = item + (separator if k + 1 < len(items) else "")
        if len(line) + len(text) > 110:
            out += f'    "{line}"\n'
            line = ""
        line += text
    return out + f'    "{line}"\n)\n'


version = (ucd / "PropertyValueAliases.txt").read_text(encoding="utf-8").splitlines()[0].lstrip("# ").strip()
ranges: list[list[int]] = []
for r in rows("DerivedNormalizationProps.txt"):
    if len(r) == 2 and r[1] == "Changes_When_NFKC_Casefolded":
        lo, _, hi = r[0].partition("..")
        first, last = int(lo, 16), int(hi or lo, 16)
        if ranges and ranges[-1][1] + 1 == first:
            ranges[-1][1] = last
        else:
            ranges.append([first, last])
changes = [f"{lo:x}" if lo == hi else f"{lo:x}-{hi:x}" for lo, hi in sorted(ranges)]

out = f"# <auto-generated> by scripts/embed_properties.py from {version}. Do not edit.\n\n"
out += '"""The property expressions of ECMA-262: what may be written in a ``\\\\p{...}`` of a pattern with the ``u`` flag.\n\n'
out += "``GENERAL_CATEGORY`` and ``SCRIPT`` have the values of those properties, with a semicolon after each value. A\n"
out += (
    "value is its short name and then its other names. ``BINARY`` has the binary properties that ECMA-262 lists, each\n"
)
out += (
    "as its name and then its alias. ``CHANGES_WHEN_NFKC_CASEFOLDED`` has the characters of that property, which the\n"
)
out += 'regex package does not have, as ranges in hexadecimal."""\n\n'
out += constant("GENERAL_CATEGORY", values("gc"), ";") + "\n"
out += constant("SCRIPT", values("sc"), ";") + "\n"
out += constant("BINARY", BINARY.split("\n"), ";") + "\n"
out += constant("CHANGES_WHEN_NFKC_CASEFOLDED", changes, " ")
(here.parent / "src" / "corvus_json_schema" / "_properties.py").write_text(out, encoding="utf-8")
print(f"Embedded {len(values('gc'))} categories, {len(values('sc'))} scripts and {len(changes)} ranges from {version}.")
