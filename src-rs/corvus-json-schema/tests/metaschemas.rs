//! Keeps `src/metaschemas.rs` in step with the metaschemas embedded in Corvus.Text.Json
//! (`src/Corvus.Text.Json/metaschema`). Regenerate with `UPDATE_METASCHEMAS=1 cargo test --test metaschemas`.

use std::fs;
use std::path::{Path, PathBuf};

fn source_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src/Corvus.Text.Json/metaschema")
}

fn generate(root: &Path) -> String {
    let mut map: Vec<(String, String)> = vec![
        ("http://json-schema.org/draft-04/schema".into(), "draft4/schema.json".into()),
        ("http://json-schema.org/draft-06/schema".into(), "draft6/schema.json".into()),
        ("http://json-schema.org/draft-07/schema".into(), "draft7/schema.json".into()),
        ("https://json-schema.org/draft/2019-09/schema".into(), "draft2019-09/schema.json".into()),
        ("https://json-schema.org/draft/2020-12/schema".into(), "draft2020-12/schema.json".into()),
    ];
    for draft in ["2019-09", "2020-12"] {
        let dir = root.join(format!("draft{draft}")).join("meta");
        let mut files: Vec<String> =
            fs::read_dir(&dir).unwrap().map(|e| e.unwrap().file_name().to_string_lossy().into_owned()).collect();
        files.sort();
        for f in files {
            let name = f.trim_end_matches(".json");
            map.push((format!("https://json-schema.org/draft/{draft}/meta/{name}"), format!("draft{draft}/meta/{f}")));
        }
    }
    let mut out = String::from(
        "// <auto-generated> by tests/metaschemas.rs from src/Corvus.Text.Json/metaschema. Do not edit.\n\n\
         /// The standard metaschemas, keyed by their canonical URI (no trailing empty fragment).\n\
         pub(crate) fn metaschema(uri: &str) -> Option<&'static str> {\n    match uri {\n",
    );
    for (uri, file) in map {
        let text = fs::read_to_string(root.join(&file)).unwrap();
        let value: serde_json::Value = serde_json::from_str(&text).unwrap();
        let json = serde_json::to_string(&value).unwrap();
        assert!(!json.contains("\"####"));
        out.push_str(&format!("        {uri:?} => Some(r####\"{json}\"####),\n"));
    }
    out.push_str("        _ => None,\n    }\n}\n");
    out
}

#[test]
fn embedded_metaschemas_are_current() {
    let root = source_root();
    if !root.exists() {
        // Outside the Corvus.JsonSchema repository (a published crate): nothing to compare against.
        return;
    }
    let generated = generate(&root);
    let target = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/metaschemas.rs");
    if std::env::var_os("UPDATE_METASCHEMAS").is_some() {
        fs::write(&target, &generated).unwrap();
        return;
    }
    let current = fs::read_to_string(&target).unwrap_or_default();
    assert!(
        current == generated,
        "src/metaschemas.rs is stale: run UPDATE_METASCHEMAS=1 cargo test --test metaschemas"
    );
}
