<#
.SYNOPSIS
    Writes src/ecmaregex/tables_gen.rs, the Unicode data of the crate.

.DESCRIPTION
    The crate takes every Unicode property its regular expression engine reads from the tables this script writes,
    and nothing from the Rust standard library or from the regex crate, so that its answers do not depend on the
    toolchain or on the versions of its dependencies.

    The source is tables_gen.go of the Go module (src-go/corvus-json-schema/internal/ucd), which its own
    gen_tables.ps1 writes from the Unicode Character Database tables of the regress crate. This script changes the
    Go syntax of that file into Rust and nothing else: the same tables with the same ranges in the same order, the
    same lookups by name, the simple case folding and the simple uppercase mapping. So the two ports hold the same
    data, and the test tables_are_those_of_the_go_module compares them again from the Go file.

.PARAMETER GoTables
    The path of tables_gen.go. The default is the one of this repository.

.PARAMETER Output
    The file to write. The default is src/ecmaregex/tables_gen.rs of the crate.

.EXAMPLE
    pwsh tools/gen-ucd-tables.ps1
#>
param(
    [string]$GoTables = (Join-Path $PSScriptRoot '../../../src-go/corvus-json-schema/internal/ucd/tables_gen.go'),
    [string]$Output = (Join-Path $PSScriptRoot '../src/ecmaregex/tables_gen.rs')
)

$ErrorActionPreference = 'Stop'
$lines = [System.IO.File]::ReadAllLines((Resolve-Path $GoTables))

# gcLu becomes GC_LU, binAsciiHexDigit becomes BIN_ASCII_HEX_DIGIT.
function ConvertTo-Constant([string]$name) {
    return ([regex]::Replace($name, '(?<=[a-z0-9])(?=[A-Z])', '_')).ToUpperInvariant()
}

$functions = @{
    'categoryTable'         = 'category_table'
    'binaryTable'           = 'binary_table'
    'scriptTable'           = 'script_table'
    'scriptExtensionsTable' = 'script_extensions_table'
}

$out = [System.Text.StringBuilder]::new()
function Add([string]$text) { [void]$out.Append($text).Append("`n") }

$version = $null
$mode = ''
foreach ($line in $lines) {
    if ($line -match '^// Code generated') {
        Add '// Code generated by tools/gen-ucd-tables.ps1 from tables_gen.go of the Go module, which holds the Unicode 17.0.0'
        Add '// property tables of the regress crate (gen-unicode). DO NOT EDIT.'
        continue
    }
    if ($line -match '^package ') {
        Add 'use super::ucd::{CaseRange, Table};'
        continue
    }
    if ($line -match '^const Version = "(.*)"$') {
        $version = $Matches[1]
        Add "pub(crate) const VERSION: &str = `"$version`";"
        continue
    }
    if ($line -match '^func (\w+)\(name string\) \*Table \{$') {
        Add "pub(super) fn $($functions[$Matches[1]])(name: &str) -> Option<&'static Table> {"
        $mode = 'lookup'
        continue
    }
    if ($mode -eq 'lookup') {
        if ($line -match '^\tswitch name \{$') { Add '    match name {'; continue }
        if ($line -match '^\tcase (.*):$') {
            $names = ($Matches[1] -split ', ') -join ' | '
            $pending = $names
            continue
        }
        if ($line -match '^\t\treturn &(\w+)$') {
            Add "        $pending => Some(&$(ConvertTo-Constant $Matches[1])),"
            continue
        }
        if ($line -match '^\t\}$') { Add '        _ => None,'; Add '    }'; continue }
        if ($line -match '^\treturn nil$') { continue }
        if ($line -eq '}') { Add '}'; $mode = ''; continue }
        throw "Unexpected line in a lookup: $line"
    }
    if ($line -match '^var scriptNames = ') { Add 'pub(super) static SCRIPT_NAMES: &[&[&str]] = &['; $mode = 'names2'; continue }
    if ($line -match '^var binaryNames = ') { Add 'pub(super) static BINARY_NAMES: &[&str] = &['; $mode = 'names1'; continue }
    if ($mode -eq 'names2') {
        if ($line -eq '}') { Add '];'; $mode = ''; continue }
        if ($line -match '^\t\{(.*)\},$') { Add "    &[$($Matches[1])],"; continue }
        throw "Unexpected line in the script names: $line"
    }
    if ($mode -eq 'names1') {
        if ($line -eq '}') { Add '];'; $mode = ''; continue }
        Add ('    ' + $line.Trim())
        continue
    }
    if ($line -match '^var (\w+) = Table\{$') {
        Add "pub(super) static $(ConvertTo-Constant $Matches[1]): Table = Table {"
        $mode = 'table'
        $seen = @{}
        continue
    }
    if ($mode -eq 'table') {
        if ($line -match '^\t(r16|r32): \[\]uint(16|32)\{$') { Add "    $($Matches[1]): &["; $seen[$Matches[1]] = $true; continue }
        if ($line -match '^\t\},$') { Add '    ],'; continue }
        if ($line -eq '}') {
            if (-not $seen['r16']) { Add '    r16: &[],' }
            if (-not $seen['r32']) { Add '    r32: &[],' }
            Add '};'
            $mode = ''
            continue
        }
        Add ('        ' + $line.Trim())
        continue
    }
    if ($line -match '^var (caseFolds|upperCases) = \[\]caseRange\{$') {
        Add "pub(super) static $(ConvertTo-Constant $Matches[1]): &[CaseRange] = &["
        $mode = 'cases'
        continue
    }
    if ($mode -eq 'cases') {
        if ($line -eq '}') { Add '];'; $mode = ''; continue }
        if ($line -match '^\t\{(\S+), (\S+), (\S+), (\S+)\},$') {
            Add "    CaseRange { first: $($Matches[1]), delta: $($Matches[2]), length: $($Matches[3]), mask: $($Matches[4]) },"
            continue
        }
        throw "Unexpected line in a case table: $line"
    }
    if ($line -match '^//' -or $line -eq '') { Add $line; continue }
    throw "Unexpected line: $line"
}
if (-not $version) { throw 'The source has no version.' }

# One newline at the end of the file.
[System.IO.File]::WriteAllText($Output, $out.ToString().TrimEnd("`n") + "`n")
Write-Host "Wrote $Output (Unicode $version)."
