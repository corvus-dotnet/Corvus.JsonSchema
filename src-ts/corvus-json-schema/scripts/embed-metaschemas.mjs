// Generates src/metaschemas.ts from the metaschemas embedded in Corvus.Text.Json
// (src/Corvus.Text.Json/metaschema), so the TypeScript evaluator resolves the same set.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../src/Corvus.Text.Json/metaschema');

const map = {
  'http://json-schema.org/draft-04/schema': 'draft4/schema.json',
  'http://json-schema.org/draft-06/schema': 'draft6/schema.json',
  'http://json-schema.org/draft-07/schema': 'draft7/schema.json',
  'https://json-schema.org/draft/2019-09/schema': 'draft2019-09/schema.json',
  'https://json-schema.org/draft/2020-12/schema': 'draft2020-12/schema.json',
};
for (const draft of ['2019-09', '2020-12']) {
  const dir = path.join(root, `draft${draft}`, 'meta');
  for (const f of fs.readdirSync(dir).sort()) {
    map[`https://json-schema.org/draft/${draft}/meta/${f.replace(/\.json$/, '')}`] = `draft${draft}/meta/${f}`;
  }
}

let out = '// <auto-generated> by scripts/embed-metaschemas.mjs from src/Corvus.Text.Json/metaschema. Do not edit.\n\n';
out += '/** The standard metaschemas, keyed by their canonical URI (no trailing empty fragment). */\n';
out += 'export const metaschemas: ReadonlyMap<string, string> = new Map<string, string>([\n';
for (const [uri, file] of Object.entries(map)) {
  const json = JSON.stringify(JSON.parse(fs.readFileSync(path.join(root, file), 'utf8')));
  out += `  [${JSON.stringify(uri)}, ${JSON.stringify(json)}],\n`;
}
out += ']);\n';
fs.writeFileSync(path.resolve(here, '../src/metaschemas.ts'), out);
console.log(`Embedded ${Object.keys(map).length} metaschemas.`);
