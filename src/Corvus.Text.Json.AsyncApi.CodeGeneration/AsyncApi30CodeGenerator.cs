using Corvus.Text;
using Corvus.Text.Json;
using Corvus.Text.Json.AsyncApi;
using Corvus.Text.Json.AsyncApi30;

namespace Corvus.Text.Json.AsyncApi.CodeGeneration;

/// <summary>
/// A code generator that walks the strongly-typed <see cref="AsyncApiDocument"/>
/// model (3.0) and emits C# source files for producers, consumers, and message types.
/// </summary>
/// <remarks>
/// <para>
/// In AsyncAPI 3.x, operations are top-level with an <c>action</c> of <c>send</c> or
/// <c>receive</c>, and reference channels via <c>$ref</c>. Channels contain messages
/// whose payloads and headers are JSON Schemas.
/// </para>
/// </remarks>
public sealed class AsyncApi30CodeGenerator
{
    private readonly string rootNamespace;
    private readonly IReadOnlyDictionary<string, string> schemaTypeMap;
    private readonly List<AsyncApiGenerationDiagnostic> diagnostics = [];

    /// <summary>
    /// Initializes a new instance of the <see cref="AsyncApi30CodeGenerator"/> class.
    /// </summary>
    /// <param name="rootNamespace">The root namespace for generated code.</param>
    /// <param name="schemaTypeMap">
    /// A map from JSON pointer strings to fully qualified .NET type names
    /// generated by the V5 code generator. Every schema pointer discovered
    /// during the walk must have a corresponding entry.
    /// </param>
    public AsyncApi30CodeGenerator(
        string rootNamespace,
        IReadOnlyDictionary<string, string> schemaTypeMap)
    {
        this.rootNamespace = rootNamespace;
        this.schemaTypeMap = schemaTypeMap;
    }

    /// <summary>
    /// Gets the problems the most recent <see cref="Generate"/> call encountered and worked
    /// around, such as references that did not resolve. Empty when generation was clean.
    /// </summary>
    public IReadOnlyList<AsyncApiGenerationDiagnostic> Diagnostics => this.diagnostics;

    /// <summary>
    /// Walks the AsyncAPI 3.0 specification and collects all schema
    /// JSON Pointer strings reachable from the selected operations.
    /// </summary>
    /// <param name="doc">The parsed AsyncAPI document.</param>
    /// <param name="filter">Optional operation filter (filters by channel address).</param>
    /// <param name="referenceResolver">
    /// Optional external reference resolver. When provided, external <c>$ref</c> pointers
    /// are resolved to absolute paths via <see cref="IAsyncApiReferenceResolver.ResolveToAbsolute(string)"/>.
    /// </param>
    /// <param name="diagnostics">
    /// Optional collection receiving a diagnostic for every entry that was skipped or degraded.
    /// </param>
    /// <returns>An array of schema pointer strings.</returns>
    public static string[] CollectSchemaPointers(
        AsyncApiDocument doc,
        OperationFilter? filter = null,
        IAsyncApiReferenceResolver? referenceResolver = null,
        ICollection<AsyncApiGenerationDiagnostic>? diagnostics = null)
    {
        List<string> pointers = [];

        if (doc.ChannelsValue.IsUndefined())
        {
            return [];
        }

        // Collect schemas from channels → messages → payload/headers
        foreach (var channelProp in doc.ChannelsValue.EnumerateObject())
        {
            string channelName = channelProp.Name;

            if (!TryResolveEntry(channelProp.Value, doc, referenceResolver, out JsonElement resolvedChannel))
            {
                diagnostics?.Add(new(
                    AsyncApiGenerationDiagnosticSeverity.Warning,
                    $"#/channels/{channelName}",
                    "The channel entry is a $ref that does not resolve; its message schemas were skipped."));
                continue;
            }

            AsyncApiDocument.Channel channel = resolvedChannel;

            if (channel.IsUndefined())
            {
                continue;
            }

            if (filter?.Matches(GetChannelAddress(channel, channelName)) == false)
            {
                continue;
            }

            using UnescapedUtf8JsonString channelNameUtf8 = channelProp.Utf8NameSpan;
            CollectChannelSchemaPointers(channelNameUtf8.Span, channel, pointers);
        }

        // Collect schemas from components/schemas
        if (doc.ComponentsValue.IsNotUndefined())
        {
            AsyncApiDocument.Components components = doc.ComponentsValue;
            if (components.Schemas.IsNotUndefined())
            {
                foreach (var schemaProp in components.Schemas.EnumerateObject())
                {
                    using UnescapedUtf8JsonString schemaName = schemaProp.Utf8NameSpan;
                    pointers.Add(AsyncApiSchemaPointerBuilder.ComponentSchema(schemaName.Span));
                }
            }

            // Collect inline payload/headers schemas from component messages
            if (components.Messages.IsNotUndefined())
            {
                foreach (var msgProp in components.Messages.EnumerateObject())
                {
                    using UnescapedUtf8JsonString msgName = msgProp.Utf8NameSpan;
                    AsyncApiDocument.MessageObject msg = msgProp.Value;

                    if (msg.Payload.IsNotUndefined())
                    {
                        pointers.Add(AsyncApiSchemaPointerBuilder.ComponentMessagePayload(msgName.Span));
                    }

                    if (msg.Headers.IsNotUndefined())
                    {
                        pointers.Add(AsyncApiSchemaPointerBuilder.ComponentMessageHeaders(msgName.Span));
                    }
                }
            }
        }

        return [.. pointers];
    }

    /// <summary>
    /// Lists all operations in the AsyncAPI 3.0 specification, optionally filtered.
    /// </summary>
    /// <param name="doc">The parsed AsyncAPI document.</param>
    /// <param name="filter">Optional operation filter (filters by channel address).</param>
    /// <param name="referenceResolver">
    /// Optional external reference resolver for <c>$ref</c> values pointing outside the document.
    /// </param>
    /// <param name="diagnostics">
    /// Optional collection receiving a diagnostic for every entry that was skipped or degraded.
    /// </param>
    /// <returns>An array of <see cref="AsyncApiOperationSummary"/> records.</returns>
    public static AsyncApiOperationSummary[] ListOperations(
        AsyncApiDocument doc,
        OperationFilter? filter = null,
        IAsyncApiReferenceResolver? referenceResolver = null,
        ICollection<AsyncApiGenerationDiagnostic>? diagnostics = null)
    {
        List<AsyncApiOperationSummary> result = [];

        if (doc.OperationsValue.IsUndefined())
        {
            return [];
        }

        foreach (var operationProp in doc.OperationsValue.EnumerateObject())
        {
            if (!TryResolveEntry(operationProp.Value, doc, referenceResolver, out JsonElement resolvedOperation))
            {
                diagnostics?.Add(new(
                    AsyncApiGenerationDiagnosticSeverity.Warning,
                    $"#/operations/{operationProp.Name}",
                    "The operation entry is a $ref that does not resolve; the operation was skipped."));
                continue;
            }

            AsyncApiDocument.Type300Operation operation = resolvedOperation;

            if (operation.IsUndefined())
            {
                continue;
            }

            // Get the action (send/receive)
            if (operation.Action.IsUndefined())
            {
                continue;
            }

            OperationAction action = operation.Action == AsyncApiDocument.Type300Operation.ActionEntity.EnumValues.Send
                ? OperationAction.Send
                : OperationAction.Receive;

            // Resolve channel reference to get address
            string channelAddress = ResolveChannelAddress(operation, doc, referenceResolver, diagnostics);

            if (filter?.Matches(channelAddress) == false)
            {
                continue;
            }

            // In AsyncAPI 3.0, operations are named at the map level — the key IS the operationId
            string operationId = operationProp.Name;

            // Get summary (checking operation traits for fallback)
            string? summary = null;
            if (TryGetPropertyWithTraits(operation, "summary"u8, doc, null, out JsonElement summaryEl) &&
                summaryEl.ValueKind == JsonValueKind.String)
            {
                summary = summaryEl.GetString();
            }

            // Get tags (checking operation traits for fallback)
            List<string> tags = [];
            if (TryGetPropertyWithTraits(operation, "tags"u8, doc, null, out JsonElement tagsEl) &&
                tagsEl.ValueKind == JsonValueKind.Array)
            {
                foreach (JsonElement tag in tagsEl.EnumerateArray())
                {
                    if (tag.TryGetProperty("name"u8, out JsonElement nameEl) &&
                        nameEl.ValueKind == JsonValueKind.String)
                    {
                        tags.Add(nameEl.GetString()!);
                    }
                }
            }

            if (filter?.MatchesTags(tags) == false)
            {
                continue;
            }

            // Count messages (checking operation traits for fallback)
            int messageCount = 0;
            if (TryGetPropertyWithTraits(operation, "messages"u8, doc, null, out JsonElement msgsEl) &&
                msgsEl.ValueKind == JsonValueKind.Array)
            {
                foreach (var msg in msgsEl.EnumerateArray())
                {
                    _ = msg;
                    messageCount++;
                }
            }

            result.Add(new AsyncApiOperationSummary(
                channelAddress,
                action,
                operationId,
                [.. tags],
                summary,
                messageCount,
                Protocol: null));
        }

        return [.. result];
    }

    /// <summary>
    /// Lists all servers defined in the AsyncAPI 3.0 specification.
    /// </summary>
    /// <param name="doc">The parsed AsyncAPI document.</param>
    /// <param name="referenceResolver">
    /// Optional external reference resolver for <c>$ref</c> values pointing outside the document.
    /// </param>
    /// <param name="diagnostics">
    /// Optional collection receiving a diagnostic for every entry that was skipped or degraded.
    /// </param>
    /// <returns>An array of <see cref="ServerInfo"/> records.</returns>
    public static ServerInfo[] ListServers(AsyncApiDocument doc, IAsyncApiReferenceResolver? referenceResolver = null, ICollection<AsyncApiGenerationDiagnostic>? diagnostics = null)
    {
        List<ServerInfo> result = [];

        if (doc.ServersValue.IsUndefined())
        {
            return [];
        }

        foreach (var serverProp in doc.ServersValue.EnumerateObject())
        {
            string name = serverProp.Name;

            if (!TryResolveEntry(serverProp.Value, doc, referenceResolver, out JsonElement resolvedServer))
            {
                diagnostics?.Add(new(
                    AsyncApiGenerationDiagnosticSeverity.Warning,
                    $"#/servers/{name}",
                    "The server entry is a $ref that does not resolve; the server was skipped."));
                continue;
            }

            AsyncApiDocument.Type300Server server = resolvedServer;

            if (server.IsUndefined())
            {
                continue;
            }

            string host = server.Host.IsNotUndefined() ? server.Host.GetString()! : string.Empty;
            string protocol = server.Protocol.IsNotUndefined() ? server.Protocol.GetString()! : string.Empty;
            string? pathname = server.Pathname.IsNotUndefined() ? server.Pathname.GetString() : null;

            List<ServerVariable> variables = [];
            if (server.Variables.IsNotUndefined())
            {
                foreach (var varProp in server.Variables.EnumerateObject())
                {
                    string varName = varProp.Name;

                    if (!TryResolveEntry(varProp.Value, doc, referenceResolver, out JsonElement resolvedVariable))
                    {
                        diagnostics?.Add(new(
                            AsyncApiGenerationDiagnosticSeverity.Warning,
                            $"#/servers/{name}/variables/{varName}",
                            "The server variable is a $ref that does not resolve; the variable was skipped."));
                        continue;
                    }

                    AsyncApiDocument.ServerVariable variable = resolvedVariable;

                    if (variable.IsUndefined())
                    {
                        continue;
                    }

                    string? defaultValue = variable.Default.IsNotUndefined() ? variable.Default.GetString() : null;
                    string? description = variable.Description.IsNotUndefined() ? variable.Description.GetString() : null;

                    List<string> enumValues = [];
                    if (variable.Enum.IsNotUndefined())
                    {
                        foreach (var enumValue in variable.Enum.EnumerateArray())
                        {
                            enumValues.Add((string)enumValue);
                        }
                    }

                    variables.Add(new ServerVariable(varName, defaultValue, enumValues, description));
                }
            }

            List<SecuritySchemeInfo> securitySchemes = [];
            if (server.Security.IsNotUndefined())
            {
                foreach (var secItem in server.Security.EnumerateArray())
                {
                    string? schemeName = secItem.Match<string?>(
                        matchReference: static (in AsyncApiDocument.Reference asRef) =>
                        {
                            string refStr = asRef.Ref.GetString()!;
                            const string prefix = "#/components/securitySchemes/";
                            if (refStr.StartsWith(prefix, StringComparison.Ordinal))
                            {
                                return refStr[prefix.Length..];
                            }

                            return null;
                        },
                        matchSecurityScheme: static (in AsyncApiDocument.SecurityScheme _) => (string?)null,
                        defaultMatch: static (in AsyncApiDocument.SecurityRequirements.ItemsEntity _) => (string?)null);

                    if (schemeName is not null)
                    {
                        string schemeType = ResolveSecuritySchemeType(doc, schemeName, referenceResolver, diagnostics);
                        securitySchemes.Add(new SecuritySchemeInfo(schemeName, schemeType));
                    }
                }
            }

            result.Add(new ServerInfo(name, host, protocol, pathname, variables, securitySchemes, server.Bindings.IsNotUndefined() ? server.Bindings.ToString() : null));
        }

        return [.. result];
    }

    /// <summary>
    /// Extracts typed protocol bindings from channel and operation elements in the spec.
    /// </summary>
    /// <param name="doc">The parsed AsyncAPI document.</param>
    /// <param name="channelName">The channel key to extract bindings from.</param>
    /// <param name="resolver">
    /// Optional external reference resolver for <c>$ref</c> values pointing outside the document.
    /// </param>
    /// <param name="diagnostics">
    /// Optional collection receiving a diagnostic for every entry that was skipped or degraded.
    /// </param>
    /// <returns>A <see cref="ChannelBindingInfo"/> containing the resolved bindings.</returns>
    public static ChannelBindingInfo GetBindings(
        AsyncApiDocument doc,
        string channelName,
        string? messageName = null,
        IAsyncApiReferenceResolver? resolver = null,
        ICollection<AsyncApiGenerationDiagnostic>? diagnostics = null)
    {
        AsyncApiDocument.ChannelBindingsObject channelBindings = default;
        AsyncApiDocument.OperationBindingsObject operationBindings = default;
        AsyncApiDocument.MessageBindingsObject messageBindings = default;

        // Channel-level bindings
        if (doc.ChannelsValue.IsNotUndefined() &&
            doc.ChannelsValue.TryGetProperty(channelName, out var channelEntity))
        {
            AsyncApiDocument.Channel channel = default;
            if (TryResolveEntry(channelEntity, doc, resolver, out JsonElement resolvedChannel))
            {
                channel = resolvedChannel;
            }
            else
            {
                diagnostics?.Add(new(
                    AsyncApiGenerationDiagnosticSeverity.Warning,
                    $"#/channels/{channelName}",
                    "The channel entry is a $ref that does not resolve; its bindings were skipped."));
            }

            if (channel.IsNotUndefined() && channel.Bindings.IsNotUndefined())
            {
                var ctx = (doc, channelName, resolver);
                channelBindings = channel.Bindings.Match(
                    in ctx,
                    matchReference: static (in AsyncApiDocument.Reference r, in (AsyncApiDocument doc, string channelName, IAsyncApiReferenceResolver? resolver) c) =>
                    {
                        JsonElement resolved = ResolveRef(r, c.doc, c.resolver);
                        return AsyncApiDocument.ChannelBindingsObject.From(resolved);
                    },
                    matchChannelBindingsObject: static (in AsyncApiDocument.ChannelBindingsObject b, in (AsyncApiDocument, string, IAsyncApiReferenceResolver?) _) => b,
                    defaultMatch: static (in AsyncApiDocument.Channel.BindingsEntity _, in (AsyncApiDocument, string channelName, IAsyncApiReferenceResolver?) c) =>
                    {
                        ThrowHelper.ThrowUnsupportedBindingsFormat(c.channelName);
                        return default;
                    });
            }
        }

        // Operation-level bindings (first operation referencing this channel)
        if (doc.OperationsValue.IsNotUndefined())
        {
            string channelRef = $"#/channels/{channelName}";
            foreach (var opProp in doc.OperationsValue.EnumerateObject())
            {
                if (!TryResolveEntry(opProp.Value, doc, resolver, out JsonElement resolvedOperation))
                {
                    diagnostics?.Add(new(
                        AsyncApiGenerationDiagnosticSeverity.Warning,
                        $"#/operations/{opProp.Name}",
                        "The operation entry is a $ref that does not resolve; its bindings were skipped."));
                    continue;
                }

                AsyncApiDocument.Type300Operation operation = resolvedOperation;

                if (operation.IsUndefined())
                {
                    continue;
                }

                AsyncApiDocument.Reference chAsRef = operation.Channel;
                if (chAsRef.Ref.IsNotUndefined() &&
                    chAsRef.Ref.ValueEquals(channelRef))
                {
                    if (operation.Bindings.IsNotUndefined())
                    {
                        var ctx = (doc, channelName, resolver);
                        operationBindings = operation.Bindings.Match(
                            in ctx,
                            matchReference: static (in AsyncApiDocument.Reference r, in (AsyncApiDocument doc, string channelName, IAsyncApiReferenceResolver? resolver) c) =>
                            {
                                JsonElement resolved = ResolveRef(r, c.doc, c.resolver);
                                return AsyncApiDocument.OperationBindingsObject.From(resolved);
                            },
                            matchOperationBindingsObject: static (in AsyncApiDocument.OperationBindingsObject b, in (AsyncApiDocument, string, IAsyncApiReferenceResolver?) _) => b,
                            defaultMatch: static (in AsyncApiDocument.Type300Operation.BindingsEntity _, in (AsyncApiDocument, string channelName, IAsyncApiReferenceResolver?) c) =>
                            {
                                ThrowHelper.ThrowUnsupportedBindingsFormat(c.channelName);
                                return default;
                            });

                        break;
                    }
                }
            }
        }

        // Message-level bindings (from the named message, if specified)
        if (messageName is not null &&
            doc.ChannelsValue.IsNotUndefined() &&
            doc.ChannelsValue.TryGetProperty(channelName, out var chEntityForMsg))
        {
            AsyncApiDocument.Channel channelForMsg = default;
            if (TryResolveEntry(chEntityForMsg, doc, resolver, out JsonElement resolvedChannelForMsg))
            {
                channelForMsg = resolvedChannelForMsg;
            }

            if (channelForMsg.IsNotUndefined() && channelForMsg.Messages.IsNotUndefined())
            {
                if (channelForMsg.Messages.TryGetProperty(messageName, out var msgEntity))
                {
                    AsyncApiDocument.MessageObject msg = default;
                    if (TryResolveEntry(msgEntity, doc, resolver, out JsonElement resolvedMsg))
                    {
                        msg = resolvedMsg;
                    }
                    else
                    {
                        diagnostics?.Add(new(
                            AsyncApiGenerationDiagnosticSeverity.Warning,
                            $"#/channels/{channelName}/messages/{messageName}",
                            "The message entry is a $ref that does not resolve; its bindings were skipped."));
                    }

                    if (msg.IsNotUndefined() && msg.Bindings.IsNotUndefined())
                    {
                        messageBindings = AsyncApiDocument.MessageBindingsObject.From(ResolveRef(msg.Bindings, doc, resolver));
                    }
                }
            }
        }

        return new ChannelBindingInfo
        {
            ChannelBindings = channelBindings,
            OperationBindings = operationBindings,
            MessageBindings = messageBindings,
        };
    }

    /// <summary>
    /// Walks the AsyncAPI 3.0 specification and emits C# source files for
    /// producers, consumers, and message wrapper types.
    /// </summary>
    /// <param name="doc">The parsed AsyncAPI document.</param>
    /// <param name="filter">Optional operation filter (filters by channel address).</param>
    /// <param name="referenceResolver">
    /// Optional external reference resolver. When provided, <c>$ref</c> values that point
    /// outside the entry document are resolved through this resolver. When <see langword="null"/>,
    /// only local fragment-only references are supported.
    /// </param>
    /// <returns>The generated source files.</returns>
    public IReadOnlyList<GeneratedFile> Generate(
        AsyncApiDocument doc,
        OperationFilter? filter = null,
        IAsyncApiReferenceResolver? referenceResolver = null)
    {
        this.diagnostics.Clear();

        List<GeneratedFile> files = [];

        if (doc.OperationsValue.IsUndefined())
        {
            return files;
        }

        (List<OperationInfo> sendOps, List<OperationInfo> receiveOps) = this.CollectOperations(doc, filter, referenceResolver);

        files.AddRange(this.GenerateOperations(sendOps, receiveOps, ListServers(doc, referenceResolver, this.diagnostics)));

        return files;
    }

    /// <summary>
    /// Collects the document's send/receive operations (channel address, messages with resolved payload
    /// type names, parameters, reply, bindings) — the shared walk behind <see cref="Generate"/> and
    /// <see cref="DescribeChannelOperations"/>.
    /// </summary>
    internal (List<OperationInfo> Send, List<OperationInfo> Receive) CollectOperations(
        AsyncApiDocument doc,
        OperationFilter? filter = null,
        IAsyncApiReferenceResolver? referenceResolver = null)
    {
        List<OperationInfo> sendOps = [];
        List<OperationInfo> receiveOps = [];

        if (doc.OperationsValue.IsUndefined())
        {
            return (sendOps, receiveOps);
        }

        foreach (var operationProp in doc.OperationsValue.EnumerateObject())
        {
            if (!TryResolveEntry(operationProp.Value, doc, referenceResolver, out JsonElement resolvedOperation))
            {
                this.diagnostics.Add(new(
                    AsyncApiGenerationDiagnosticSeverity.Warning,
                    $"#/operations/{operationProp.Name}",
                    "The operation entry is a $ref that does not resolve; the operation was skipped."));
                continue;
            }

            AsyncApiDocument.Type300Operation operation = resolvedOperation;

            if (operation.IsUndefined())
            {
                continue;
            }

            if (operation.Action.IsUndefined())
            {
                continue;
            }

            OperationAction action = operation.Action == AsyncApiDocument.Type300Operation.ActionEntity.EnumValues.Send
                ? OperationAction.Send
                : OperationAction.Receive;

            (string channelAddress, bool isDynamicAddress) = ResolveChannelAddressInfo(operation, doc, referenceResolver, this.diagnostics);

            if (filter?.Matches(channelAddress) == false)
            {
                continue;
            }

            string operationName = operationProp.Name;
            List<MessageInfo> messages = CollectOperationMessages(operation, doc, referenceResolver);
            List<ChannelParameter> parameters = CollectChannelParameters(operation, doc, referenceResolver, this.diagnostics);
            ReplyInfo? reply = CollectReplyInfo(operation, doc, referenceResolver);

            // Extract channel name and allowed servers
            string? channelName = ExtractChannelName(operation, doc);
            IReadOnlyList<string>? allowedServers = channelName is not null
                ? GetChannelAllowedServers(doc, channelName, referenceResolver, this.diagnostics)
                : null;

            // Collect security schemes from the servers this operation is allowed to use
            IReadOnlyList<SecuritySchemeInfo> operationSecuritySchemes = CollectOperationSecuritySchemes(doc, allowedServers);

            // Extract channel/operation bindings as raw JSON for the generated types
            string? channelBindingsJson = null;
            string? operationBindingsJson = null;
            if (channelName is not null)
            {
                ChannelBindingInfo bindings = GetBindings(doc, channelName, resolver: referenceResolver);
                if (bindings.ChannelBindings.IsNotUndefined())
                {
                    channelBindingsJson = bindings.ChannelBindings.ToString();
                }

                if (bindings.OperationBindings.IsNotUndefined())
                {
                    operationBindingsJson = bindings.OperationBindings.ToString();
                }
            }

            OperationInfo info = new(
                operationName,
                action,
                channelAddress,
                isDynamicAddress,
                messages,
                parameters,
                reply,
                channelName,
                allowedServers,
                channelBindingsJson,
                operationBindingsJson,
                operationSecuritySchemes);

            if (action == OperationAction.Send)
            {
                sendOps.Add(info);
            }
            else
            {
                receiveOps.Add(info);
            }
        }

        return (sendOps, receiveOps);
    }

    /// <summary>
    /// Describes the document's channel operations with the generated producer/consumer details an
    /// Arazzo channel step needs to call: the channel address, the operation action, the producer class
    /// (for send operations), and per-message the resolved payload type name and producer publish method.
    /// </summary>
    /// <param name="doc">The AsyncAPI document.</param>
    /// <param name="filter">An optional channel filter.</param>
    /// <param name="referenceResolver">An optional reference resolver for cross-document <c>$ref</c>s.</param>
    /// <returns>One descriptor per channel operation.</returns>
    public IReadOnlyList<AsyncApiChannelDescriptor> DescribeChannelOperations(
        AsyncApiDocument doc,
        OperationFilter? filter = null,
        IAsyncApiReferenceResolver? referenceResolver = null)
    {
        (List<OperationInfo> sendOps, List<OperationInfo> receiveOps) = CollectOperations(doc, filter, referenceResolver);
        return this.BuildChannelDescriptors(sendOps, receiveOps);
    }

    /// <summary>
    /// Maps collected <see cref="OperationInfo"/> records to <see cref="AsyncApiChannelDescriptor"/>s —
    /// the version-independent half of <see cref="DescribeChannelOperations"/>, shared with the AsyncAPI
    /// 2.6 generator (which collects its own operations from the older channel/publish/subscribe shape but
    /// emits and describes them through this generator).
    /// </summary>
    /// <param name="sendOps">The send operations.</param>
    /// <param name="receiveOps">The receive operations.</param>
    /// <returns>One descriptor per operation.</returns>
    internal IReadOnlyList<AsyncApiChannelDescriptor> BuildChannelDescriptors(
        IReadOnlyList<OperationInfo> sendOps,
        IReadOnlyList<OperationInfo> receiveOps)
    {
        var descriptors = new List<AsyncApiChannelDescriptor>(sendOps.Count + receiveOps.Count);
        foreach (OperationInfo op in sendOps.Concat(receiveOps))
        {
            bool isSend = op.Action == OperationAction.Send;
            string? producerClassName = isSend ? $"{this.rootNamespace}.{ToPascalCase(op.Name)}Producer" : null;

            // An operation that declares a reply is request/reply. On the send side the producer exposes a
            // SendAndReceive{Message}Async method; on the receive side the descriptor still carries the reply
            // payload type so a responder (consumer / Arazzo responder step) knows what reply to produce.
            bool hasReply = op.Reply is not null;
            bool isSendRequestReply = isSend && hasReply;
            string? replyPayloadTypeName = hasReply
                ? (op.Reply!.Value.Messages.Count == 1 ? op.Reply.Value.Messages[0].PayloadTypeName : null) ?? "Corvus.Text.Json.JsonElement"
                : null;

            var messages = new List<AsyncApiChannelMessageDescriptor>(op.Messages.Count);
            foreach (MessageInfo message in op.Messages)
            {
                messages.Add(new AsyncApiChannelMessageDescriptor(
                    message.Name,
                    message.PayloadTypeName,
                    message.HeadersTypeName,
                    message.ContentType,
                    isSend ? $"Publish{ToPascalCase(message.Name)}Async" : null,
                    isSendRequestReply ? $"SendAndReceive{ToPascalCase(message.Name)}Async" : null,
                    message.CorrelationIdName,
                    message.CorrelationIdLocation));
            }

            descriptors.Add(new AsyncApiChannelDescriptor(
                op.ChannelAddress,
                op.Action,
                op.Name,
                producerClassName,
                op.IsDynamicAddress,
                op.Parameters.Select(static p => p.Name).ToList(),
                messages,
                replyPayloadTypeName));
        }

        return descriptors;
    }

    internal IReadOnlyList<GeneratedFile> GenerateOperations(
        IReadOnlyList<OperationInfo> sendOps,
        IReadOnlyList<OperationInfo> receiveOps,
        ServerInfo[] servers)
    {
        List<GeneratedFile> files = [];

        // Emit producer types for send operations
        foreach (OperationInfo op in sendOps)
        {
            files.Add(EmitProducer(op));
        }

        // An operation legitimately named *WithDeliveryContext collides with another operation's
        // delivery-context variant names; a collision skips the variant with a diagnostic instead
        // of silently clobbering generated files.
        HashSet<string> receiveOpPascalNames = new(StringComparer.Ordinal);
        foreach (OperationInfo op in receiveOps)
        {
            receiveOpPascalNames.Add(ToPascalCase(op.Name));
        }

        // Emit consumer handler interfaces and consumer classes for receive operations
        foreach (OperationInfo op in receiveOps)
        {
            files.Add(EmitConsumerHandler(op, withDeliveryContext: false));
            files.Add(EmitConsumer(op, withDeliveryContext: false));

            // Responders get delivery-context variants too: IMessageDeliveryContextTransport
            // exposes SubscribeReplyWithDeliveryContextAsync, so a responder's handler can now
            // receive MessageDeliveryContext exactly as a plain consumer's can.
            {
                string variantBaseName = ToPascalCase(op.Name) + "WithDeliveryContext";
                if (receiveOpPascalNames.Contains(variantBaseName))
                {
                    this.diagnostics.Add(new(
                        AsyncApiGenerationDiagnosticSeverity.Warning,
                        $"#/operations/{op.Name}",
                        $"The delivery-context variants were skipped: their generated names would collide with the operation named '{variantBaseName}'."));
                }
                else
                {
                    files.Add(EmitConsumerHandler(op, withDeliveryContext: true));
                    files.Add(EmitConsumer(op, withDeliveryContext: true));
                }
            }

            // Multi-message operations need a discriminated received message type
            if (op.Messages.Count > 1)
            {
                files.Add(EmitReceivedMessage(op));
            }
        }

        // Emit message wrapper types for all operations
        foreach (OperationInfo op in sendOps.Concat(receiveOps))
        {
            foreach (MessageInfo msg in op.Messages)
            {
                if (msg.PayloadTypeName is not null)
                {
                    files.Add(EmitMessageWrapper(op, msg));
                }
            }
        }

        // Emit server URL builder if servers have variables
        if (servers.Any(s => s.Variables.Count > 0))
        {
            files.Add(EmitServerUrlBuilder(servers));
        }

        return files;
    }

