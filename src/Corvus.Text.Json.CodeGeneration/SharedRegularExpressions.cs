using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using Corvus.Json.CodeGeneration;
using EcmaRegexEdition = Corvus.Ecma262.RegularExpressions.CodeGeneration.RegexEdition;
using EcmaRegexEmitter = Corvus.Ecma262.RegularExpressions.CodeGeneration.RegexEmitter;
using EcmaRegexFlags = Corvus.Ecma262.RegularExpressions.CodeGeneration.RegexFlags;
using EcmaRegexUnicodeVersion = Corvus.Ecma262.RegularExpressions.CodeGeneration.RegexUnicodeVersion;

namespace Corvus.Text.Json.CodeGeneration;

/// <summary>
/// The Corvus.Regex.Ecma262 regular expressions of one generation, each written once: the generated types' fields and
/// the program's table refer to a property of one class (<see cref="ClassName"/>), whose holder the library's emitter
/// writes, with the compiled regular expression as data. A pattern every type of a specification carries (the name of
/// its extensions, say) is then one holder, not one for each type.
/// </summary>
internal sealed class SharedRegularExpressions
{
    /// <summary>The name of the class that holds the regular expressions.</summary>
    internal const string ClassName = "CorvusJsonSchemaRegularExpressions";

    private readonly Dictionary<(string Pattern, bool Unicode, GeneratedRegexEdition Edition, GeneratedRegexUnicodeVersion UnicodeVersion), string> names = [];
    private readonly List<(string Name, string Pattern, bool Unicode, GeneratedRegexEdition Edition, GeneratedRegexUnicodeVersion UnicodeVersion)> entries = [];
    private readonly object sync = new();
    private readonly string classReference;

    /// <summary>Initializes a new instance of the <see cref="SharedRegularExpressions"/> class.</summary>
    /// <param name="defaultNamespace">The namespace the class is written in (the program's).</param>
    public SharedRegularExpressions(string defaultNamespace)
    {
        this.Namespace = defaultNamespace;
        this.classReference = defaultNamespace.Length == 0 ? "global::" + ClassName : "global::" + defaultNamespace + "." + ClassName;
    }

    /// <summary>Gets the namespace the class is written in.</summary>
    public string Namespace { get; }

    /// <summary>
    /// Gets the reference to the regular expression for a pattern read with the flags, edition and version of Unicode
    /// given, adding it when it is not there yet.
    /// </summary>
    /// <param name="pattern">The pattern.</param>
    /// <param name="unicode">Whether it is read with the u flag (otherwise with none).</param>
    /// <param name="edition">The edition of the grammar.</param>
    /// <param name="unicodeVersion">The version of Unicode.</param>
    /// <returns>The fully qualified reference to its property, a <c>Corvus.Ecma262.RegularExpressions.Regex</c>.</returns>
    public string Reference(string pattern, bool unicode, GeneratedRegexEdition edition, GeneratedRegexUnicodeVersion unicodeVersion)
    {
        lock (this.sync)
        {
            if (!this.names.TryGetValue((pattern, unicode, edition, unicodeVersion), out string? name))
            {
                name = "Regex" + this.entries.Count.ToString(CultureInfo.InvariantCulture);
                this.names.Add((pattern, unicode, edition, unicodeVersion), name);
                this.entries.Add((name, pattern, unicode, edition, unicodeVersion));
            }

            return this.classReference + "." + name;
        }
    }

    /// <summary>Writes the class, or nothing when no regular expression was asked for.</summary>
    /// <param name="fileExtension">The extension of generated files.</param>
    /// <param name="lineEnd">The line ending.</param>
    /// <returns>The file, or <see langword="null"/>.</returns>
    public GeneratedCodeFile? Generate(string fileExtension, string lineEnd)
    {
        lock (this.sync)
        {
            if (this.entries.Count == 0)
            {
                return null;
            }

            var sb = new StringBuilder();
            void Line(string text) => sb.Append(text).Append(lineEnd);

            Line("// <auto-generated/>");
            Line(string.Empty);
            Line("#nullable enable");
            Line(string.Empty);
            if (this.Namespace.Length > 0)
            {
                Line($"namespace {this.Namespace};");
                Line(string.Empty);
            }

            Line("/// <summary>");
            Line("/// The regular expressions of the generated code: Corvus.Regex.Ecma262's compiled matchers, each with its compiled");
            Line("/// regular expression as data, built when it is first used.");
            Line("/// </summary>");
            Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Corvus.Text.Json.CodeGeneration\", \"{typeof(SharedRegularExpressions).Assembly.GetName().Version}\")]");
            Line($"internal static class {ClassName}");
            Line("{");
            bool first = true;
            foreach ((string name, string pattern, bool unicode, GeneratedRegexEdition edition, GeneratedRegexUnicodeVersion unicodeVersion) in this.entries)
            {
                if (!first)
                {
                    Line(string.Empty);
                }

                first = false;
                string holder = name + "Holder";
                if (!EcmaRegexEmitter.TryEmit(
                    pattern,
                    unicode ? EcmaRegexFlags.Unicode : EcmaRegexFlags.None,
                    CodeGenerationExtensions.RegexMatchTimeoutMilliseconds,
                    (EcmaRegexEdition)(int)edition,
                    (EcmaRegexUnicodeVersion)(int)unicodeVersion,
                    holder,
                    out string? source,
                    out string? error))
                {
                    throw new InvalidOperationException($"The pattern '{pattern}' could not be written. {error}");
                }

                Line("    /// <summary>");
                Line($"    /// Gets the regular expression {EcmaRegexEmitter.Summary(pattern, unicode ? "u" : string.Empty)}.");
                Line("    /// </summary>");
                Line($"    internal static global::Corvus.Ecma262.RegularExpressions.Regex {name} => {holder}.Instance;");
                Line(string.Empty);

                // The matcher is straight-line code with labels and locals for every way through the pattern, some of
                // which a given pattern does not take; the compiler's warnings about them are not the generated code's.
                Line("#pragma warning disable");
                foreach (string text in source!.Split('\n'))
                {
                    string trimmed = text.TrimEnd('\r');
                    Line(trimmed.Length == 0 ? string.Empty : "    " + trimmed);
                }

                Line("#pragma warning restore");
            }

            Line("}");
            return new GeneratedCodeFile(ClassName + fileExtension, sb.ToString());
        }
    }
}