namespace Corvus.Text.Json.OpenApi20;

/// <summary>
/// A self-contained code generator that walks the strongly-typed
/// <see cref="OpenApiDocument"/> model directly and emits C# source files.
/// </summary>
/// <remarks>
/// <para>
/// This replaces the multi-stage pipeline (Walker → Walked* → ClientModelBuilder →
/// Client* → ClientCodeEmitter) with a single class that:
/// <list type="number">
/// <item><description>Walks the typed model to collect operation data into lightweight internal records.</description></item>
/// <item><description>Emits C# source files from those records.</description></item>
/// </list>
/// </para>
/// <para>
/// All shared text utilities, scalar emission, and pointer construction are delegated
/// to <see cref="CodeEmitHelpers"/> and <see cref="SchemaPointerBuilder"/>.
/// </para>
/// </remarks>
public sealed class OpenApi20CodeGenerator
{
    private readonly string rootNamespace;
    private readonly string? clientNamePrefix;
    private readonly bool ignoreEmptyFormUrlEncodedBody;
    private readonly IReadOnlySet<string> contextSourceBodyPointers;
    private readonly IReadOnlyDictionary<string, string> schemaTypeMap;

    /// <summary>
    /// Initializes a new instance of the <see cref="OpenApi20CodeGenerator"/> class.
    /// </summary>
    /// <param name="rootNamespace">The root namespace for generated code.</param>
    /// <param name="schemaTypeMap">
    /// A map from JSON pointer strings to fully qualified .NET type names
    /// generated by the V5 code generator. Every schema pointer discovered
    /// during the walk must have a corresponding entry.
    /// </param>
    /// <param name="clientNamePrefix">
    /// Optional prefix for client type names. If <see langword="null"/>,
    /// <c>"Api"</c> is used.
    /// </param>
    /// <param name="ignoreEmptyFormUrlEncodedBody">
    /// When <see langword="true"/>, form-urlencoded request bodies whose schema defines
    /// no properties are treated as if the body were absent.
    /// </param>
    public OpenApi20CodeGenerator(
        string rootNamespace,
        IReadOnlyDictionary<string, string> schemaTypeMap,
        string? clientNamePrefix = null,
        bool ignoreEmptyFormUrlEncodedBody = false,
        IReadOnlySet<string>? contextSourceBodyPointers = null)
    {
        this.rootNamespace = rootNamespace;
        this.schemaTypeMap = schemaTypeMap;
        this.clientNamePrefix = clientNamePrefix;
        this.ignoreEmptyFormUrlEncodedBody = ignoreEmptyFormUrlEncodedBody;
        this.contextSourceBodyPointers = contextSourceBodyPointers ?? new HashSet<string>(StringComparer.Ordinal);
    }

    // ── Walk-phase reference (typed model objects, no strings extracted) ──
    // PathProp is JsonProperty<JsonElement> because PathsValue.EnumerateObject()
    // yields untyped properties in the 3.0 generated model.
    // In 3.0, HTTP methods on PathItem are pattern properties (not named props)
    // so we discover them via TryGetProperty with UTF-8 method names.
    private readonly record struct OperationRef(
        JsonProperty<JsonElement> PathProp,
        OpenApiDocument.Operation Operation,
        OperationMethod Method,
        OpenApiDocument.PathItem PathItem);

    private static readonly (ReadOnlyMemory<byte> Name, OperationMethod Method)[] HttpMethods =
    [
        ("get"u8.ToArray(), OperationMethod.Get),
        ("put"u8.ToArray(), OperationMethod.Put),
        ("post"u8.ToArray(), OperationMethod.Post),
        ("delete"u8.ToArray(), OperationMethod.Delete),
        ("options"u8.ToArray(), OperationMethod.Options),
        ("head"u8.ToArray(), OperationMethod.Head),
        ("patch"u8.ToArray(), OperationMethod.Patch),
    ];

    // ── Emit-boundary record types (strings for C# code generation) ─────
    private readonly record struct OperationInfo(
        string PathTemplate,
        OperationMethod Method,
        string MethodName,
        string? OperationId,
        string? Summary,
        string? Description,
        bool IsDeprecated,
        string[] Tags,
        ParameterInfo[] Parameters,
        RequestBodyInfo? RequestBody,
        ResponseInfo[] Responses,
        ServerInfo? EffectiveServer,
        OperationSecurityRequirementSet[]? SecurityRequirements = null);

    // One element of an OpenAPI `security` array (a "Security Requirement Object"): an alternative
    // that, on its own, satisfies the operation's security. The schemes within it are AND'd; the
    // alternatives across the array are OR'd. An empty object ({}) marks anonymous access as an
    // accepted alternative.
    private readonly record struct OperationSecurityRequirementSet(
        OperationSecurityRequirement[] Requirements,
        bool IsOptional);

    private readonly record struct OperationSecurityRequirement(
        string SchemeName,
        string[] Scopes,
        string? SchemeType = null);

    private readonly record struct ServerInfo(
        string UrlTemplate,
        ServerVariableInfo[] Variables);

    private readonly record struct ServerVariableInfo(
        string Name,
        string DefaultValue,
        string[]? AllowedValues);

    private readonly record struct ParameterInfo(
        string Name,
        ParameterLocation Location,
        bool IsRequired,
        ParameterStyle Style,
        bool Explode,
        ParameterSerializationKind SerializationKind,
        ParameterSerializationKind ElementSerializationKind,
        string? SchemaPointer,
        bool HasDeepNesting,
        string? DefaultValueJson,
        JsonValueKind DefaultValueKind,
        bool DegradedCollectionFormat = false);

    private readonly record struct RequestBodyInfo(
        string? Description,
        bool IsRequired,
        ContentInfo[] Content,
        BinaryPropertyInfo[] BinaryProperties);

    private readonly record struct BinaryPropertyInfo(
        string PropertyName,
        string ParameterName,
        string? ContentType);

    private readonly record struct ResponseInfo(
        string StatusCode,
        ContentInfo[] Content,
        HeaderInfo[] Headers,
        LinkInfo[] Links);

    private readonly record struct ContentInfo(
        string MediaType,
        string? SchemaPointer,
        IReadOnlyDictionary<string, EncodingInfo>? Encodings);

    private readonly record struct EncodingInfo(
        string? Style,
        bool? Explode,
        bool AllowReserved,
        string? ContentType);

    private readonly record struct HeaderInfo(
        string HeaderName,
        string? SchemaPointer,
        bool Explode,
        ParameterSerializationKind SerializationKind,
        ParameterSerializationKind ElementSerializationKind,
        bool HasDeepNesting);

    private readonly record struct LinkInfo(
        string LinkName,
        string? TargetOperationId,
        LinkParameterBinding[] ParameterBindings,
        string? RequestBodyExpression,
        string? Description,
        string SourceStatusCode);

    private readonly record struct LinkParameterBinding(
        string ParameterName,
        string Expression);

    /// <summary>
    /// Walks the OpenAPI 3.0 specification and collects all schema
    /// JSON Pointer strings reachable from the selected operations.
    /// </summary>
    /// <param name="specRoot">The root element of the parsed spec document.</param>
    /// <param name="filter">Optional operation filter.</param>
    /// <param name="referenceResolver">
    /// Optional reference resolver. If <see langword="null"/>,
    /// a <see cref="LocalReferenceResolver"/> is used.
    /// </param>
    /// <returns>An array of <see cref="SchemaReference"/> values.</returns>
    public static SchemaReference[] CollectSchemaPointers(
        JsonElement specRoot,
        out Dictionary<string, string> parameterNames,
        OperationFilter? filter = null,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        return CollectSchemaPointers(specRoot, out parameterNames, out _, filter, referenceResolver);
    }

    /// <summary>
    /// Collects schema pointers, additionally returning the synthesized documents that
    /// hold the aggregated formData body schemas. Each entry maps a synthetic document
    /// URI to its UTF-8 JSON text; the caller must register these documents with the
    /// schema type builder's resolver so the form-body <see cref="SchemaReference"/>s
    /// resolve. The <c>.invalid</c> TLD guarantees an unregistered document fails fast
    /// rather than triggering a network fetch.
    /// </summary>
    /// <param name="specRoot">The root element of the parsed spec document.</param>
    /// <param name="parameterNames">Receives the parameter-name map for the naming heuristic.</param>
    /// <param name="syntheticDocuments">Receives the synthesized form-body documents (URI → JSON).</param>
    /// <param name="filter">Optional operation filter.</param>
    /// <param name="referenceResolver">
    /// Optional reference resolver. If <see langword="null"/>,
    /// a <see cref="LocalReferenceResolver"/> is used.
    /// </param>
    /// <returns>An array of <see cref="SchemaReference"/> values.</returns>
    public static SchemaReference[] CollectSchemaPointers(
        JsonElement specRoot,
        out Dictionary<string, string> parameterNames,
        out IReadOnlyDictionary<string, string> syntheticDocuments,
        OperationFilter? filter = null,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        referenceResolver ??= new LocalReferenceResolver(specRoot);
        OpenApiDocument doc = specRoot;

        if (doc.PathsValue.IsUndefined())
        {
            parameterNames = new Dictionary<string, string>();
            syntheticDocuments = new Dictionary<string, string>();
            return [];
        }

        List<SchemaReference> pointers = [];
        Dictionary<string, string> paramNames = new(StringComparer.Ordinal);
        Dictionary<string, string> formBodies = new(StringComparer.Ordinal);

        foreach (JsonProperty<JsonElement> pathProp in doc.PathsValue.EnumerateObject())
        {
            if (filter is not null)
            {
                using UnescapedUtf16JsonString name = pathProp.Utf16NameSpan;
                if (!filter.Matches(name.Span))
                {
                    continue;
                }
            }

            CollectPathItemPointers(pathProp, pointers, paramNames, formBodies, referenceResolver, "paths"u8);
        }

        Dictionary<string, string> synthetic = new(StringComparer.Ordinal);
        if (formBodies.Count > 0)
        {
            StringBuilder sb = new("{\"schemas\":{");
            bool first = true;
            foreach ((string name, string schemaJson) in formBodies)
            {
                if (!first)
                {
                    sb.Append(',');
                }

                sb.Append('"').Append(name).Append("\":").Append(schemaJson);
                first = false;
            }

            sb.Append("}}");
            synthetic[FormBodyDocumentUri] = sb.ToString();
        }

        parameterNames = paramNames;
        syntheticDocuments = synthetic;
        return [.. pointers];
    }

    /// <summary>
    /// The synthetic document URI under which aggregated formData body schemas are
    /// registered. The <c>.invalid</c> TLD is reserved (RFC 2606), so an accidental
    /// resolution attempt outside the prepopulated resolver fails fast.
    /// </summary>
    public const string FormBodyDocumentUri = "https://corvus-openapi20.invalid/form-bodies.json";

    /// <summary>
    /// Lists all operations in the OpenAPI 3.0 specification, optionally filtered.
    /// </summary>
    /// <param name="specRoot">The root element of the parsed spec document.</param>
    /// <param name="filter">Optional operation filter.</param>
    /// <returns>An array of <see cref="OperationSummary"/> records.</returns>
    public static OperationSummary[] ListOperations(
        JsonElement specRoot,
        OperationFilter? filter = null)
    {
        List<OperationSummary> result = [];

        foreach (OperationRef opRef in WalkOperationRefs(specRoot, filter))
        {
            using UnescapedUtf16JsonString pathName = opRef.PathProp.Utf16NameSpan;
            string path = pathName.Span.ToString();

            string? operationId = opRef.Operation.OperationId.IsNotUndefined()
                ? opRef.Operation.OperationId.GetString()
                : null;

            string? summary = opRef.Operation.Summary.IsNotUndefined()
                ? opRef.Operation.Summary.GetString()
                : null;

            bool isDeprecated = opRef.Operation.Deprecated.ValueKind == JsonValueKind.True;

            List<string> tags = [];
            if (opRef.Operation.Tags.IsNotUndefined())
            {
                foreach (var tag in opRef.Operation.Tags.EnumerateArray())
                {
                    if (tag.ValueKind == JsonValueKind.String)
                    {
                        tags.Add(tag.GetString()!);
                    }
                }
            }

            int paramCount = 0;
            if (opRef.Operation.Parameters.IsNotUndefined())
            {
                foreach (var param in opRef.Operation.Parameters.EnumerateArray())
                {
                    _ = param;
                    paramCount++;
                }
            }

            // Also count path-level parameters
            if (opRef.PathItem.Parameters.IsNotUndefined())
            {
                foreach (var param in opRef.PathItem.Parameters.EnumerateArray())
                {
                    _ = param;
                    paramCount++;
                }
            }

            bool hasBody = OperationHasBodyOrFormData(opRef.Operation, opRef.PathItem);

            string methodName = GetMethodName(operationId, opRef.Method, path);

            result.Add(new OperationSummary(
                path,
                opRef.Method,
                operationId,
                [.. tags],
                isDeprecated,
                paramCount,
                hasBody,
                summary,
                methodName,
                GeneratedClientTypeNaming.RequestTypeName(methodName),
                GeneratedClientTypeNaming.ResponseTypeName(methodName)));
        }

        return [.. result];
    }

    /// <summary>
    /// Lists all tags defined in the top-level <c>tags</c> array of an OpenAPI 3.0 specification.
    /// </summary>
    /// <remarks>
    /// The <c>parent</c> and <c>kind</c> fields are new in OpenAPI 3.2, but this method will
    /// still read them if present (e.g. from extension usage in 3.0 specs).
    /// </remarks>
    /// <param name="specRoot">The root element of the parsed spec document.</param>
    /// <returns>An array of <see cref="TagInfo"/> records.</returns>
    public static TagInfo[] ListTags(JsonElement specRoot)
    {
        if (!specRoot.TryGetProperty("tags"u8, out JsonElement tagsElement)
            || tagsElement.ValueKind != JsonValueKind.Array)
        {
            return [];
        }

        List<TagInfo> result = [];
        foreach (JsonElement tag in tagsElement.EnumerateArray())
        {
            if (tag.ValueKind != JsonValueKind.Object)
            {
                continue;
            }

            string? name = tag.TryGetProperty("name"u8, out JsonElement nameEl) && nameEl.ValueKind == JsonValueKind.String
                ? nameEl.GetString()
                : null;

            if (name is null)
            {
                continue;
            }

            string? summary = tag.TryGetProperty("summary"u8, out JsonElement summaryEl) && summaryEl.ValueKind == JsonValueKind.String
                ? summaryEl.GetString()
                : null;

            string? description = tag.TryGetProperty("description"u8, out JsonElement descEl) && descEl.ValueKind == JsonValueKind.String
                ? descEl.GetString()
                : null;

            string? parent = tag.TryGetProperty("parent"u8, out JsonElement parentEl) && parentEl.ValueKind == JsonValueKind.String
                ? parentEl.GetString()
                : null;

            string? kind = tag.TryGetProperty("kind"u8, out JsonElement kindEl) && kindEl.ValueKind == JsonValueKind.String
                ? kindEl.GetString()
                : null;

            result.Add(new TagInfo(name, summary, description, parent, kind));
        }

        return [.. result];
    }

    /// <summary>
    /// Walks the OpenAPI 3.0 specification and emits C# source files.
    /// </summary>
    /// <param name="specRoot">The root element of the parsed spec document.</param>
    /// <param name="filter">Optional operation filter.</param>
    /// <param name="referenceResolver">
    /// Optional reference resolver. If <see langword="null"/>,
    /// a <see cref="LocalReferenceResolver"/> is used.
    /// </param>
    /// <returns>The generated source files.</returns>
    public IReadOnlyList<GeneratedFile> Generate(
        JsonElement specRoot,
        OperationFilter? filter = null,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        referenceResolver ??= new LocalReferenceResolver(specRoot);
        List<OperationInfo> operations = [];
        ServerInfo? rootServer = GetDefaultServerInfo(specRoot);

        foreach (OperationRef opRef in WalkOperationRefs(specRoot, filter, referenceResolver))
        {
            operations.Add(PrepareOperation(opRef, referenceResolver, rootServer, specRoot));
        }

        List<GeneratedFile> files = [];
        Dictionary<string, List<OperationInfo>> groups = GroupOperationsByTag(operations);

        foreach (OperationInfo op in operations)
        {
            files.Add(this.EmitRequestStruct(op));
            files.Add(this.EmitResponseStruct(op));
        }

        foreach ((string tag, List<OperationInfo> tagOps) in groups)
        {
            string clientName = this.GetClientName(tag);
            files.Add(this.EmitInterface(clientName, tagOps, rootServer));
            files.Add(this.EmitImplementation(clientName, tagOps));
        }

        return files;
    }

    // ═══════════════════════════════════════════════════════════════════
    // Schema pointer collection — walks typed model directly
    // ═══════════════════════════════════════════════════════════════════
    private static void CollectPathItemPointers(
        JsonProperty<JsonElement> pathProp,
        List<SchemaReference> pointers,
        Dictionary<string, string> parameterNames,
        Dictionary<string, string> formBodies,
        IOpenApiReferenceResolver referenceResolver,
        ReadOnlySpan<byte> rootSegmentUtf8,
        string? callbackPathItemRef = null)
    {
        OpenApiDocument.PathItem pathItem = OpenApiDocument.PathItem.From(pathProp.Value);

        // Determine if this path item is a $ref and compute its absolute reference
        string? pathItemRefValue = callbackPathItemRef;
        if (pathItemRefValue is null)
        {
            OpenApiDocument.JsonReference asRef = OpenApiDocument.JsonReference.From(pathItem);
            if (asRef.Ref.IsNotUndefined())
            {
                string refStr = asRef.Ref.GetString()!;
                pathItemRefValue = referenceResolver.ResolveToAbsolute(refStr);
            }
        }

        if (!TryResolvePathItem(pathItem, referenceResolver, out OpenApiDocument.PathItem resolved, out IDisposable pathItemScope))
        {
            return;
        }

        using (pathItemScope)
        {
            foreach ((ReadOnlyMemory<byte> methodName, OperationMethod method) in HttpMethods)
            {
                if (((JsonElement)resolved).TryGetProperty(methodName.Span, out JsonElement operationElement)
                    && operationElement.ValueKind == JsonValueKind.Object)
                {
                    OpenApiDocument.Operation operation = operationElement;
                    CollectOperationPointers(pathProp, operation, method, resolved, pointers, parameterNames, formBodies, referenceResolver, rootSegmentUtf8, pathItemRefValue);
                }
            }
        }
    }

    private static void CollectOperationPointers(
        JsonProperty<JsonElement> pathProp,
        OpenApiDocument.Operation operation,
        OperationMethod method,
        OpenApiDocument.PathItem pathItem,
        List<SchemaReference> pointers,
        Dictionary<string, string> parameterNames,
        Dictionary<string, string> formBodies,
        IOpenApiReferenceResolver referenceResolver,
        ReadOnlySpan<byte> rootSegmentUtf8,
        string? pathItemRefValue = null)
    {
        using UnescapedUtf8JsonString pathName = pathProp.Utf8NameSpan;

        // Parameter schema pointers (with path/operation merge).
        // In OpenAPI 2.0 (Swagger) a body parameter carries a real Schema Object under
        // /schema; non-body parameters carry their constraint keywords directly on the
        // Parameter Object, so the Parameter Object itself is the schema position.
        // formData parameters have no schema position in the document — they are
        // aggregated into a synthesized form-body document during preparation.
        List<(OpenApiDocument.Parameter Parameter, int SourceIndex, bool IsPathLevel)> formDataParams = [];

        foreach ((OpenApiDocument.Parameter param, int sourceIndex, bool isPathLevel, string? refValue) in
            MergeParameters(operation, pathItem, referenceResolver))
        {
            if (ParameterIsIn(param, "formData"u8))
            {
                formDataParams.Add((param, sourceIndex, isPathLevel));
                continue;
            }

            string positionalPointer;
            string? subPathForPathItemRef;

            if (ParameterIsIn(param, "body"u8))
            {
                OpenApiDocument.BodyParameter bodyParam = OpenApiDocument.BodyParameter.From(param);
                if (bodyParam.SchemaValue.IsUndefined())
                {
                    continue;
                }

                positionalPointer = SchemaPointerBuilder.BuildParameterSchemaPointer(
                    rootSegmentUtf8, pathName.Span, method, sourceIndex, isPathLevel);

                string resolvableForBody = refValue is not null
                    ? SchemaPointerBuilder.BuildRefBasedPointer(refValue, "/schema")
                    : pathItemRefValue is not null
                        ? SchemaPointerBuilder.BuildRefBasedPointer(pathItemRefValue, SchemaPointerBuilder.BuildParameterSubPath(method, sourceIndex, isPathLevel))
                        : positionalPointer;

                pointers.Add(new SchemaReference(positionalPointer, resolvableForBody));

                if (bodyParam.Name.IsNotUndefined())
                {
                    string? bodyParamName = bodyParam.Name.GetString();
                    if (bodyParamName is not null)
                    {
                        parameterNames[positionalPointer.AsSpan(1).ToString()] = bodyParamName;
                    }
                }

                continue;
            }
            else
            {
                // query/path/header: the Parameter Object is the schema position (no /schema tail).
                // File-typed parameters are only legal in formData; skip anything claiming type: file.
                if (((JsonElement)param).TryGetProperty("type"u8, out JsonElement typeEl) && typeEl.ValueEquals("file"u8))
                {
                    continue;
                }

                positionalPointer = SchemaPointerBuilder.BuildParameterObjectPointer(
                    rootSegmentUtf8, pathName.Span, method, sourceIndex, isPathLevel);
                subPathForPathItemRef = SchemaPointerBuilder.BuildParameterObjectSubPath(method, sourceIndex, isPathLevel);
            }

            string resolvablePointer = refValue is not null
                ? refValue
                : pathItemRefValue is not null
                    ? SchemaPointerBuilder.BuildRefBasedPointer(pathItemRefValue, subPathForPathItemRef)
                    : positionalPointer;

            pointers.Add(new SchemaReference(positionalPointer, resolvablePointer));

            // Record the parameter name so the naming heuristic can use it.
            // Key is the fragment (pointer without leading '#') for direct lookup.
            if (((JsonElement)param).TryGetProperty("name"u8, out JsonElement nameEl) && nameEl.ValueKind == JsonValueKind.String)
            {
                string? name = nameEl.GetString();
                if (name is not null)
                {
                    parameterNames[positionalPointer.AsSpan(1).ToString()] = name;
                }
            }
        }

        if (formDataParams.Count > 0)
        {
            // Synthesize the aggregated form-body schema for this operation and emit a
            // SchemaReference whose positional pointer is the deterministic key shared
            // with PrepareRequestBody, and whose resolvable pointer targets the
            // synthetic document registered by the caller.
            string? operationId = operation.OperationId.IsNotUndefined()
                ? operation.OperationId.GetString()
                : null;

            string formBodyTypeName = GetMethodName(operationId, method, pathProp.Name) + "FormBody";
            formBodies[formBodyTypeName] = BuildFormBodySchemaJson(formDataParams);

            string positionalPointer = BuildFormBodyPositionalPointer(pathName.Span, method);
            string resolvablePointer = FormBodyDocumentUri + "#/schemas/" + formBodyTypeName;
            pointers.Add(new SchemaReference(positionalPointer, resolvablePointer));
        }

        // Response schema and header pointers. OpenAPI 2.0 responses carry a direct
        // /schema member (no content media-type map — media types come from produces),
        // and response headers are Header Objects whose constraint keywords live
        // directly on the header (no /schema tail, and headers cannot be $refs).
        if (operation.ResponsesValue.IsNotUndefined())
        {
            foreach (var responseProp in operation.ResponsesValue.EnumerateObject())
            {
                if (responseProp.Value.IsUndefined())
                {
                    continue;
                }

                if (!TryResolveResponse(
                    responseProp.Value,
                    referenceResolver,
                    out OpenApiDocument.Response response,
                    out IDisposable responseScope,
                    out string? responseRefValue))
                {
                    continue;
                }

                using (responseScope)
                {
                    using UnescapedUtf8JsonString statusCode = responseProp.Utf8NameSpan;

                    // type: file response schemas map to the raw-stream path; no JSON Schema type needed.
                    if (response.Schema.IsNotUndefined()
                        && !(((JsonElement)response.Schema).TryGetProperty("type"u8, out JsonElement schemaTypeEl) && schemaTypeEl.ValueEquals("file"u8)))
                    {
                        string positionalPointer = SchemaPointerBuilder.BuildResponseSchemaPointer(
                            rootSegmentUtf8, pathName.Span, method, statusCode.Span);

                        string resolvablePointer = responseRefValue is not null
                            ? SchemaPointerBuilder.BuildRefBasedPointer(responseRefValue, "/schema")
                            : pathItemRefValue is not null
                                ? SchemaPointerBuilder.BuildRefBasedPointer(
                                    pathItemRefValue, SchemaPointerBuilder.BuildResponseSchemaSubPath(method, statusCode.Span))
                                : positionalPointer;

                        pointers.Add(new SchemaReference(positionalPointer, resolvablePointer));
                    }

                    if (response.HeadersValue.IsNotUndefined())
                    {
                        foreach (var headerProp in response.HeadersValue.EnumerateObject())
                        {
                            if (headerProp.Value.IsUndefined())
                            {
                                continue;
                            }

                            using UnescapedUtf8JsonString headerName = headerProp.Utf8NameSpan;

                            string positionalPointer = SchemaPointerBuilder.BuildResponseHeaderObjectPointer(
                                rootSegmentUtf8, pathName.Span, method, statusCode.Span, headerName.Span);

                            string resolvablePointer = responseRefValue is not null
                                ? SchemaPointerBuilder.BuildRefBasedPointer(
                                    responseRefValue, SchemaPointerBuilder.BuildHeaderObjectSubPath(headerName.Span))
                                : pathItemRefValue is not null
                                    ? SchemaPointerBuilder.BuildRefBasedPointer(
                                        pathItemRefValue, SchemaPointerBuilder.BuildResponseHeaderObjectSubPath(method, statusCode.Span, headerName.Span))
                                    : positionalPointer;

                            pointers.Add(new SchemaReference(positionalPointer, resolvablePointer));
                        }
                    }
                }
            }
        }
    }

    /// <summary>
    /// Determines whether a parameter's <c>in</c> field matches the given UTF-8 value.
    /// </summary>
    private static bool ParameterIsIn(OpenApiDocument.Parameter param, ReadOnlySpan<byte> inValue)
    {
        return ((JsonElement)param).TryGetProperty("in"u8, out JsonElement inEl) && inEl.ValueEquals(inValue);
    }

    // ═══════════════════════════════════════════════════════════════════
    // Walk logic — yields typed model references
    // ═══════════════════════════════════════════════════════════════════
    private static IEnumerable<OperationRef> WalkOperationRefs(
        JsonElement specRoot,
        OperationFilter? filter,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        OpenApiDocument doc = specRoot;

        if (doc.PathsValue.IsUndefined())
        {
            yield break;
        }

        referenceResolver ??= new LocalReferenceResolver(specRoot);

        foreach (JsonProperty<JsonElement> pathProp in doc.PathsValue.EnumerateObject())
        {
            if (filter is not null)
            {
                using UnescapedUtf16JsonString name = pathProp.Utf16NameSpan;
                if (!filter.Matches(name.Span))
                {
                    continue;
                }
            }

            foreach (OperationRef entry in WalkPathItemRefs(pathProp, referenceResolver))
            {
                yield return entry;
            }
        }
    }

    private static IEnumerable<OperationRef> WalkPathItemRefs(
        JsonProperty<JsonElement> pathProp,
        IOpenApiReferenceResolver referenceResolver)
    {
        OpenApiDocument.PathItem pathItem = OpenApiDocument.PathItem.From(pathProp.Value);

        if (!TryResolvePathItem(pathItem, referenceResolver, out OpenApiDocument.PathItem resolved, out IDisposable pathItemScope))
        {
            yield break;
        }

        using (pathItemScope)
        {
            foreach ((ReadOnlyMemory<byte> methodName, OperationMethod method) in HttpMethods)
            {
                if (((JsonElement)resolved).TryGetProperty(methodName.Span, out JsonElement operationElement)
                    && operationElement.ValueKind == JsonValueKind.Object)
                {
                    OpenApiDocument.Operation operation = operationElement;
                    yield return new OperationRef(pathProp, operation, method, resolved);
                }
            }
        }
    }

    // ═══════════════════════════════════════════════════════════════════
    // Parameter merging — typed dedup via JsonString equality
    // ═══════════════════════════════════════════════════════════════════
    private static List<(OpenApiDocument.Parameter Parameter, int SourceIndex, bool IsPathLevel, string? RefValue)> MergeParameters(
        OpenApiDocument.Operation operation,
        OpenApiDocument.PathItem pathItem,
        IOpenApiReferenceResolver referenceResolver)
    {
        bool hasOperationParams = operation.Parameters.IsNotUndefined();
        bool hasPathParams = pathItem.Parameters.IsNotUndefined();

        if (!hasOperationParams && !hasPathParams)
        {
            return [];
        }

        List<(OpenApiDocument.Parameter Parameter, int SourceIndex, bool IsPathLevel, string? RefValue)> result = [];

        if (hasPathParams)
        {
            int sourceIndex = 0;
            foreach (OpenApiDocument.ParametersList.ParametersListEntity paramOrRef in pathItem.Parameters.EnumerateArray())
            {
                if (paramOrRef.IsUndefined())
                {
                    sourceIndex++;
                    continue;
                }

                if (TryResolveParameter(paramOrRef, referenceResolver, out OpenApiDocument.Parameter typed, out IDisposable paramScope, out string? refValue))
                {
                    paramScope.Dispose();
                    result.Add((typed, sourceIndex, true, refValue));
                }

                sourceIndex++;
            }
        }

        if (hasOperationParams)
        {
            int sourceIndex = 0;
            foreach (OpenApiDocument.ParametersList.ParametersListEntity paramOrRef in operation.Parameters.EnumerateArray())
            {
                if (paramOrRef.IsUndefined())
                {
                    sourceIndex++;
                    continue;
                }

                if (TryResolveParameter(paramOrRef, referenceResolver, out OpenApiDocument.Parameter typed, out IDisposable paramScope, out string? refValue))
                {
                    paramScope.Dispose();
                    int existingIndex = FindParameterIndex(result, typed);

                    if (existingIndex >= 0)
                    {
                        result[existingIndex] = (typed, sourceIndex, false, refValue);
                    }
                    else
                    {
                        result.Add((typed, sourceIndex, false, refValue));
                    }
                }

                sourceIndex++;
            }
        }

        return result;
    }

    private static int FindParameterIndex(
        List<(OpenApiDocument.Parameter Parameter, int SourceIndex, bool IsPathLevel, string? RefValue)> parameters,
        OpenApiDocument.Parameter newParam)
    {
        // The Parameter union does not expose name/in directly; the BodyParameter view
        // reads the same fixed fields for every parameter kind.
        OpenApiDocument.BodyParameter a = OpenApiDocument.BodyParameter.From(newParam);
        for (int i = 0; i < parameters.Count; i++)
        {
            OpenApiDocument.BodyParameter b = OpenApiDocument.BodyParameter.From(parameters[i].Parameter);
            if (a.In.Equals(b.In) && a.Name.Equals(b.Name))
            {
                return i;
            }
        }

        return -1;
    }

    // ── $ref resolution ─────────────────────────────────────────────────
    private static bool TryResolvePathItem(
        OpenApiDocument.PathItem pathItem,
        IOpenApiReferenceResolver referenceResolver,
        out OpenApiDocument.PathItem resolved,
        out IDisposable baseScope)
    {
        OpenApiDocument.JsonReference asRef = OpenApiDocument.JsonReference.From(pathItem);
        if (asRef.Ref.IsNotUndefined())
        {
            string refStr = asRef.Ref.GetString()!;
            if (referenceResolver.TryResolve(refStr, out JsonElement element))
            {
                resolved = OpenApiDocument.PathItem.From(element);
                baseScope = referenceResolver.PushResolvedBase(refStr);
                return true;
            }

            resolved = default;
            baseScope = EmptyScope.Instance;
            return false;
        }

        resolved = pathItem;
        baseScope = EmptyScope.Instance;
        return true;
    }

    private static bool TryResolveParameter(
        OpenApiDocument.ParametersList.ParametersListEntity paramOrRef,
        IOpenApiReferenceResolver referenceResolver,
        out OpenApiDocument.Parameter resolved,
        out IDisposable baseScope,
        out string? refValue)
    {
        OpenApiDocument.JsonReference asRef = OpenApiDocument.JsonReference.From(paramOrRef);
        if (asRef.Ref.IsNotUndefined())
        {
            string refStr = asRef.Ref.GetString()!;
            if (referenceResolver.TryResolve(refStr, out JsonElement paramElement))
            {
                resolved = OpenApiDocument.Parameter.From(paramElement);
                refValue = referenceResolver.ResolveToAbsolute(refStr);
                baseScope = referenceResolver.PushResolvedBase(refStr);
                return true;
            }

            resolved = default;
            baseScope = EmptyScope.Instance;
            refValue = null;
            return false;
        }

        resolved = OpenApiDocument.Parameter.From(paramOrRef);
        baseScope = EmptyScope.Instance;
        refValue = null;
        return true;
    }

    private static bool TryResolveResponse(
        JsonElement responseOrRef,
        IOpenApiReferenceResolver referenceResolver,
        out OpenApiDocument.Response resolved,
        out IDisposable baseScope,
        out string? refValue)
    {
        // Check for $ref directly and fall back to From() rather than using the
        // Match discriminator, mirroring the 3.x generators: schema validation can
        // reject otherwise-usable Response Objects with missing optional members.
        OpenApiDocument.JsonReference asRef = OpenApiDocument.JsonReference.From(responseOrRef);
        if (asRef.Ref.IsNotUndefined())
        {
            string refStr = asRef.Ref.GetString()!;
            if (referenceResolver.TryResolve(refStr, out JsonElement respElement))
            {
                resolved = OpenApiDocument.Response.From(respElement);
                refValue = referenceResolver.ResolveToAbsolute(refStr);
                baseScope = referenceResolver.PushResolvedBase(refStr);
                return true;
            }

            resolved = default;
            baseScope = EmptyScope.Instance;
            refValue = null;
            return false;
        }

        resolved = OpenApiDocument.Response.From(responseOrRef);
        baseScope = EmptyScope.Instance;
        refValue = null;
        return true;
    }

    // ── Parameter trait parsing ──────────────────────────────────────────
    // In OpenAPI 3.0, the "in" and "style" properties are plain JSON strings
    // without const-string enum Match — we use ValueEquals with UTF-8 literals.
    private static (ParameterLocation Location, ParameterStyle Style, bool Explode, bool DegradedCollectionFormat) ParseParameterTraits(
        OpenApiDocument.Parameter typed)
    {
        // OpenAPI 2.0 has no style/explode; array serialization is governed by
        // collectionFormat (csv default | ssv | tsv | pipes | multi). There is no
        // cookie location, and body/formData parameters never reach this method.
        ParameterLocation location =
            ParameterIsIn(typed, "header"u8) ? ParameterLocation.Header
            : ParameterIsIn(typed, "path"u8) ? ParameterLocation.Path
            : ParameterLocation.Query;

        (ParameterStyle style, bool explode, bool degraded) = ParseCollectionFormat(typed, location);
        return (location, style, explode, degraded);
    }

    private static (ParameterStyle Style, bool Explode, bool Degraded) ParseCollectionFormat(
        OpenApiDocument.Parameter typed,
        ParameterLocation location)
    {
        // csv maps to form (query, explicit explode: false — the 3.x form default is
        // exploded) or simple (path, header). multi is only valid for query/formData
        // per the 2.0 specification. ssv/tsv/pipes only have wire machinery for query
        // parameters; on path or header they DEGRADE to csv (simple) semantics on both
        // the client and server sides, and the degradation is reported via a #warning
        // in the generated code so it is never silent.
        ParameterStyle csvStyle = location == ParameterLocation.Query ? ParameterStyle.Form : ParameterStyle.Simple;

        if (!((JsonElement)typed).TryGetProperty("collectionFormat"u8, out JsonElement cf) || cf.ValueKind != JsonValueKind.String)
        {
            return (csvStyle, false, false);
        }

        bool isDelimited = cf.ValueEquals("ssv"u8) || cf.ValueEquals("tsv"u8) || cf.ValueEquals("pipes"u8);

        if (location != ParameterLocation.Query)
        {
            return (csvStyle, false, isDelimited || cf.ValueEquals("multi"u8));
        }

        if (cf.ValueEquals("multi"u8))
        {
            return (ParameterStyle.Form, true, false);
        }

        if (cf.ValueEquals("ssv"u8))
        {
            return (ParameterStyle.SpaceDelimited, false, false);
        }

        if (cf.ValueEquals("tsv"u8))
        {
            return (ParameterStyle.TabDelimited, false, false);
        }

        if (cf.ValueEquals("pipes"u8))
        {
            return (ParameterStyle.PipeDelimited, false, false);
        }

        return (csvStyle, false, false);
    }

    // ═══════════════════════════════════════════════════════════════════
    // Preparation — converts typed model to emit-boundary records
    // ═══════════════════════════════════════════════════════════════════
    private OperationInfo PrepareOperation(
        OperationRef opRef,
        IOpenApiReferenceResolver referenceResolver,
        ServerInfo? rootServer,
        JsonElement specRoot = default)
    {
        using UnescapedUtf8JsonString pathName = opRef.PathProp.Utf8NameSpan;
        ReadOnlySpan<byte> pathNameUtf8 = pathName.Span;

        // Extract strings at the emit boundary
        string pathTemplate = opRef.PathProp.Name;
        string? operationId = opRef.Operation.OperationId.IsNotUndefined()
            ? opRef.Operation.OperationId.GetString()
            : null;
        string? summary = opRef.Operation.Summary.IsNotUndefined()
            ? opRef.Operation.Summary.GetString()
            : null;
        string? description = opRef.Operation.Description.IsNotUndefined()
            ? opRef.Operation.Description.GetString()
            : null;
        bool isDeprecated = opRef.Operation.Deprecated.ValueKind == JsonValueKind.True;
        string[] tags = ExtractTags(opRef.Operation);
        string methodName = GetMethodName(operationId, opRef.Method, pathTemplate);

        ParameterInfo[] parameters = PrepareParameters(
            opRef.Operation, opRef.PathItem, pathNameUtf8, opRef.Method, referenceResolver);
        RequestBodyInfo? requestBody = PrepareRequestBody(
            opRef.Operation, opRef.PathItem, specRoot, pathNameUtf8, opRef.Method, referenceResolver, this.ignoreEmptyFormUrlEncodedBody);
        ResponseInfo[] responses = PrepareResponses(
            opRef.Operation, specRoot, pathNameUtf8, opRef.Method, referenceResolver);

        ServerInfo? effectiveServer = ResolveEffectiveServer(
            opRef.Operation, specRoot, rootServer);

        OperationSecurityRequirementSet[]? securityRequirements = specRoot.ValueKind != JsonValueKind.Undefined
            ? ExtractSecurityRequirements(opRef.Operation, specRoot)
            : null;

        return new OperationInfo(
            pathTemplate,
            opRef.Method,
            methodName,
            operationId,
            summary,
            description,
            isDeprecated,
            tags,
            parameters,
            requestBody,
            responses,
            effectiveServer,
            securityRequirements);
    }

    private static OperationSecurityRequirementSet[]? ExtractSecurityRequirements(
        OpenApiDocument.Operation operation,
        JsonElement specRoot)
    {
        OpenApiDocument doc = specRoot;
        Dictionary<string, string> schemeTypes = BuildSecuritySchemeTypeLookup(specRoot);

        // Operation-level security overrides document-level.
        if (operation.SecurityValue.IsNotUndefined())
        {
            return ParseSecurityRequirements(JsonElement.From(operation.SecurityValue), schemeTypes);
        }

        // Fall back to document-level security.
        if (doc.SecurityValue.IsNotUndefined())
        {
            return ParseSecurityRequirements(JsonElement.From(doc.SecurityValue), schemeTypes);
        }

        return null;
    }

    /// <summary>
    /// Builds a map of security-scheme name to its OpenAPI <c>type</c> by reading
    /// the top-level <c>securityDefinitions</c> directly from the raw document. Reading raw
    /// JSON keeps this tolerant of the typed model's union shapes.
    /// </summary>
    private static Dictionary<string, string> BuildSecuritySchemeTypeLookup(JsonElement specRoot)
    {
        Dictionary<string, string> lookup = new(StringComparer.Ordinal);

        if (specRoot.ValueKind != JsonValueKind.Object
            || !specRoot.TryGetProperty("securityDefinitions"u8, out JsonElement schemes)
            || schemes.ValueKind != JsonValueKind.Object)
        {
            return lookup;
        }

        foreach (var scheme in schemes.EnumerateObject())
        {
            if (scheme.Value.ValueKind == JsonValueKind.Object
                && scheme.Value.TryGetProperty("type"u8, out JsonElement schemeType)
                && schemeType.ValueKind == JsonValueKind.String)
            {
                lookup[scheme.Name] = schemeType.GetString()!;
            }
        }

        return lookup;
    }

    private static OperationSecurityRequirementSet[]? ParseSecurityRequirements(
        JsonElement securityArray,
        Dictionary<string, string> schemeTypes)
    {
        if (securityArray.ValueKind != JsonValueKind.Array)
        {
            return null;
        }

        List<OperationSecurityRequirementSet> sets = [];

        // Each element of the array is an alternative (OR); the schemes within it are AND'd.
        foreach (JsonElement requirement in securityArray.EnumerateArray())
        {
            sets.Add(ParseSecurityRequirementSet(requirement, schemeTypes));
        }

        return sets.Count > 0 ? [.. sets] : null;
    }

    private static OperationSecurityRequirementSet ParseSecurityRequirementSet(
        JsonElement requirement,
        Dictionary<string, string> schemeTypes)
    {
        List<OperationSecurityRequirement> requirements = [];

        // Each property is one scheme: { "schemeName": ["scope1", "scope2"] }. An empty object marks
        // anonymous access as an accepted alternative.
        foreach (var schemeProp in requirement.EnumerateObject())
        {
            string schemeName = schemeProp.Name;
            List<string> scopes = [];

            foreach (var scope in schemeProp.Value.EnumerateArray())
            {
                scopes.Add(scope.GetString()!);
            }

            requirements.Add(new OperationSecurityRequirement(
                schemeName,
                [.. scopes],
                schemeTypes.TryGetValue(schemeName, out string? schemeType) ? schemeType : null));
        }

        return new OperationSecurityRequirementSet([.. requirements], requirements.Count == 0);
    }

    private static ParameterInfo[] PrepareParameters(
        OpenApiDocument.Operation operation,
        OpenApiDocument.PathItem pathItem,
        ReadOnlySpan<byte> pathNameUtf8,
        OperationMethod method,
        IOpenApiReferenceResolver referenceResolver)
    {
        var merged = MergeParameters(operation, pathItem, referenceResolver);

        if (merged.Count == 0)
        {
            return [];
        }

        List<ParameterInfo> result = [];

        for (int i = 0; i < merged.Count; i++)
        {
            (OpenApiDocument.Parameter param, int sourceIndex, bool isPathLevel, string? _) = merged[i];

            // body and formData parameters become the request body, not ParameterInfo entries.
            if (ParameterIsIn(param, "body"u8) || ParameterIsIn(param, "formData"u8))
            {
                continue;
            }

            (ParameterLocation location, ParameterStyle style, bool explode, bool degradedCollectionFormat) = ParseParameterTraits(param);

            bool required = ((JsonElement)param).TryGetProperty("required"u8, out JsonElement requiredEl)
                && requiredEl.ValueKind == JsonValueKind.True;

            // The non-body Parameter Object carries its constraint keywords directly,
            // so the parameter element itself is the schema.
            JsonElement schemaElement = (JsonElement)param;
            ParameterSerializationKind serializationKind = SchemaClassifier.Classify(schemaElement);

            ParameterSerializationKind elementKind = serializationKind switch
            {
                ParameterSerializationKind.Array => SchemaClassifier.ClassifyArrayElement(schemaElement),
                ParameterSerializationKind.Object => SchemaClassifier.ClassifyObjectValue(schemaElement),
                _ => ParameterSerializationKind.String,
            };

            bool deepNesting = serializationKind is ParameterSerializationKind.Object or ParameterSerializationKind.Array
                && SchemaClassifier.HasDeepNesting(schemaElement);

            string? schemaPointer = SchemaPointerBuilder.BuildParameterObjectPointer(
                "paths"u8, pathNameUtf8, method, sourceIndex, isPathLevel);

            // Extract the default value (if any) for optional parameters.
            string? defaultValueJson = null;
            JsonValueKind defaultValueKind = JsonValueKind.Undefined;
            if (!required
                && schemaElement.TryGetProperty("default"u8, out JsonElement defaultEl)
                && defaultEl.ValueKind != JsonValueKind.Undefined)
            {
                defaultValueJson = defaultEl.GetRawText();
                defaultValueKind = defaultEl.ValueKind;
            }

            // Extract name at the emit boundary
            if (!((JsonElement)param).TryGetProperty("name"u8, out JsonElement nameEl) || nameEl.ValueKind != JsonValueKind.String)
            {
                continue;
            }

            string name = nameEl.GetString()!;

            result.Add(new ParameterInfo(
                name, location, required, style, explode,
                serializationKind, elementKind, schemaPointer, deepNesting, defaultValueJson, defaultValueKind,
                degradedCollectionFormat));
        }

        return [.. result];
    }

    /// <summary>
    /// Determines whether the operation (or its path item) declares a body or formData
    /// parameter. Unresolved $ref parameters are not inspected; this is a display-level
    /// summary used by the operation listing.
    /// </summary>
    private static bool OperationHasBodyOrFormData(
        OpenApiDocument.Operation operation,
        OpenApiDocument.PathItem pathItem)
    {
        return ListHasBodyOrFormData(operation.Parameters) || ListHasBodyOrFormData(pathItem.Parameters);

        static bool ListHasBodyOrFormData(OpenApiDocument.ParametersList parameters)
        {
            if (parameters.IsUndefined())
            {
                return false;
            }

            foreach (OpenApiDocument.ParametersList.ParametersListEntity paramOrRef in parameters.EnumerateArray())
            {
                if (((JsonElement)paramOrRef).TryGetProperty("in"u8, out JsonElement inEl)
                    && (inEl.ValueEquals("body"u8) || inEl.ValueEquals("formData"u8)))
                {
                    return true;
                }
            }

            return false;
        }
    }

    /// <summary>
    /// Gets the effective media-type list for an operation: the operation-level
    /// <c>consumes</c>/<c>produces</c> REPLACES the root-level list per the 2.0
    /// specification (no merging).
    /// </summary>
    private static List<string> GetEffectiveMediaTypes(
        OpenApiDocument.Operation operation,
        JsonElement specRoot,
        ReadOnlySpan<byte> fieldName)
    {
        List<string> result = [];

        if (((JsonElement)operation).TryGetProperty(fieldName, out JsonElement opList) && opList.ValueKind == JsonValueKind.Array)
        {
            foreach (JsonElement mt in opList.EnumerateArray())
            {
                if (mt.ValueKind == JsonValueKind.String)
                {
                    result.Add(mt.GetString()!);
                }
            }

            return result;
        }

        if (specRoot.ValueKind == JsonValueKind.Object
            && specRoot.TryGetProperty(fieldName, out JsonElement rootList)
            && rootList.ValueKind == JsonValueKind.Array)
        {
            foreach (JsonElement mt in rootList.EnumerateArray())
            {
                if (mt.ValueKind == JsonValueKind.String)
                {
                    result.Add(mt.GetString()!);
                }
            }
        }

        return result;
    }

    /// <summary>
    /// Builds the deterministic positional pointer used as the schemaTypeMap key for a
    /// synthesized form body: <c>#/paths/&lt;path&gt;/&lt;method&gt;/x-corvus-form-body</c>.
    /// This pointer is only ever a dictionary key shared between the pointer-collection
    /// and preparation passes; it is never dereferenced against the document.
    /// </summary>
    private static string BuildFormBodyPositionalPointer(ReadOnlySpan<byte> pathNameUtf8, OperationMethod method)
    {
        StringBuilder sb = new("#/paths/");
        foreach (byte b in pathNameUtf8)
        {
            switch (b)
            {
                case (byte)'~':
                    sb.Append("~0");
                    break;
                case (byte)'/':
                    sb.Append("~1");
                    break;
                default:
                    sb.Append((char)b);
                    break;
            }
        }

        sb.Append('/');
        sb.Append(GetMethodSegment(method));
        sb.Append("/x-corvus-form-body");
        return sb.ToString();
    }

    private static string GetMethodSegment(OperationMethod method) => method switch
    {
        OperationMethod.Get => "get",
        OperationMethod.Put => "put",
        OperationMethod.Post => "post",
        OperationMethod.Delete => "delete",
        OperationMethod.Options => "options",
        OperationMethod.Head => "head",
        OperationMethod.Patch => "patch",
        _ => throw new UnreachableException(),
    };

    private static RequestBodyInfo? PrepareRequestBody(
        OpenApiDocument.Operation operation,
        OpenApiDocument.PathItem pathItem,
        JsonElement specRoot,
        ReadOnlySpan<byte> pathNameUtf8,
        OperationMethod method,
        IOpenApiReferenceResolver referenceResolver,
        bool ignoreEmptyFormUrlEncodedBody = false)
    {
        var merged = MergeParameters(operation, pathItem, referenceResolver);

        // A single in: body parameter carries the request payload schema; consumes
        // supplies the media types. formData parameters aggregate into a synthesized
        // object schema serialized as application/x-www-form-urlencoded or
        // multipart/form-data.
        List<(OpenApiDocument.Parameter Parameter, int SourceIndex, bool IsPathLevel)> formDataParams = [];

        foreach ((OpenApiDocument.Parameter param, int sourceIndex, bool isPathLevel, string? _) in merged)
        {
            if (ParameterIsIn(param, "body"u8))
            {
                OpenApiDocument.BodyParameter bodyParam = OpenApiDocument.BodyParameter.From(param);

                bool required = ((JsonElement)param).TryGetProperty("required"u8, out JsonElement requiredEl)
                    && requiredEl.ValueKind == JsonValueKind.True;

                string? description = bodyParam.Description.IsNotUndefined()
                    ? bodyParam.Description.GetString()
                    : null;

                bool hasSchema = bodyParam.SchemaValue.IsNotUndefined();
                bool schemaIsFile = hasSchema
                    && ((JsonElement)bodyParam.SchemaValue).TryGetProperty("type"u8, out JsonElement bodyTypeEl)
                    && bodyTypeEl.ValueEquals("file"u8);

                string? schemaPointer = hasSchema && !schemaIsFile
                    ? SchemaPointerBuilder.BuildParameterSchemaPointer(
                        "paths"u8, pathNameUtf8, method, sourceIndex, isPathLevel)
                    : null;

                List<string> consumes = GetEffectiveMediaTypes(operation, specRoot, "consumes"u8);
                if (consumes.Count == 0)
                {
                    consumes.Add("application/json");
                }

                List<ContentInfo> content = [];
                foreach (string mediaType in consumes)
                {
                    if (CodeEmitHelpers.IsFormUrlEncodedMediaType(mediaType) || CodeEmitHelpers.IsMultipartMediaType(mediaType))
                    {
                        // Form media types require formData parameters, not a body parameter.
                        continue;
                    }

                    string? pointerForMediaType = CodeEmitHelpers.IsRawStreamMediaType(mediaType) ? null : schemaPointer;
                    content.Add(new ContentInfo(mediaType, pointerForMediaType, null));
                }

                if (content.Count == 0)
                {
                    content.Add(new ContentInfo("application/json", schemaPointer, null));
                }

                return new RequestBodyInfo(description, required, [.. content], []);
            }

            if (ParameterIsIn(param, "formData"u8))
            {
                formDataParams.Add((param, sourceIndex, isPathLevel));
            }
        }

        if (formDataParams.Count == 0)
        {
            return null;
        }

        // Synthesize the form body from the formData parameters.
        bool anyFile = false;
        bool anyRequired = false;
        Dictionary<string, EncodingInfo> encodings = new(StringComparer.Ordinal);
        List<BinaryPropertyInfo> binaryProperties = [];

        foreach ((OpenApiDocument.Parameter param, int _, bool _) in formDataParams)
        {
            if (!((JsonElement)param).TryGetProperty("name"u8, out JsonElement nameEl) || nameEl.ValueKind != JsonValueKind.String)
            {
                continue;
            }

            string name = nameEl.GetString()!;

            if (((JsonElement)param).TryGetProperty("required"u8, out JsonElement reqEl) && reqEl.ValueKind == JsonValueKind.True)
            {
                anyRequired = true;
            }

            if (((JsonElement)param).TryGetProperty("type"u8, out JsonElement typeEl) && typeEl.ValueEquals("file"u8))
            {
                anyFile = true;
                binaryProperties.Add(new BinaryPropertyInfo(name, CodeEmitHelpers.SanitizeParameterName(name), null));
                continue;
            }

            // Per-field collectionFormat lowers into the encodings map consumed by the
            // form serializers. Array fields with csv (or no) collectionFormat get an
            // explicit non-exploded form entry: the client's comma join is unchanged,
            // and the server-side deserializer needs the entry to split the value.
            bool isArrayField = ((JsonElement)param).TryGetProperty("type"u8, out JsonElement fieldTypeEl)
                && fieldTypeEl.ValueEquals("array"u8);

            if (((JsonElement)param).TryGetProperty("collectionFormat"u8, out JsonElement cf) && cf.ValueKind == JsonValueKind.String)
            {
                if (cf.ValueEquals("multi"u8))
                {
                    encodings[name] = new EncodingInfo("form", true, false, null);
                }
                else if (cf.ValueEquals("ssv"u8))
                {
                    encodings[name] = new EncodingInfo("spaceDelimited", false, false, null);
                }
                else if (cf.ValueEquals("tsv"u8))
                {
                    encodings[name] = new EncodingInfo("tabDelimited", false, false, null);
                }
                else if (cf.ValueEquals("pipes"u8))
                {
                    encodings[name] = new EncodingInfo("pipeDelimited", false, false, null);
                }
                else if (isArrayField)
                {
                    encodings[name] = new EncodingInfo("form", false, false, null);
                }
            }
            else if (isArrayField)
            {
                encodings[name] = new EncodingInfo("form", false, false, null);
            }
        }

        List<string> effectiveConsumes = GetEffectiveMediaTypes(operation, specRoot, "consumes"u8);
        bool wantsMultipart = anyFile;
        bool wantsUrlEncoded = false;

        foreach (string mediaType in effectiveConsumes)
        {
            if (CodeEmitHelpers.IsMultipartMediaType(mediaType))
            {
                wantsMultipart = true;
            }
            else if (CodeEmitHelpers.IsFormUrlEncodedMediaType(mediaType))
            {
                wantsUrlEncoded = true;
            }
        }

        if (!wantsMultipart && !wantsUrlEncoded)
        {
            wantsUrlEncoded = true;
        }

        if (ignoreEmptyFormUrlEncodedBody && !wantsMultipart && formDataParams.Count == 0)
        {
            return null;
        }

        string formBodyPointer = BuildFormBodyPositionalPointer(pathNameUtf8, method);
        IReadOnlyDictionary<string, EncodingInfo>? encodingMap = encodings.Count > 0 ? encodings : null;

        List<ContentInfo> formContent = [];
        if (wantsMultipart)
        {
            formContent.Add(new ContentInfo("multipart/form-data", formBodyPointer, encodingMap));
        }

        if (wantsUrlEncoded && !anyFile)
        {
            formContent.Add(new ContentInfo("application/x-www-form-urlencoded", formBodyPointer, encodingMap));
        }

        return new RequestBodyInfo(null, anyRequired, [.. formContent], [.. binaryProperties]);
    }

    /// <summary>
    /// Builds the synthesized draft-04-style object schema for an operation's formData
    /// parameters, shaped like the multipart schemas the emitter already understands
    /// (file fields become <c>type: string, format: binary</c> properties).
    /// </summary>
    private static string BuildFormBodySchemaJson(
        List<(OpenApiDocument.Parameter Parameter, int SourceIndex, bool IsPathLevel)> formDataParams)
    {
        var buffer = new System.Buffers.ArrayBufferWriter<byte>();
        using (var writer = new Utf8JsonWriter(buffer))
        {
            writer.WriteStartObject();
            writer.WriteString("type"u8, "object"u8);
            writer.WriteStartObject("properties"u8);

            List<string> required = [];

            foreach ((OpenApiDocument.Parameter param, int _, bool _) in formDataParams)
            {
                if (!((JsonElement)param).TryGetProperty("name"u8, out JsonElement nameEl) || nameEl.ValueKind != JsonValueKind.String)
                {
                    continue;
                }

                string name = nameEl.GetString()!;

                if (((JsonElement)param).TryGetProperty("required"u8, out JsonElement reqEl) && reqEl.ValueKind == JsonValueKind.True)
                {
                    required.Add(name);
                }

                writer.WritePropertyName(name);

                if (((JsonElement)param).TryGetProperty("type"u8, out JsonElement typeEl) && typeEl.ValueEquals("file"u8))
                {
                    writer.WriteStartObject();
                    writer.WriteString("type"u8, "string"u8);
                    writer.WriteString("format"u8, "binary"u8);
                    writer.WriteEndObject();
                    continue;
                }

                // Copy the schema-relevant keywords from the parameter object; the
                // parameter-specific fields (name, in, required, collectionFormat,
                // allowEmptyValue) are not schema keywords.
                writer.WriteStartObject();
                foreach (JsonProperty<JsonElement> prop in ((JsonElement)param).EnumerateObject())
                {
                    if (prop.NameEquals("name"u8)
                        || prop.NameEquals("in"u8)
                        || prop.NameEquals("required"u8)
                        || prop.NameEquals("collectionFormat"u8)
                        || prop.NameEquals("allowEmptyValue"u8)
                        || prop.NameEquals("description"u8))
                    {
                        continue;
                    }

                    prop.WriteTo(writer);
                }

                writer.WriteEndObject();
            }

            writer.WriteEndObject();

            if (required.Count > 0)
            {
                writer.WriteStartArray("required"u8);
                foreach (string name in required)
                {
                    writer.WriteStringValue(name);
                }

                writer.WriteEndArray();
            }

            writer.WriteEndObject();
        }

        return Encoding.UTF8.GetString(buffer.WrittenSpan);
    }

    private static ResponseInfo[] PrepareResponses(
        OpenApiDocument.Operation operation,
        JsonElement specRoot,
        ReadOnlySpan<byte> pathNameUtf8,
        OperationMethod method,
        IOpenApiReferenceResolver referenceResolver)
    {
        if (operation.ResponsesValue.IsUndefined())
        {
            return [];
        }

        List<string> produces = GetEffectiveMediaTypes(operation, specRoot, "produces"u8);

        List<ResponseInfo> result = [];

        foreach (var responseProp in operation.ResponsesValue.EnumerateObject())
        {
            if (responseProp.Value.IsUndefined())
            {
                continue;
            }

            if (!TryResolveResponse(
                responseProp.Value,
                referenceResolver,
                out OpenApiDocument.Response response,
                out IDisposable responseScope,
                out string? _))
            {
                ThrowHelper.ThrowUnableToResolveResponseRef();
            }

            using (responseScope)
            {
                // Extract status code at the emit boundary
                string statusCode = responseProp.Name;

                using UnescapedUtf8JsonString statusCodeUtf8 = responseProp.Utf8NameSpan;

                // A 2.0 response has a direct schema; the media types come from the
                // effective produces list (operation replaces root). type: file maps
                // to the raw-stream path via a schema-less content entry.
                ContentInfo[] content = [];
                if (response.Schema.IsNotUndefined())
                {
                    bool schemaIsFile = ((JsonElement)response.Schema).TryGetProperty("type"u8, out JsonElement schemaTypeEl)
                        && schemaTypeEl.ValueEquals("file"u8);

                    string? schemaPointer = schemaIsFile
                        ? null
                        : SchemaPointerBuilder.BuildResponseSchemaPointer(
                            "paths"u8, pathNameUtf8, method, statusCodeUtf8.Span);

                    List<string> mediaTypes = produces.Count > 0
                        ? produces
                        : [schemaIsFile ? "application/octet-stream" : "application/json"];

                    List<ContentInfo> entries = [];
                    foreach (string mediaType in mediaTypes)
                    {
                        string? pointerForMediaType = CodeEmitHelpers.IsRawStreamMediaType(mediaType) ? null : schemaPointer;
                        entries.Add(new ContentInfo(mediaType, pointerForMediaType, null));
                    }

                    content = [.. entries];
                }

                HeaderInfo[] headers = PrepareResponseHeaders(
                    response.HeadersValue, pathNameUtf8, method, statusCodeUtf8.Span);

                result.Add(new ResponseInfo(statusCode, content, headers, []));
            }
        }

        return [.. result];
    }

    private static HeaderInfo[] PrepareResponseHeaders(
        OpenApiDocument.Headers headersMap,
        ReadOnlySpan<byte> pathNameUtf8,
        OperationMethod method,
        ReadOnlySpan<byte> statusCodeUtf8)
    {
        if (headersMap.IsUndefined())
        {
            return [];
        }

        List<HeaderInfo> result = [];

        foreach (var headerProp in headersMap.EnumerateObject())
        {
            if (headerProp.Value.IsUndefined())
            {
                continue;
            }

            // 2.0 response headers are Header Objects (never $refs) whose constraint
            // keywords live directly on the header, so the Header Object is the schema.
            JsonElement headerEl = JsonElement.From(headerProp.Value);

            string? schemaPointer;
            {
                using UnescapedUtf8JsonString headerName = headerProp.Utf8NameSpan;
                schemaPointer = SchemaPointerBuilder.BuildResponseHeaderObjectPointer(
                    "paths"u8, pathNameUtf8, method, statusCodeUtf8, headerName.Span);
            }

            ParameterSerializationKind serializationKind = SchemaClassifier.Classify(headerEl);

            ParameterSerializationKind elementKind = serializationKind switch
            {
                ParameterSerializationKind.Array => SchemaClassifier.ClassifyArrayElement(headerEl),
                ParameterSerializationKind.Object => SchemaClassifier.ClassifyObjectValue(headerEl),
                _ => ParameterSerializationKind.String,
            };

            bool deepNesting = serializationKind is ParameterSerializationKind.Object or ParameterSerializationKind.Array
                && SchemaClassifier.HasDeepNesting(headerEl);

            // Extract header name at the emit boundary. 2.0 has no explode.
            string name = headerProp.Name;
            result.Add(new HeaderInfo(name, schemaPointer, Explode: false, serializationKind, elementKind, deepNesting));
        }

        return [.. result];
    }

