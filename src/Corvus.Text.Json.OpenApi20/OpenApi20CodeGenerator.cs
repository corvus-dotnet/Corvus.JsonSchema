    private static string GetMethodName(
        string? operationId,
        OperationMethod method,
        string pathTemplate)
    {
        if (operationId is not null)
        {
            return CodeEmitHelpers.ToPascalCase(operationId);
        }

        string methodPrefix = method switch
        {
            OperationMethod.Get => "get",
            OperationMethod.Put => "put",
            OperationMethod.Post => "post",
            OperationMethod.Delete => "delete",
            OperationMethod.Options => "options",
            OperationMethod.Head => "head",
            OperationMethod.Patch => "patch",
            OperationMethod.Trace => "trace",
            _ => throw new UnreachableException(),
        };

        string pathPart = pathTemplate
            .Replace("/", " ", StringComparison.Ordinal)
            .Replace("{", string.Empty, StringComparison.Ordinal)
            .Replace("}", string.Empty, StringComparison.Ordinal)
            .Trim();

        return CodeEmitHelpers.ToPascalCase(methodPrefix + " " + pathPart);
    }

    // ── Server info extraction ───────────────────────────────────────────
    // OpenAPI 2.0 has host + basePath + schemes rather than a servers array.
    private static ServerInfo? GetDefaultServerInfo(JsonElement specRoot)
    {
        return BuildServerInfo(specRoot, operationSchemes: default);
    }

    private static ServerInfo? BuildServerInfo(JsonElement specRoot, JsonElement operationSchemes)
    {
        if (specRoot.ValueKind != JsonValueKind.Object)
        {
            return null;
        }

        string? host = specRoot.TryGetProperty("host"u8, out JsonElement hostEl) && hostEl.ValueKind == JsonValueKind.String
            ? hostEl.GetString()
            : null;

        string basePath = specRoot.TryGetProperty("basePath"u8, out JsonElement basePathEl) && basePathEl.ValueKind == JsonValueKind.String
            ? basePathEl.GetString()!
            : string.Empty;

        if (host is null)
        {
            // No host: a bare basePath yields a relative server URL; nothing at all
            // yields no server (the caller must supply a base address).
            return basePath.Length > 0 ? new ServerInfo(basePath, []) : null;
        }

        JsonElement schemes = operationSchemes.ValueKind == JsonValueKind.Array
            ? operationSchemes
            : specRoot.TryGetProperty("schemes"u8, out JsonElement rootSchemes) ? rootSchemes : default;

        string scheme = PickScheme(schemes);
        return new ServerInfo($"{scheme}://{host}{basePath}", []);
    }

    private static string PickScheme(JsonElement schemes)
    {
        // Prefer https when several schemes are listed; default to https when none are.
        string? first = null;

        if (schemes.ValueKind == JsonValueKind.Array)
        {
            foreach (JsonElement scheme in schemes.EnumerateArray())
            {
                if (scheme.ValueKind != JsonValueKind.String)
                {
                    continue;
                }

                if (scheme.ValueEquals("https"u8))
                {
                    return "https";
                }

                first ??= scheme.GetString();
            }
        }

        return first ?? "https";
    }

    private static ServerInfo? ResolveEffectiveServer(
        OpenApiDocument.Operation operation,
        JsonElement specRoot,
        ServerInfo? rootServer)
    {
        // The only operation-level override in 2.0 is schemes.
        if (((JsonElement)operation).TryGetProperty("schemes"u8, out JsonElement opSchemes) && opSchemes.ValueKind == JsonValueKind.Array)
        {
            return BuildServerInfo(specRoot, opSchemes);
        }

        return rootServer;
    }

