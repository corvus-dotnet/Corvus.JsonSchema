        if (defaultResp is { } def)
        {
            if (named.Count > 0)
            {
                w.WriteLine("else");
                w.OpenBrace();
                EmitBodyValidation(w, def.AccessorName, "this.StatusCode", detailed);
                w.CloseBrace();
            }
            else
            {
                EmitBodyValidation(w, def.AccessorName, "this.StatusCode", detailed);
            }
        }
    }

