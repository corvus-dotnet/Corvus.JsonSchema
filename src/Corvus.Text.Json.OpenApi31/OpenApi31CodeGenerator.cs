/// <summary>
/// A self-contained code generator that walks the strongly-typed
/// <see cref="OpenApiDocument"/> model directly and emits C# source files.
/// </summary>
/// <remarks>
/// <para>
/// This replaces the multi-stage pipeline (Walker → Walked* → ClientModelBuilder →
/// Client* → ClientCodeEmitter) with a single class that:
/// <list type="number">
/// <item><description>Walks the typed model to collect operation data into lightweight internal records.</description></item>
/// <item><description>Emits C# source files from those records.</description></item>
/// </list>
/// </para>
/// <para>
/// All shared text utilities, scalar emission, and pointer construction are delegated
/// to <see cref="CodeEmitHelpers"/> and <see cref="SchemaPointerBuilder"/>.
/// </para>
/// </remarks>
public sealed class OpenApi31CodeGenerator
{
    private readonly string rootNamespace;
    private readonly string? clientNamePrefix;
    private readonly bool ignoreEmptyFormUrlEncodedBody;
    private readonly IModelTypeMap typeMap;

    /// <summary>
    /// Initializes a new instance of the <see cref="OpenApi31CodeGenerator"/> class.
    /// </summary>
    /// <param name="rootNamespace">The root namespace for generated code.</param>
    /// <param name="schemaTypeMap">
    /// A map from JSON pointer strings to fully qualified .NET type names
    /// generated by the V5 code generator. Every schema pointer discovered
    /// during the walk must have a corresponding entry.
    /// </param>
    /// <param name="clientNamePrefix">
    /// Optional prefix for client type names. If <see langword="null"/>,
    /// <c>"Api"</c> is used.
    /// </param>
    /// <param name="ignoreEmptyFormUrlEncodedBody">
    /// When <see langword="true"/>, form-urlencoded request bodies whose schema defines
    /// no properties are treated as if the body were absent.
    /// </param>
    /// <param name="contextSourceBodyPointers">
    /// The subset of <paramref name="schemaTypeMap"/> pointers whose type is an object or array — i.e. types for
    /// which the model generator emits a context-threaded <c>Source&lt;TContext&gt;</c>. A server result factory emits
    /// a closure-free, single-materialisation <c>Ok&lt;TContext&gt;</c> overload only for a response body in this set;
    /// a scalar body (no <c>Source&lt;TContext&gt;</c>) falls back to the non-generic factory. When <see langword="null"/>
    /// no generic overloads are emitted (the conservative default for client/model generation).
    /// </param>
    public OpenApi31CodeGenerator(
        string rootNamespace,
        IReadOnlyDictionary<string, string> schemaTypeMap,
        string? clientNamePrefix = null,
        bool ignoreEmptyFormUrlEncodedBody = false,
        IReadOnlySet<string>? contextSourceBodyPointers = null)
        : this(rootNamespace, new SchemaTypeMap(schemaTypeMap, contextSourceBodyPointers, "JsonElement"), clientNamePrefix, ignoreEmptyFormUrlEncodedBody)
    {
    }

    /// <summary>
    /// Initializes a new instance of the <see cref="OpenApi31CodeGenerator"/> class over a model type map.
    /// </summary>
    /// <param name="rootNamespace">The root namespace for generated types.</param>
    /// <param name="typeMap">The generated model types the client refers to, by schema pointer.</param>
    /// <param name="clientNamePrefix">The prefix for generated client type names, or <see langword="null"/> to derive one from the API title.</param>
    /// <param name="ignoreEmptyFormUrlEncodedBody">Whether a form-urlencoded request body whose schema defines no properties is treated as absent.</param>
    public OpenApi31CodeGenerator(
        string rootNamespace,
        IModelTypeMap typeMap,
        string? clientNamePrefix = null,
        bool ignoreEmptyFormUrlEncodedBody = false)
    {
        this.rootNamespace = rootNamespace;
        this.typeMap = typeMap;
        this.clientNamePrefix = clientNamePrefix;
        this.ignoreEmptyFormUrlEncodedBody = ignoreEmptyFormUrlEncodedBody;
    }

    // ── Walk-phase reference (typed model objects, no strings extracted) ──
    private readonly record struct OperationRef(
        JsonProperty<OpenApiDocument.PathItem> PathProp,
        OpenApiDocument.Operation Operation,
        OperationMethod Method,
        OpenApiDocument.PathItem PathItem);

    /// <summary>
    /// Walks the OpenAPI 3.1 specification and collects all schema
    /// JSON Pointer strings reachable from the selected operations.
    /// </summary>
    /// <param name="specRoot">The root element of the parsed spec document.</param>
    /// <param name="filter">Optional operation filter.</param>
    /// <param name="referenceResolver">
    /// Optional reference resolver. If <see langword="null"/>,
    /// a <see cref="LocalReferenceResolver"/> is used.
    /// </param>
    /// <returns>An array of JSON Pointer strings.</returns>
    public static SchemaReference[] CollectSchemaPointers(
        JsonElement specRoot,
        out Dictionary<string, string> parameterNames,
        OperationFilter? filter = null,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        referenceResolver ??= new LocalReferenceResolver(specRoot);
        OpenApiDocument doc = specRoot;

        if (doc.PathsValue.IsUndefined())
        {
            parameterNames = new Dictionary<string, string>();
            return [];
        }

        List<SchemaReference> pointers = [];
        Dictionary<string, string> paramNames = new(StringComparer.Ordinal);

        foreach (JsonProperty<OpenApiDocument.PathItem> pathProp in doc.PathsValue.EnumerateObject())
        {
            if (filter is not null)
            {
                using UnescapedUtf16JsonString name = pathProp.Utf16NameSpan;
                if (!filter.Matches(name.Span))
                {
                    continue;
                }
            }

            CollectPathItemPointers(pathProp, pointers, paramNames, referenceResolver, "paths"u8);
        }

        parameterNames = paramNames;
        return [.. pointers];
    }

    /// <summary>
    /// Lists all operations in the OpenAPI 3.1 specification, optionally filtered.
    /// </summary>
    /// <param name="specRoot">The root element of the parsed spec document.</param>
    /// <param name="filter">Optional operation filter.</param>
    /// <returns>An array of <see cref="OperationSummary"/> records.</returns>
    public static OperationSummary[] ListOperations(
        JsonElement specRoot,
        OperationFilter? filter = null)
    {
        List<OperationSummary> result = [];

        foreach (OperationRef opRef in WalkOperationRefs(specRoot, filter))
        {
            using UnescapedUtf16JsonString pathName = opRef.PathProp.Utf16NameSpan;
            string path = pathName.Span.ToString();

            string? operationId = opRef.Operation.OperationId.IsNotUndefined()
                ? opRef.Operation.OperationId.GetString()
                : null;

            string? summary = opRef.Operation.Summary.IsNotUndefined()
                ? opRef.Operation.Summary.GetString()
                : null;

            bool isDeprecated = opRef.Operation.Deprecated.ValueKind == JsonValueKind.True;

            List<string> tags = [];
            if (opRef.Operation.Tags.IsNotUndefined())
            {
                foreach (var tag in opRef.Operation.Tags.EnumerateArray())
                {
                    if (tag.ValueKind == JsonValueKind.String)
                    {
                        tags.Add(tag.GetString()!);
                    }
                }
            }

            int paramCount = 0;
            if (opRef.Operation.Parameters.IsNotUndefined())
            {
                foreach (var param in opRef.Operation.Parameters.EnumerateArray())
                {
                    _ = param;
                    paramCount++;
                }
            }

            // Also count path-level parameters
            if (opRef.PathItem.Parameters.IsNotUndefined())
            {
                foreach (var param in opRef.PathItem.Parameters.EnumerateArray())
                {
                    _ = param;
                    paramCount++;
                }
            }

            bool hasBody = opRef.Operation.RequestBody.IsNotUndefined();

            string methodName = CodeEmitHelpers.GetMethodName(operationId, opRef.Method, path);
            result.Add(new OperationSummary(
                path,
                opRef.Method,
                operationId,
                [.. tags],
                isDeprecated,
                paramCount,
                hasBody,
                summary,
                methodName,
                GeneratedClientTypeNaming.RequestTypeName(methodName),
                GeneratedClientTypeNaming.ResponseTypeName(methodName)));
        }

        return [.. result];
    }

    /// <summary>
    /// Lists all tags defined in the top-level <c>tags</c> array of an OpenAPI 3.1 specification.
    /// </summary>
    /// <remarks>
    /// The <c>parent</c> and <c>kind</c> fields are new in OpenAPI 3.2, but this method will
    /// still read them if present (e.g. from extension usage in 3.1 specs).
    /// </remarks>
    /// <param name="specRoot">The root element of the parsed spec document.</param>
    /// <returns>An array of <see cref="TagInfo"/> records.</returns>
    public static TagInfo[] ListTags(JsonElement specRoot)
    {
        if (!specRoot.TryGetProperty("tags"u8, out JsonElement tagsElement)
            || tagsElement.ValueKind != JsonValueKind.Array)
        {
            return [];
        }

        List<TagInfo> result = [];
        foreach (JsonElement tag in tagsElement.EnumerateArray())
        {
            if (tag.ValueKind != JsonValueKind.Object)
            {
                continue;
            }

            string? name = tag.TryGetProperty("name"u8, out JsonElement nameEl) && nameEl.ValueKind == JsonValueKind.String
                ? nameEl.GetString()
                : null;

            if (name is null)
            {
                continue;
            }

            string? summary = tag.TryGetProperty("summary"u8, out JsonElement summaryEl) && summaryEl.ValueKind == JsonValueKind.String
                ? summaryEl.GetString()
                : null;

            string? description = tag.TryGetProperty("description"u8, out JsonElement descEl) && descEl.ValueKind == JsonValueKind.String
                ? descEl.GetString()
                : null;

            string? parent = tag.TryGetProperty("parent"u8, out JsonElement parentEl) && parentEl.ValueKind == JsonValueKind.String
                ? parentEl.GetString()
                : null;

            string? kind = tag.TryGetProperty("kind"u8, out JsonElement kindEl) && kindEl.ValueKind == JsonValueKind.String
                ? kindEl.GetString()
                : null;

            result.Add(new TagInfo(name, summary, description, parent, kind));
        }

        return [.. result];
    }

    /// <summary>
    /// Prepares the operations of a specification for emission: the language-neutral operation model every client
    /// emitter consumes.
    /// </summary>
    /// <param name="specRoot">The root element of the OpenAPI document.</param>
    /// <param name="scope">Whether to prepare the <c>paths</c> operations or the webhook and callback operations.</param>
    /// <param name="filter">An optional operation filter.</param>
    /// <param name="referenceResolver">An optional reference resolver; defaults to a local resolver over <paramref name="specRoot"/>.</param>
    /// <returns>The prepared model.</returns>
    public OpenApiClientModel PrepareOperations(
        JsonElement specRoot,
        OperationScope scope,
        OperationFilter? filter = null,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        referenceResolver ??= new LocalReferenceResolver(specRoot);
        ServerInfo? rootServer = GetDefaultServerInfo(specRoot);
        List<OperationInfo> operations = [];
        IEnumerable<OperationRef> operationRefs = scope == OperationScope.Paths
            ? WalkOperationRefs(specRoot, filter, referenceResolver)
            : WalkWebhookAndCallbackOperationRefs(specRoot, filter, referenceResolver);

        foreach (OperationRef opRef in operationRefs)
        {
            operations.Add(PrepareOperation(opRef, referenceResolver, rootServer, specRoot));
        }

        SpecificationInfoReader.Read(specRoot, out string? title, out string? apiVersion);
        return new OpenApiClientModel("3.1", title, apiVersion, null, rootServer, SecuritySchemeReader.ReadOpenApi3(specRoot), [.. operations]);
    }

    /// <summary>
    /// Walks the OpenAPI 3.1 specification and emits C# source files.
    /// </summary>
    /// <param name="specRoot">The root element of the parsed spec document.</param>
    /// <param name="filter">Optional operation filter.</param>
    /// <param name="referenceResolver">
    /// Optional reference resolver. If <see langword="null"/>,
    /// a <see cref="LocalReferenceResolver"/> is used.
    /// </param>
    /// <returns>The generated source files.</returns>
    public IReadOnlyList<GeneratedFile> Generate(
        JsonElement specRoot,
        OperationFilter? filter = null,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        OpenApiClientModel model = this.PrepareOperations(specRoot, OperationScope.Paths, filter, referenceResolver);
        return this.EmitClientFiles(in model);
    }

    private IReadOnlyList<GeneratedFile> EmitClientFiles(in OpenApiClientModel model)
        => new CSharpClientEmitter().EmitClient(in model, this.typeMap, new ClientEmitOptions(this.rootNamespace, this.clientNamePrefix));

    /// <summary>
    /// Describes every operation for downstream generators: its identity, the generated
    /// request/response type names, and the request parameters — the authoritative mapping the
    /// generator emits, so callers never re-derive the naming or type convention.
    /// </summary>
    /// <param name="specRoot">The root element of the parsed spec document.</param>
    /// <param name="filter">Optional operation filter.</param>
    /// <param name="referenceResolver">
    /// Optional reference resolver. If <see langword="null"/>, a <see cref="LocalReferenceResolver"/> is used.
    /// </param>
    /// <returns>The operation descriptors.</returns>
    public IReadOnlyList<OperationDescriptor> DescribeOperations(
        JsonElement specRoot,
        OperationFilter? filter = null,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        referenceResolver ??= new LocalReferenceResolver(specRoot);
        ServerInfo? rootServer = GetDefaultServerInfo(specRoot);
        List<OperationDescriptor> result = [];

        foreach (OperationRef opRef in WalkOperationRefs(specRoot, filter, referenceResolver))
        {
            OperationInfo op = PrepareOperation(opRef, referenceResolver, rootServer, specRoot);

            var parameters = new RequestParameterInfo[op.Parameters.Length];
            for (int i = 0; i < op.Parameters.Length; i++)
            {
                ParameterInfo parameter = op.Parameters[i];
                parameters[i] = new RequestParameterInfo(
                    parameter.Name,
                    parameter.Location,
                    CodeEmitHelpers.SanitizeIdentifier(parameter.Name),
                    this.GetParameterTypeName(parameter),
                    parameter.IsRequired,
                    CodeEmitHelpers.EscapeCSharpKeyword(CodeEmitHelpers.SanitizeParameterName(parameter.Name)));
            }

            var responses = new ResponseDescriptor[op.Responses.Length];
            for (int r = 0; r < op.Responses.Length; r++)
            {
                ResponseInfo response = op.Responses[r];
                string? bodyTypeName = this.ResolveResponseTypeName(response);
                responses[r] = new ResponseDescriptor(
                    response.StatusCode,
                    bodyTypeName,
                    bodyTypeName is null ? null : CodeEmitHelpers.ResponseBodyPropertyName(response.StatusCode));
            }

            ResponseHeaderInfo[] responseHeaders = this.DescribeResponseHeaders(op.Responses);

            string clientTag = op.Tags.Length > 0 ? op.Tags[0] : "default";
            string? requestBodyTypeName = op.RequestBody is { } rb && !IsRawStreamRequestBody(rb)
                ? this.ResolveRequestBodyTypeName(rb)
                : null;

            result.Add(new OperationDescriptor(
                op.PathTemplate,
                op.Method,
                op.OperationId,
                op.CSharpMethodName(),
                $"{this.rootNamespace}.{GeneratedClientTypeNaming.RequestTypeName(op.CSharpMethodName())}",
                $"{this.rootNamespace}.{GeneratedClientTypeNaming.ResponseTypeName(op.CSharpMethodName())}",
                parameters,
                op.RequestBody is not null,
                responses,
                $"{this.rootNamespace}.{this.GetClientName(clientTag)}Client",
                $"{op.CSharpMethodName()}Async",
                requestBodyTypeName,
                responseHeaders));
        }

        return result;
    }

    /// <summary>
    /// Describes the response headers an operation declares — mirroring the client emitter's response header properties and their
    /// naming and typing so a caller can resolve <c>$response.header.&lt;name&gt;</c> against the generated
    /// response property. Deduplicated by generated property name across all responses.
    /// </summary>
    /// <param name="responses">The operation's responses.</param>
    /// <returns>The described response headers.</returns>
    private ResponseHeaderInfo[] DescribeResponseHeaders(ResponseInfo[] responses)
    {
        var headers = new List<ResponseHeaderInfo>();
        var seen = new HashSet<string>(StringComparer.Ordinal);

        foreach (ResponseInfo response in responses)
        {
            foreach (HeaderInfo header in response.Headers)
            {
                string propertyName = CodeEmitHelpers.HeaderNameToPropertyName(header.HeaderName) + "Header";
                if (!seen.Add(propertyName))
                {
                    continue;
                }

                bool isString = header.SchemaPointer is null;
                string typeName = isString ? "string" : this.ResolveSchemaTypeName(header.SchemaPointer);
                headers.Add(new ResponseHeaderInfo(header.HeaderName, propertyName, typeName, isString));
            }
        }

        return [.. headers];
    }

    // ═══════════════════════════════════════════════════════════════════
    // Schema pointer collection — walks typed model directly
    // ═══════════════════════════════════════════════════════════════════
    private static void CollectPathItemPointers(
        JsonProperty<OpenApiDocument.PathItem> pathProp,
        List<SchemaReference> pointers,
        Dictionary<string, string> parameterNames,
        IOpenApiReferenceResolver referenceResolver,
        ReadOnlySpan<byte> rootSegmentUtf8,
        string? callbackPathItemRef = null)
    {
        OpenApiDocument.PathItem pathItem = pathProp.Value;

        // Determine if this path item is a $ref and compute its absolute reference
        string? pathItemRefValue = callbackPathItemRef;
        if (pathItemRefValue is null)
        {
            OpenApiDocument.Reference asRef = OpenApiDocument.Reference.From(pathItem);
            if (asRef.Ref.IsNotUndefined())
            {
                string refStr = asRef.Ref.GetString()!;
                pathItemRefValue = referenceResolver.ResolveToAbsolute(refStr);
            }
        }

        if (!TryResolvePathItem(pathItem, referenceResolver, out OpenApiDocument.PathItem resolved, out IDisposable pathItemScope))
        {
            return;
        }

        using (pathItemScope)
        {
            if (resolved.Get.IsNotUndefined())
            {
                CollectOperationPointers(pathProp, resolved.Get, OperationMethod.Get, resolved, pointers, parameterNames, referenceResolver, rootSegmentUtf8, pathItemRefValue);
            }

            if (resolved.Put.IsNotUndefined())
            {
                CollectOperationPointers(pathProp, resolved.Put, OperationMethod.Put, resolved, pointers, parameterNames, referenceResolver, rootSegmentUtf8, pathItemRefValue);
            }

            if (resolved.Post.IsNotUndefined())
            {
                CollectOperationPointers(pathProp, resolved.Post, OperationMethod.Post, resolved, pointers, parameterNames, referenceResolver, rootSegmentUtf8, pathItemRefValue);
            }

            if (resolved.Delete.IsNotUndefined())
            {
                CollectOperationPointers(pathProp, resolved.Delete, OperationMethod.Delete, resolved, pointers, parameterNames, referenceResolver, rootSegmentUtf8, pathItemRefValue);
            }

            if (resolved.Options.IsNotUndefined())
            {
                CollectOperationPointers(pathProp, resolved.Options, OperationMethod.Options, resolved, pointers, parameterNames, referenceResolver, rootSegmentUtf8, pathItemRefValue);
            }

            if (resolved.Head.IsNotUndefined())
            {
                CollectOperationPointers(pathProp, resolved.Head, OperationMethod.Head, resolved, pointers, parameterNames, referenceResolver, rootSegmentUtf8, pathItemRefValue);
            }

            if (resolved.Patch.IsNotUndefined())
            {
                CollectOperationPointers(pathProp, resolved.Patch, OperationMethod.Patch, resolved, pointers, parameterNames, referenceResolver, rootSegmentUtf8, pathItemRefValue);
            }

            if (resolved.Trace.IsNotUndefined())
            {
                CollectOperationPointers(pathProp, resolved.Trace, OperationMethod.Trace, resolved, pointers, parameterNames, referenceResolver, rootSegmentUtf8, pathItemRefValue);
            }
        }
    }

    private static void CollectOperationPointers(
        JsonProperty<OpenApiDocument.PathItem> pathProp,
        OpenApiDocument.Operation operation,
        OperationMethod method,
        OpenApiDocument.PathItem pathItem,
        List<SchemaReference> pointers,
        Dictionary<string, string> parameterNames,
        IOpenApiReferenceResolver referenceResolver,
        ReadOnlySpan<byte> rootSegmentUtf8,
        string? pathItemRefValue = null)
    {
        using UnescapedUtf8JsonString pathName = pathProp.Utf8NameSpan;

        // Parameter schema pointers (with path/operation merge)
        foreach ((OpenApiDocument.Parameter param, int sourceIndex, bool isPathLevel, string? refValue) in
            MergeParameters(operation, pathItem, referenceResolver))
        {
            if (param.SchemaValue.IsNotUndefined())
            {
                string positionalPointer = SchemaPointerBuilder.BuildParameterSchemaPointer(
                    rootSegmentUtf8, pathName.Span, method, sourceIndex, isPathLevel);

                string resolvablePointer = refValue is not null
                    ? SchemaPointerBuilder.BuildRefBasedPointer(refValue, "/schema")
                    : pathItemRefValue is not null
                        ? SchemaPointerBuilder.BuildRefBasedPointer(pathItemRefValue, SchemaPointerBuilder.BuildParameterSubPath(method, sourceIndex, isPathLevel))
                        : positionalPointer;

                pointers.Add(new SchemaReference(positionalPointer, resolvablePointer));

                // Record the parameter name keyed by fragment (pointer without '#')
                // so the heuristic can look it up from reference.Fragment without allocating.
                if (param.Name.IsNotUndefined())
                {
                    string? name = param.Name.GetString();
                    if (name is not null)
                    {
                        parameterNames[positionalPointer.AsSpan(1).ToString()] = name;
                    }
                }
            }
        }

        // Request body content schema pointers
        if (operation.RequestBody.IsNotUndefined()
            && TryResolveRequestBody(operation.RequestBody, referenceResolver, out OpenApiDocument.RequestBody requestBody, out IDisposable rbScope, out string? rbRefValue)
            && requestBody.ContentValue.IsNotUndefined())
        {
            using (rbScope)
            {
                foreach (var mediaTypeProp in requestBody.ContentValue.EnumerateObject())
                {
                    if (mediaTypeProp.Value.SchemaValue.IsNotUndefined())
                    {
                        using UnescapedUtf8JsonString mediaTypeName = mediaTypeProp.Utf8NameSpan;

                        // Skip raw stream content types — no JSON Schema type needed.
                        if (CodeEmitHelpers.IsRawStreamMediaType(mediaTypeProp.Name))
                        {
                            continue;
                        }

                        string positionalPointer = SchemaPointerBuilder.BuildContentSchemaPointer(
                            rootSegmentUtf8, pathName.Span, method, "/requestBody"u8, mediaTypeName.Span);

                        string resolvablePointer = rbRefValue is not null
                            ? SchemaPointerBuilder.BuildRefBasedPointer(
                                rbRefValue, SchemaPointerBuilder.BuildContentSubPath(mediaTypeName.Span))
                            : pathItemRefValue is not null
                                ? SchemaPointerBuilder.BuildRefBasedPointer(
                                    pathItemRefValue, SchemaPointerBuilder.BuildRequestBodyContentSubPath(method, mediaTypeName.Span))
                                : positionalPointer;

                        pointers.Add(new SchemaReference(positionalPointer, resolvablePointer));
                    }
                }
            }
        }

        // Response content and header schema pointers
        if (operation.ResponsesValue.IsNotUndefined())
        {
            foreach (var responseProp in operation.ResponsesValue.EnumerateObject())
            {
                if (responseProp.Value.IsUndefined())
                {
                    continue;
                }

                if (!TryResolveResponse(responseProp.Value, referenceResolver, out OpenApiDocument.Response response, out IDisposable responseScope, out string? responseRefValue))
                {
                    continue;
                }

                using (responseScope)
                {
                    using UnescapedUtf8JsonString statusCode = responseProp.Utf8NameSpan;

                    if (response.ContentValue.IsNotUndefined())
                    {
                        foreach (var mediaTypeProp in response.ContentValue.EnumerateObject())
                        {
                            if (mediaTypeProp.Value.SchemaValue.IsNotUndefined())
                            {
                                // Skip raw stream content types — no JSON Schema type needed.
                                if (CodeEmitHelpers.IsRawStreamMediaType(mediaTypeProp.Name))
                                {
                                    continue;
                                }

                                using UnescapedUtf8JsonString mediaTypeName = mediaTypeProp.Utf8NameSpan;

                                string positionalPointer = SchemaPointerBuilder.BuildResponseContentSchemaPointer(
                                    rootSegmentUtf8, pathName.Span, method, statusCode.Span, mediaTypeName.Span);

                                string resolvablePointer = responseRefValue is not null
                                    ? SchemaPointerBuilder.BuildRefBasedPointer(
                                        responseRefValue, SchemaPointerBuilder.BuildContentSubPath(mediaTypeName.Span))
                                    : pathItemRefValue is not null
                                        ? SchemaPointerBuilder.BuildRefBasedPointer(
                                            pathItemRefValue, SchemaPointerBuilder.BuildResponseContentSubPath(method, statusCode.Span, mediaTypeName.Span))
                                        : positionalPointer;

                                pointers.Add(new SchemaReference(positionalPointer, resolvablePointer));
                            }
                        }
                    }

                    if (response.Headers.IsNotUndefined())
                    {
                        foreach (var headerProp in response.Headers.EnumerateObject())
                        {
                            if (headerProp.Value.IsUndefined())
                            {
                                continue;
                            }

                            if (!TryResolveHeader(headerProp.Value, referenceResolver, out OpenApiDocument.Header header, out IDisposable headerScope, out string? headerRefValue))
                            {
                                continue;
                            }

                            using (headerScope)
                            {
                                if (header.SchemaValue.IsNotUndefined())
                                {
                                    using UnescapedUtf8JsonString headerName = headerProp.Utf8NameSpan;

                                    string positionalPointer = SchemaPointerBuilder.BuildResponseHeaderSchemaPointer(
                                        rootSegmentUtf8, pathName.Span, method, statusCode.Span, headerName.Span);

                                    string resolvablePointer = headerRefValue is not null
                                        ? SchemaPointerBuilder.BuildRefBasedPointer(headerRefValue, "/schema")
                                        : responseRefValue is not null
                                            ? SchemaPointerBuilder.BuildRefBasedPointer(
                                                responseRefValue, SchemaPointerBuilder.BuildHeaderSubPath(headerName.Span))
                                            : pathItemRefValue is not null
                                                ? SchemaPointerBuilder.BuildRefBasedPointer(
                                                    pathItemRefValue, SchemaPointerBuilder.BuildResponseHeaderSubPath(method, statusCode.Span, headerName.Span))
                                                : positionalPointer;

                                    pointers.Add(new SchemaReference(positionalPointer, resolvablePointer));
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    // ═══════════════════════════════════════════════════════════════════
    // Walk logic — yields typed model references
    // ═══════════════════════════════════════════════════════════════════
    private static IEnumerable<OperationRef> WalkOperationRefs(
        JsonElement specRoot,
        OperationFilter? filter,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        OpenApiDocument doc = specRoot;

        if (doc.PathsValue.IsUndefined())
        {
            yield break;
        }

        referenceResolver ??= new LocalReferenceResolver(specRoot);

        foreach (JsonProperty<OpenApiDocument.PathItem> pathProp in doc.PathsValue.EnumerateObject())
        {
            if (filter is not null)
            {
                using UnescapedUtf16JsonString name = pathProp.Utf16NameSpan;
                if (!filter.Matches(name.Span))
                {
                    continue;
                }
            }

            foreach (OperationRef entry in WalkPathItemRefs(pathProp, referenceResolver))
            {
                yield return entry;
            }
        }
    }

    private static IEnumerable<OperationRef> WalkPathItemRefs(
        JsonProperty<OpenApiDocument.PathItem> pathProp,
        IOpenApiReferenceResolver referenceResolver)
    {
        OpenApiDocument.PathItem pathItem = pathProp.Value;

        if (!TryResolvePathItem(pathItem, referenceResolver, out OpenApiDocument.PathItem resolved, out IDisposable pathItemScope))
        {
            yield break;
        }

        using (pathItemScope)
        {
            if (resolved.Get.IsNotUndefined())
            {
                yield return new OperationRef(pathProp, resolved.Get, OperationMethod.Get, resolved);
            }

            if (resolved.Put.IsNotUndefined())
            {
                yield return new OperationRef(pathProp, resolved.Put, OperationMethod.Put, resolved);
            }

            if (resolved.Post.IsNotUndefined())
            {
                yield return new OperationRef(pathProp, resolved.Post, OperationMethod.Post, resolved);
            }

            if (resolved.Delete.IsNotUndefined())
            {
                yield return new OperationRef(pathProp, resolved.Delete, OperationMethod.Delete, resolved);
            }

            if (resolved.Options.IsNotUndefined())
            {
                yield return new OperationRef(pathProp, resolved.Options, OperationMethod.Options, resolved);
            }

            if (resolved.Head.IsNotUndefined())
            {
                yield return new OperationRef(pathProp, resolved.Head, OperationMethod.Head, resolved);
            }

            if (resolved.Patch.IsNotUndefined())
            {
                yield return new OperationRef(pathProp, resolved.Patch, OperationMethod.Patch, resolved);
            }

            if (resolved.Trace.IsNotUndefined())
            {
                yield return new OperationRef(pathProp, resolved.Trace, OperationMethod.Trace, resolved);
            }
        }
    }

    private static IEnumerable<OperationRef> WalkWebhookOperationRefs(
        JsonElement specRoot,
        OperationFilter? filter,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        OpenApiDocument doc = specRoot;

        if (doc.Webhooks.IsUndefined())
        {
            yield break;
        }

        referenceResolver ??= new LocalReferenceResolver(specRoot);

        foreach (JsonProperty<OpenApiDocument.PathItem> webhookProp in doc.Webhooks.EnumerateObject())
        {
            if (filter is not null)
            {
                using UnescapedUtf16JsonString name = webhookProp.Utf16NameSpan;
                if (!filter.Matches(name.Span))
                {
                    continue;
                }
            }

            foreach (OperationRef entry in WalkPathItemRefs(webhookProp, referenceResolver))
            {
                yield return entry;
            }
        }
    }

    private static IEnumerable<OperationRef> WalkCallbackOperationRefs(
        JsonElement specRoot,
        OperationFilter? filter,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        OpenApiDocument doc = specRoot;

        if (doc.PathsValue.IsUndefined())
        {
            yield break;
        }

        referenceResolver ??= new LocalReferenceResolver(specRoot);

        // Walk each operation in paths and check for callbacks
        foreach (JsonProperty<OpenApiDocument.PathItem> pathProp in doc.PathsValue.EnumerateObject())
        {
            OpenApiDocument.PathItem pathItem = pathProp.Value;

            if (!TryResolvePathItem(pathItem, referenceResolver, out OpenApiDocument.PathItem resolved, out IDisposable pathItemScope))
            {
                continue;
            }

            using (pathItemScope)
            {
                foreach (OpenApiDocument.Operation operation in EnumerateOperationsInPathItem(resolved))
                {
                    OpenApiDocument.Operation.CallbacksEntity callbacks = operation.Callbacks;
                    if (callbacks.IsUndefined())
                    {
                        continue;
                    }

                    foreach (JsonProperty<OpenApiDocument.CallbacksOrReference> callbackProp in callbacks.EnumerateObject())
                    {
                        // Resolve the callbacks-or-reference
                        OpenApiDocument.Callbacks? resolvedCallbacks = ResolveCallbacksOrReference(callbackProp.Value, referenceResolver);
                        if (resolvedCallbacks is null)
                        {
                            continue;
                        }

                        // Each property in the Callbacks object is a runtime-expression → path-item
                        foreach (JsonProperty<OpenApiDocument.PathItem> callbackPathProp in resolvedCallbacks.Value.EnumerateObject())
                        {
                            if (filter is not null)
                            {
                                using UnescapedUtf16JsonString name = callbackPathProp.Utf16NameSpan;
                                if (!filter.Matches(name.Span))
                                {
                                    continue;
                                }
                            }

                            foreach (OperationRef entry in WalkPathItemRefs(callbackPathProp, referenceResolver))
                            {
                                yield return entry;
                            }
                        }
                    }
                }
            }
        }
    }

    private static IEnumerable<OperationRef> WalkWebhookAndCallbackOperationRefs(
        JsonElement specRoot,
        OperationFilter? filter,
        IOpenApiReferenceResolver? referenceResolver = null)
    {
        referenceResolver ??= new LocalReferenceResolver(specRoot);

        foreach (OperationRef opRef in WalkWebhookOperationRefs(specRoot, filter, referenceResolver))
        {
            yield return opRef;
        }

        foreach (OperationRef opRef in WalkCallbackOperationRefs(specRoot, filter, referenceResolver))
        {
            yield return opRef;
        }
    }

