        string sanitized = CodeEmitHelpers.SanitizeIdentifier(tag);
        return $"{prefix}{sanitized}";
    }

    private GeneratedFile EmitServerHandlerInterface(
        string handlerName,
        IReadOnlyList<OperationInfo> operations)
    {
        string interfaceName = $"I{handlerName}Handler";
        IndentedWriter w = new();

        CodeEmitHelpers.EmitHeader(w);
        w.WriteLine($"namespace {this.rootNamespace};");
        w.WriteLine();

        w.WriteLine("/// <summary>");
        w.WriteLine($"/// Handler interface for {handlerName} API operations.");
        w.WriteLine("/// Implement this interface to provide the server-side logic.");
        w.WriteLine("/// </summary>");
        w.WriteLine($"public interface {interfaceName}");
        w.OpenBrace();

        for (int i = 0; i < operations.Count; i++)
        {
            if (i > 0)
            {
                w.WriteLine();
            }

            OperationInfo op = operations[i];
            string paramsName = $"{op.CSharpMethodName()}Params";
            string resultName = $"{op.CSharpMethodName()}Result";

            w.WriteLine("/// <summary>");
            string httpMethod = op.Method.ToString().ToUpperInvariant();
            string summary = op.Summary is not null
                ? $"Handles {httpMethod} {op.PathTemplate} \u2014 {CodeEmitHelpers.EscapeXml(op.Summary)}"
                : $"Handles {httpMethod} {op.PathTemplate}.";
            w.WriteLine($"/// {summary}");
            w.WriteLine("/// </summary>");
            w.WriteLine($"/// <param name=\"parameters\">The operation parameters.</param>");
            w.WriteLine($"/// <param name=\"workspace\">The workspace for building response values.</param>");
            w.WriteLine($"/// <param name=\"cancellationToken\">A cancellation token.</param>");
            w.WriteLine($"/// <returns>The operation result.</returns>");

            if (op.IsDeprecated)
            {
                w.WriteLine("[Obsolete(\"This operation is deprecated.\")]");
            }

            w.WriteLine(
                $"ValueTask<{resultName}> Handle{op.CSharpMethodName()}Async({paramsName} parameters, JsonWorkspace workspace, CancellationToken cancellationToken = default);");
        }

        w.CloseBrace();

        return new GeneratedFile($"{interfaceName}.cs", w.ToString());
    }

    private GeneratedFile EmitServerOperationParams(OperationInfo op)
    {
        string structName = $"{op.CSharpMethodName()}Params";
        IndentedWriter w = new();

        CodeEmitHelpers.EmitHeader(w);
        w.WriteLine($"namespace {this.rootNamespace};");
        w.WriteLine();

        w.WriteLine("/// <summary>");
        w.WriteLine($"/// Parameters for the {op.CSharpMethodName()} operation ({op.Method.ToString().ToUpperInvariant()} {op.PathTemplate}).");
        w.WriteLine("/// </summary>");

        string? remarks = op.Description ?? op.Summary;
        if (remarks is not null)
        {
            w.WriteLine($"/// <remarks>{CodeEmitHelpers.EscapeXml(remarks)}</remarks>");
        }

        w.WriteLine($"public readonly struct {structName}");
        w.OpenBrace();

        foreach (ParameterInfo param in op.Parameters)
        {
            string fieldName = CodeEmitHelpers.SanitizeIdentifier(param.Name);
            string typeName = this.GetParameterTypeName(param);

            w.WriteLine();
            w.WriteLine("/// <summary>");
            w.WriteLine($"/// Gets the '{param.Name}' {param.Location.ToString().ToLowerInvariant()} parameter.");
            w.WriteLine("/// </summary>");
            w.WriteLine($"public {typeName} {fieldName} {{ get; init; }}");
        }

        if (op.RequestBody is { } rb)
        {
            bool isRawStream = IsRawStreamRequestBody(rb);
            string bodyTypeName = isRawStream ? "System.IO.Stream" : this.ResolveRequestBodyTypeName(rb);
            w.WriteLine();
            w.WriteLine("/// <summary>");
            string bodyDesc = rb.Description ?? "Gets the request body.";
            w.WriteLine($"/// {CodeEmitHelpers.EscapeXml(bodyDesc)}");
            w.WriteLine("/// </summary>");
            w.WriteLine($"public {bodyTypeName} Body {{ get; init; }}");

            // For multipart/form-data bodies with format:binary parts, expose each binary part
            // as a separate ReadOnlyMemory<byte> property so the handler can read the raw bytes.
            if (IsMultipartRequestBody(rb))
            {
                foreach (BinaryPropertyInfo binaryProp in rb.BinaryProperties)
                {
                    w.WriteLine();
                    w.WriteLine("/// <summary>");
                    w.WriteLine($"/// Gets the binary content of the '{binaryProp.PropertyName}' part.");
                    w.WriteLine("/// </summary>");
                    w.WriteLine($"public ReadOnlyMemory<byte> {CodeEmitHelpers.ToPascalCase(binaryProp.PropertyName)} {{ get; init; }}");
                }
            }
        }

        w.CloseBrace();

        return new GeneratedFile($"{structName}.cs", w.ToString());
    }

    private GeneratedFile EmitServerOperationResult(OperationInfo op)
    {
        string structName = $"{op.CSharpMethodName()}Result";
        IndentedWriter w = new();

        CodeEmitHelpers.EmitHeader(w);
        w.WriteLine("using System;");
        w.WriteLine("using System.IO;");
        w.WriteLine("using System.Threading;");
        w.WriteLine("using System.Threading.Tasks;");
        w.WriteLine();
        w.WriteLine($"namespace {this.rootNamespace};");
        w.WriteLine();

        // Collect all distinct response headers across all responses.
        List<(HeaderInfo Header, string TypeName, string FieldName, string PropertyName)> allHeaders = [];
        HashSet<string> emittedHeaderNames = [];
        foreach (ResponseInfo resp in op.Responses)
        {
            foreach (HeaderInfo header in resp.Headers)
            {
                if (!emittedHeaderNames.Add(header.HeaderName))
                {
                    continue;
                }

                string propertyName = CodeEmitHelpers.HeaderNameToPropertyName(header.HeaderName);
                string fieldName = CodeEmitHelpers.ToCamelCase(propertyName);
                string? typeName = header.SchemaPointer is not null
                    ? this.ResolveSchemaTypeName(header.SchemaPointer)
                    : null;

                allHeaders.Add((header, typeName ?? "JsonElement", fieldName, propertyName));
            }
        }

        bool hasHeaders = allHeaders.Count > 0;

        // Detect a 2xx or default binary-style (octet-stream or text-only) response: the server
        // must be able to write raw bytes.
        bool hasOctetStreamResponse = op.Responses.Any(IsBinaryStyleResponse);

        w.WriteLine("/// <summary>");
        w.WriteLine($"/// Result type for the {op.CSharpMethodName()} operation.");
        w.WriteLine("/// </summary>");
        w.WriteLine($"public readonly struct {structName}");
        w.OpenBrace();

        // Private constructor
        if (hasHeaders)
        {
            w.Write($"private {structName}(int statusCode, JsonElement body, string? contentType");
            if (hasOctetStreamResponse)
            {
                w.Write(", bool hasBinaryBody, Func<Stream, CancellationToken, ValueTask>? binaryWriter");
            }

            foreach (var (_, typeName, fieldName, _) in allHeaders)
            {
                w.Write($", {typeName} {fieldName} = default");
            }

            w.WriteLine(")");
            w.OpenBrace();
            w.WriteLine("this.StatusCode = statusCode;");
            w.WriteLine("this.Body = body;");
            w.WriteLine("this.ContentType = contentType;");
            if (hasOctetStreamResponse)
            {
                w.WriteLine("this.HasBinaryBody = hasBinaryBody;");
                w.WriteLine("this.binaryWriter = binaryWriter;");
            }

            foreach (var (_, _, fieldName, propertyName) in allHeaders)
            {
                w.WriteLine($"this.{propertyName} = {fieldName};");
            }

            w.CloseBrace();
        }
        else if (hasOctetStreamResponse)
        {
            w.WriteLine($"private {structName}(int statusCode, JsonElement body, string? contentType, bool hasBinaryBody, Func<Stream, CancellationToken, ValueTask>? binaryWriter)");
            w.OpenBrace();
            w.WriteLine("this.StatusCode = statusCode;");
            w.WriteLine("this.Body = body;");
            w.WriteLine("this.ContentType = contentType;");
            w.WriteLine("this.HasBinaryBody = hasBinaryBody;");
            w.WriteLine("this.binaryWriter = binaryWriter;");
            w.CloseBrace();
        }
        else
        {
            w.WriteLine($"private {structName}(int statusCode, JsonElement body = default, string? contentType = null)");
            w.OpenBrace();
            w.WriteLine("this.StatusCode = statusCode;");
            w.WriteLine("this.Body = body;");
            w.WriteLine("this.ContentType = contentType;");
            w.CloseBrace();
        }

        w.WriteLine();
        w.WriteLine("/// <summary>Gets the HTTP status code.</summary>");
        w.WriteLine("public int StatusCode { get; }");
        w.WriteLine();
        w.WriteLine("/// <summary>Gets the response body.</summary>");
        w.WriteLine("public JsonElement Body { get; }");
        w.WriteLine();
        w.WriteLine("/// <summary>Gets the content type for the response body.</summary>");
        w.WriteLine("public string? ContentType { get; }");

        if (hasOctetStreamResponse)
        {
            w.WriteLine();
            w.WriteLine("private readonly Func<Stream, CancellationToken, ValueTask>? binaryWriter;");
            w.WriteLine();
            w.WriteLine("/// <summary>Gets a value indicating whether the result carries a raw binary body.</summary>");
            w.WriteLine("public bool HasBinaryBody { get; }");
            w.WriteLine();
            w.WriteLine("/// <summary>Writes the raw binary response body to the supplied stream.</summary>");
            w.WriteLine("/// <param name=\"stream\">The stream to write the binary body to.</param>");
            w.WriteLine("/// <param name=\"cancellationToken\">A token to cancel the write.</param>");
            w.WriteLine("/// <returns>A <see cref=\"ValueTask\"/> that completes when the body has been written.</returns>");
            w.WriteLine("public ValueTask WriteBinaryBodyAsync(Stream stream, CancellationToken cancellationToken) => this.binaryWriter is { } writer ? writer(stream, cancellationToken) : ValueTask.CompletedTask;");
        }

        // Header properties
        foreach (var (header, typeName, _, propertyName) in allHeaders)
        {
            w.WriteLine();
            w.WriteLine("/// <summary>");
            w.WriteLine($"/// Gets the value of the <c>{header.HeaderName}</c> response header.");
            w.WriteLine("/// </summary>");
            w.WriteLine($"public {typeName} {propertyName} {{ get; }}");
        }

        // Factory methods for each declared response
        foreach (ResponseInfo resp in op.Responses)
        {
            string factoryName = CodeEmitHelpers.StatusCodeToName(resp.StatusCode);
            string? typeName = this.ResolveResponseTypeName(resp);

            // For a binary-style (octet-stream or text-only) 2xx or default response, emit
            // factories that take raw bytes or a write callback so the handler can return
            // binary or text content. A response that also declares JSON content falls
            // through so the JSON factory is emitted alongside.
            if (IsBinaryStyleResponse(resp))
            {
                bool isDefaultResp = resp.StatusCode == "default";
                bool isTextOnlyResp = IsTextOnlyResponse(resp);
                string statusParam = isDefaultResp ? "int statusCode, " : string.Empty;
                string statusArg = isDefaultResp ? "statusCode" : resp.StatusCode;
                string statusDoc = isDefaultResp ? "the given status" : $"status {resp.StatusCode}";
                string defaultContentType = isTextOnlyResp ? "text/plain; charset=utf-8" : "application/octet-stream";
                string ctorPrefix = $"{statusArg}, default, contentType, hasBinaryBody: true, binaryWriter: ";

                void EmitStatusParamDoc()
                {
                    if (isDefaultResp)
                    {
                        w.WriteLine("/// <param name=\"statusCode\">The HTTP status code.</param>");
                    }
                }

                w.WriteLine();
                w.WriteLine("/// <summary>");
                w.WriteLine($"/// Creates a {factoryName} result with a buffered raw binary body.");
                w.WriteLine("/// </summary>");
                EmitStatusParamDoc();
                w.WriteLine("/// <param name=\"body\">The raw binary response body.</param>");
                w.WriteLine("/// <param name=\"contentType\">The content type for the response body.</param>");
                w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with {statusDoc}.</returns>");
                w.WriteLine($"public static {structName} {factoryName}({statusParam}ReadOnlyMemory<byte> body, string? contentType = \"{defaultContentType}\") => new({ctorPrefix}(stream, cancellationToken) => stream.WriteAsync(body, cancellationToken));");

                w.WriteLine();
                w.WriteLine("/// <summary>");
                w.WriteLine($"/// Creates a {factoryName} result that streams a raw binary body.");
                w.WriteLine("/// </summary>");
                EmitStatusParamDoc();
                w.WriteLine("/// <param name=\"writeBody\">A callback that writes the raw binary body to the response stream.</param>");
                w.WriteLine("/// <param name=\"contentType\">The content type for the response body.</param>");
                w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with {statusDoc}.</returns>");
                w.WriteLine($"public static {structName} {factoryName}({statusParam}Func<Stream, CancellationToken, ValueTask> writeBody, string? contentType = \"{defaultContentType}\") => new({ctorPrefix}writeBody);");

                if (isTextOnlyResp)
                {
                    // String convenience overload — encodes the text as UTF-8 when the body is
                    // written. The UTF-8 bytes overload above is the allocation-conscious path.
                    w.WriteLine();
                    w.WriteLine("/// <summary>");
                    w.WriteLine($"/// Creates a {factoryName} result from a text body, encoded as UTF-8 when written.");
                    w.WriteLine("/// </summary>");
                    EmitStatusParamDoc();
                    w.WriteLine("/// <param name=\"body\">The text response body.</param>");
                    w.WriteLine("/// <param name=\"contentType\">The content type for the response body.</param>");
                    w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with {statusDoc}.</returns>");
                    w.WriteLine($"public static {structName} {factoryName}({statusParam}string body, string? contentType = \"{defaultContentType}\") => new({ctorPrefix}(stream, cancellationToken) => stream.WriteAsync(System.Text.Encoding.UTF8.GetBytes(body), cancellationToken));");
                }

                if (typeName is null)
                {
                    continue;
                }
            }

            List<(HeaderInfo Header, string TypeName, string FieldName, string PropertyName)> respHeaders = [];
            foreach (HeaderInfo header in resp.Headers)
            {
                var match = allHeaders.Find(h => h.Header.HeaderName == header.HeaderName);
                respHeaders.Add(match);
            }

            w.WriteLine();

            if (resp.StatusCode == "default")
            {
                w.WriteLine("/// <summary>");
                w.WriteLine("/// Creates a default error result.");
                w.WriteLine("/// </summary>");

                this.EmitServerResultFactory(w, structName, factoryName, typeName, resp, respHeaders, resp.StatusCode, hasHeaders, hasOctetStreamResponse);
            }
            else
            {
                w.WriteLine("/// <summary>");
                string desc = $"Creates a {resp.StatusCode} {factoryName} result.";
                w.WriteLine($"/// {CodeEmitHelpers.EscapeXml(desc)}");
                w.WriteLine("/// </summary>");

                this.EmitServerResultFactory(w, structName, factoryName, typeName, resp, respHeaders, resp.StatusCode, hasHeaders, hasOctetStreamResponse);
            }
        }

        // ValidateBody method — validates the response body against the typed schema
        // for the current status code.
        w.WriteLine();
        w.WriteLine("/// <summary>");
        w.WriteLine("/// Validates the response body against the schema for the current status code.");
        w.WriteLine("/// </summary>");
        w.WriteLine("/// <returns><see langword=\"true\"/> if the body is valid or undefined; otherwise <see langword=\"false\"/>.</returns>");
        w.WriteLine("public bool ValidateBody()");
        w.OpenBrace();
        w.WriteLine("if (this.Body.IsUndefined()) return true;");

        // Emit switch arms for each response that has a typed body
        bool hasAnyTypedResponse = false;
        foreach (ResponseInfo resp in op.Responses)
        {
            string? typeName = this.ResolveResponseTypeName(resp);
            if (typeName is null || resp.StatusCode == "default")
            {
                continue;
            }

            if (!hasAnyTypedResponse)
            {
                w.WriteLine("return this.StatusCode switch");
                w.OpenBrace();
                hasAnyTypedResponse = true;
            }

            w.WriteLine($"{resp.StatusCode} => {typeName}.From(this.Body).EvaluateSchema(),");
        }

        if (hasAnyTypedResponse)
        {
            w.WriteLine("_ => true,");
            w.CloseBraceNoNewline().Write(";");
            w.WriteLine();
        }
        else
        {
            w.WriteLine("return true;");
        }

        w.CloseBrace();

        w.WriteLine();
        w.WriteLine("/// <summary>");
        w.WriteLine("/// Writes the response body to the specified writer.");
        w.WriteLine("/// </summary>");
        w.WriteLine("/// <param name=\"writer\">The UTF-8 JSON writer.</param>");
        w.WriteLine("public void WriteBody(Utf8JsonWriter writer)");
        w.OpenBrace();
        w.WriteLine("if (!this.Body.IsUndefined())");
        w.OpenBrace();
        w.WriteLine("this.Body.WriteTo(writer);");
        w.CloseBrace();
        w.CloseBrace();

        // WriteResponseHeaders method (only if there are headers)
        if (hasHeaders)
        {
            w.WriteLine();
            w.WriteLine("/// <summary>");
            w.WriteLine("/// Writes the response headers using the specified callback.");
            w.WriteLine("/// </summary>");
            w.WriteLine("/// <typeparam name=\"TState\">The state type passed to the callback.</typeparam>");
            w.WriteLine("/// <param name=\"callback\">A callback that receives the header name and value.</param>");
            w.WriteLine("/// <param name=\"state\">State to pass to the callback.</param>");
            w.WriteLine("public void WriteResponseHeaders<TState>(HeaderCallback<TState> callback, TState state)");
            w.OpenBrace();

            foreach (var (header, _, _, propertyName) in allHeaders)
            {
                string uid = CodeEmitHelpers.SanitizeIdentifier(header.HeaderName);
                w.WriteLine($"if (!this.{propertyName}.IsUndefined())");
                w.OpenBrace();
                w.WriteLine($"ReadOnlySpan<byte> nameUtf8{uid} = \"{header.HeaderName}\"u8;");
                CodeEmitHelpers.EmitHeaderParamWrite(w, $"this.{propertyName}", uid, header.SerializationKind, ParameterStyle.Simple, header.Explode, elementKind: header.ElementSerializationKind);
                w.CloseBrace();
                w.WriteLine();
            }

            w.CloseBrace();
        }

        w.CloseBrace();

        return new GeneratedFile($"{structName}.cs", w.ToString());
    }

    private void EmitServerResultFactory(
        IndentedWriter w,
        string structName,
        string factoryName,
        string? bodyTypeName,
        ResponseInfo response,
        List<(HeaderInfo Header, string TypeName, string FieldName, string PropertyName)> respHeaders,
        string statusCode,
        bool structHasHeaders,
        bool structHasBinaryBody)
    {
        bool isDefault = statusCode == "default";
        bool hasBody = bodyTypeName is not null;

        // The body carries a Source<TContext> (object/array type) iff its schema pointer is in the context-source set;
        // only then can a closure-free, single-materialisation generic overload be emitted alongside the non-generic one.
        bool bodyHasContextSource = hasBody
            && this.ResolveResponseBodySchemaPointer(response) is { } bodySchemaPointer
            && this.typeMap.HasBuilder(bodySchemaPointer);

        StringBuilder paramList = new();
        if (isDefault)
        {
            paramList.Append("int statusCode");
        }

        if (hasBody)
        {
            if (paramList.Length > 0)
            {
                paramList.Append(", ");
            }

            paramList.Append($"{bodyTypeName}.Source body, JsonWorkspace workspace");
        }
        else if (respHeaders.Count > 0)
        {
            if (paramList.Length > 0)
            {
                paramList.Append(", ");
            }

            paramList.Append("JsonWorkspace workspace");
        }

        foreach (var (_, typeName, fieldName, _) in respHeaders)
        {
            if (paramList.Length > 0)
            {
                paramList.Append(", ");
            }

            paramList.Append($"{typeName}.Source {fieldName} = default");
        }

        if (isDefault)
        {
            w.WriteLine($"/// <param name=\"statusCode\">The HTTP status code.</param>");
        }

        if (hasBody)
        {
            w.WriteLine($"/// <param name=\"body\">The response body.</param>");
            w.WriteLine($"/// <param name=\"workspace\">The workspace for building the response value.</param>");
        }
        else if (respHeaders.Count > 0)
        {
            w.WriteLine($"/// <param name=\"workspace\">The workspace for building header values.</param>");
        }

        foreach (var (header, _, fieldName, _) in respHeaders)
        {
            w.WriteLine($"/// <param name=\"{fieldName}\">The value for the <c>{header.HeaderName}</c> response header.</param>");
        }

        w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with status {statusCode}.</returns>");

        string statusExpr = isDefault ? "statusCode" : statusCode;
        string bodyExpr = hasBody
            ? $"{bodyTypeName}.CreateBuilder(workspace, body, 30).RootElement"
            : "default";

        // The media type the response actually declares, not a literal "application/json". A specification declaring
        // RFC 9457 problem documents means it: answering them as application/json tells a client the body is an
        // ordinary result, and a client branching on the media type to find the problem shape never sees one.
        string contentTypeExpr = hasBody ? $"\"{DeclaredJsonMediaType(response)}\"" : "null";

        // When the struct also carries an octet-stream binary body, the private ctor has two
        // extra required parameters; non-binary factories pass the no-body defaults for them.
        string binaryArgs = structHasBinaryBody ? ", false, null" : string.Empty;

        if (structHasHeaders)
        {
            StringBuilder ctorArgs = new();
            ctorArgs.Append($"{statusExpr}, {bodyExpr}, {contentTypeExpr}{binaryArgs}");
            foreach (var (_, typeName, fieldName, _) in respHeaders)
            {
                ctorArgs.Append($", {fieldName}: {fieldName}.IsUndefined ? default : {typeName}.CreateBuilder(workspace, {fieldName}, 30).RootElement");
            }

            w.WriteLine($"public static {structName} {factoryName}({paramList}) => new({ctorArgs});");
        }
        else
        {
            w.WriteLine($"public static {structName} {factoryName}({paramList}) => new({statusExpr}, {bodyExpr}, {contentTypeExpr}{binaryArgs});");
        }

        // Closure-free, single-materialisation sibling: takes the response body already assembled as a context-threaded
        // Source<TContext> (built via the model's Build<TContext>) and routes it straight through CreateBuilder<TContext>
        // — no per-item closure on the caller side and no re-materialisation here. Only emitted for object/array bodies
        // (bodyHasContextSource); a scalar body has no Source<TContext> and uses the non-generic factory above.
        if (bodyHasContextSource)
        {
            string genericParamList = paramList.ToString().Replace($"{bodyTypeName}.Source body", $"{bodyTypeName}.Source<TContext> body");
            string genericBodyExpr = $"{bodyTypeName}.CreateBuilder(workspace, in body, 30).RootElement";

            w.WriteLine("/// <summary>");
            w.WriteLine($"/// Creates a {statusCode} {factoryName} result from a context-threaded body, materialised in a single pass.");
            w.WriteLine("/// </summary>");
            w.WriteLine("/// <typeparam name=\"TContext\">The type of the context carried by the body.</typeparam>");
            if (isDefault)
            {
                w.WriteLine("/// <param name=\"statusCode\">The HTTP status code.</param>");
            }

            w.WriteLine("/// <param name=\"body\">The context-threaded response body.</param>");
            w.WriteLine("/// <param name=\"workspace\">The workspace for building the response value.</param>");
            foreach (var (header, _, fieldName, _) in respHeaders)
            {
                w.WriteLine($"/// <param name=\"{fieldName}\">The value for the <c>{header.HeaderName}</c> response header.</param>");
            }

            w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with status {statusCode}.</returns>");

            string genericCtorArgs;
            if (structHasHeaders)
            {
                StringBuilder ctorArgs = new();
                ctorArgs.Append($"{statusExpr}, {genericBodyExpr}, {contentTypeExpr}{binaryArgs}");
                foreach (var (_, typeName, fieldName, _) in respHeaders)
                {
                    ctorArgs.Append($", {fieldName}: {fieldName}.IsUndefined ? default : {typeName}.CreateBuilder(workspace, {fieldName}, 30).RootElement");
                }

                genericCtorArgs = ctorArgs.ToString();
            }
            else
            {
                genericCtorArgs = $"{statusExpr}, {genericBodyExpr}, {contentTypeExpr}{binaryArgs}";
            }

            w.WriteLine($"public static {structName} {factoryName}<TContext>({genericParamList})");
            w.WriteLine("#if NET9_0_OR_GREATER");
            w.WriteLine("    where TContext : allows ref struct");
            w.WriteLine("#endif");
            w.WriteLine($"    => new({genericCtorArgs});");
        }
    }

