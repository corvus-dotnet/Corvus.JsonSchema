    private void EmitServerResultFactory(
        IndentedWriter w,
        string structName,
        string factoryName,
        string? bodyTypeName,
        ResponseInfo response,
        List<(HeaderInfo Header, string TypeName, string FieldName, string PropertyName)> respHeaders,
        string statusCode,
        bool structHasHeaders,
        string streamTypeName,
        string streamWriterDelegateName)
    {
        bool isDefault = statusCode == "default";
        List<ContentInfo> streamingContent = GetStreamingContent(response);
        bool hasStreamingBody = streamingContent.Count > 0;
        bool hasBody = bodyTypeName is not null && !hasStreamingBody;
        bool hasRespHeaders = respHeaders.Count > 0;

        // The body carries a Source<TContext> (object/array type) iff its schema pointer is in the context-source set;
        // only then can a closure-free, single-materialisation generic overload be emitted alongside the non-generic one.
        bool bodyHasContextSource = hasBody
            && this.ResolveResponseBodySchemaPointer(response) is { } bodySchemaPointer
            && this.typeMap.HasBuilder(bodySchemaPointer);

        if (hasStreamingBody)
        {
            this.EmitServerStreamingResultFactories(
                w,
                structName,
                factoryName,
                streamingContent,
                respHeaders,
                statusCode,
                streamTypeName,
                streamWriterDelegateName);
            return;
        }

        // For a 2xx or default response carrying a raw binary (octet-stream) or text-only body,
        // emit factories that take raw bytes or a write callback (mirrors the client exposing a
        // response Stream for the same response). When the response also carries JSON content
        // (e.g. a default response declaring both), the JSON factory is emitted as well.
        bool binaryEligible = isDefault || (statusCode.Length > 0 && statusCode[0] == '2');
        bool isTextOnly = IsTextOnlyResponse(response);
        if (binaryEligible && (IsOctetStreamResponse(response) || isTextOnly))
        {
            this.EmitServerBinaryResultFactory(
                w,
                structName,
                factoryName,
                respHeaders,
                statusCode,
                structHasHeaders,
                isDefault,
                isTextOnly);
            if (bodyTypeName is null)
            {
                return;
            }

            w.WriteLine();
        }

        // A 2xx or default multipart/form-data response with binary parts: the factory
        // takes the typed body plus BinaryPartData per binary part, mirroring the
        // client sending the same shape.
        if (binaryEligible && IsMultipartResponseWithBinaryParts(response)
            && (bodyTypeName ?? this.ResolveMultipartResponseTypeName(response)) is { } multipartBodyTypeName)
        {
            this.EmitServerMultipartResultFactory(w, structName, factoryName, multipartBodyTypeName, response, respHeaders, statusCode, structHasHeaders, isDefault);
            return;
        }

        // Parameters
        StringBuilder paramList = new();
        if (isDefault)
        {
            paramList.Append("int statusCode");
        }

        if (hasBody)
        {
            if (paramList.Length > 0)
            {
                paramList.Append(", ");
            }

            paramList.Append($"{bodyTypeName}.Source body, JsonWorkspace workspace");
        }
        else if (hasRespHeaders)
        {
            if (paramList.Length > 0)
            {
                paramList.Append(", ");
            }

            paramList.Append("JsonWorkspace workspace");
        }

        foreach (var (header, typeName, fieldName, _) in respHeaders)
        {
            if (paramList.Length > 0)
            {
                paramList.Append(", ");
            }

            // Headers use Source pattern (consistent with body parameters).
            paramList.Append($"{typeName}.Source {fieldName} = default");
        }

        // XML doc params
        if (isDefault)
        {
            w.WriteLine($"/// <param name=\"statusCode\">The HTTP status code.</param>");
        }

        if (hasBody)
        {
            w.WriteLine($"/// <param name=\"body\">The response body.</param>");
            w.WriteLine($"/// <param name=\"workspace\">The workspace for building the response value.</param>");
        }
        else if (hasRespHeaders)
        {
            w.WriteLine($"/// <param name=\"workspace\">The workspace for building header values.</param>");
        }

        foreach (var (header, _, fieldName, _) in respHeaders)
        {
            w.WriteLine($"/// <param name=\"{fieldName}\">The value for the <c>{header.HeaderName}</c> response header.</param>");
        }

        w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with status {statusCode}.</returns>");

        // Method signature + body
        string statusExpr = isDefault ? "statusCode" : statusCode;
        string bodyExpr = hasBody
            ? $"{bodyTypeName}.CreateBuilder(workspace, body, 30).RootElement"
            : "default";

        // The media type the response actually declares, not a literal "application/json". A specification declaring
        // RFC 9457 problem documents means it: answering them as application/json tells a client the body is an
        // ordinary result, and a client branching on the media type to find the problem shape never sees one.
        string contentTypeExpr = hasBody ? $"\"{DeclaredJsonMediaType(response)}\"" : "null";

        if (structHasHeaders)
        {
            // Use the expanded constructor form
            StringBuilder ctorArgs = new();
            ctorArgs.Append($"{statusExpr}, {bodyExpr}, {contentTypeExpr}");
            foreach (var (_, typeName, fieldName, _) in respHeaders)
            {
                ctorArgs.Append($", {fieldName}: {fieldName}.IsUndefined ? default : {typeName}.CreateBuilder(workspace, {fieldName}, 30).RootElement");
            }

            w.WriteLine($"public static {structName} {factoryName}({paramList}) => new({ctorArgs});");
        }
        else
        {
            w.WriteLine($"public static {structName} {factoryName}({paramList}) => new({statusExpr}, {bodyExpr}, {contentTypeExpr});");
        }

        // Closure-free, single-materialisation sibling: takes the response body already assembled as a context-threaded
        // Source<TContext> (built via the model's Build<TContext>) and routes it straight through CreateBuilder<TContext>
        // — no per-item closure on the caller side and no re-materialisation here. Only emitted for object/array bodies
        // (bodyHasContextSource); a scalar body has no Source<TContext> and uses the non-generic factory above.
        if (bodyHasContextSource)
        {
            string genericParamList = paramList.ToString().Replace($"{bodyTypeName}.Source body", $"{bodyTypeName}.Source<TContext> body");
            string genericBodyExpr = $"{bodyTypeName}.CreateBuilder(workspace, in body, 30).RootElement";

            w.WriteLine("/// <summary>");
            w.WriteLine($"/// Creates a {statusCode} {factoryName} result from a context-threaded body, materialised in a single pass.");
            w.WriteLine("/// </summary>");
            w.WriteLine("/// <typeparam name=\"TContext\">The type of the context carried by the body.</typeparam>");
            if (isDefault)
            {
                w.WriteLine("/// <param name=\"statusCode\">The HTTP status code.</param>");
            }

            w.WriteLine("/// <param name=\"body\">The context-threaded response body.</param>");
            w.WriteLine("/// <param name=\"workspace\">The workspace for building the response value.</param>");
            foreach (var (header, _, fieldName, _) in respHeaders)
            {
                w.WriteLine($"/// <param name=\"{fieldName}\">The value for the <c>{header.HeaderName}</c> response header.</param>");
            }

            w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with status {statusCode}.</returns>");

            string genericCtorArgs;
            if (structHasHeaders)
            {
                StringBuilder ctorArgs = new();
                ctorArgs.Append($"{statusExpr}, {genericBodyExpr}, {contentTypeExpr}");
                foreach (var (_, typeName, fieldName, _) in respHeaders)
                {
                    ctorArgs.Append($", {fieldName}: {fieldName}.IsUndefined ? default : {typeName}.CreateBuilder(workspace, {fieldName}, 30).RootElement");
                }

                genericCtorArgs = ctorArgs.ToString();
            }
            else
            {
                genericCtorArgs = $"{statusExpr}, {genericBodyExpr}, {contentTypeExpr}";
            }

            w.WriteLine($"public static {structName} {factoryName}<TContext>({genericParamList})");
            w.WriteLine("#if NET9_0_OR_GREATER");
            w.WriteLine("    where TContext : allows ref struct");
            w.WriteLine("#endif");
            w.WriteLine($"    => new({genericCtorArgs});");
        }
    }

    /// <summary>
    /// Emits the factories for a 2xx <c>application/octet-stream</c> response. Two overloads are
    /// generated: one buffered (taking a <c>ReadOnlyMemory&lt;byte&gt;</c>) and one streaming
    /// (taking a <c>Func&lt;Stream, CancellationToken, ValueTask&gt;</c> that writes the body
    /// directly to the response stream). Both store a writer that the endpoint invokes via
    /// <c>WriteBinaryBodyAsync</c>.
    /// </summary>
    private void EmitServerBinaryResultFactory(
        IndentedWriter w,
        string structName,
        string factoryName,
        List<(HeaderInfo Header, string TypeName, string FieldName, string PropertyName)> respHeaders,
        string statusCode,
        bool structHasHeaders,
        bool isDefault = false,
        bool isTextOnly = false)
    {
        bool hasRespHeaders = respHeaders.Count > 0;

        // Default responses carry the caller's status code as the first parameter; declared
        // statuses bake the literal into the constructor call.
        string statusParam = isDefault ? "int statusCode, " : string.Empty;
        string statusArg = isDefault ? "statusCode" : statusCode;
        string statusDoc = isDefault ? "the given status" : $"status {statusCode}";
        string defaultContentType = isTextOnly ? "text/plain; charset=utf-8" : "application/octet-stream";

        // Build the trailing constructor arguments (headers + binary flags) shared by both overloads.
        // The writer expression varies between overloads, so it is appended by each call.
        string HeaderCtorArgs()
        {
            StringBuilder sb = new();
            if (structHasHeaders)
            {
                foreach (var (_, typeName, fieldName, _) in respHeaders)
                {
                    sb.Append($", {fieldName}: {fieldName}.IsUndefined ? default : {typeName}.CreateBuilder(workspace, {fieldName}, 30).RootElement");
                }
            }

            return sb.ToString();
        }

        // The workspace is REQUIRED and contentType is optional, so the workspace has to precede it: emitting the
        // header parameters as one trailing block put a required parameter after an optional one (CS1737), which the
        // JSON factories never hit because they have no optional parameter before the workspace.
        string RequiredParams() => hasRespHeaders ? ", JsonWorkspace workspace" : string.Empty;

        string OptionalHeaderParams()
        {
            StringBuilder sb = new();
            foreach (var (_, typeName, fieldName, _) in respHeaders)
            {
                sb.Append($", {typeName}.Source {fieldName} = default");
            }

            return sb.ToString();
        }

        void EmitHeaderDocs()
        {
            if (hasRespHeaders)
            {
                w.WriteLine("/// <param name=\"workspace\">The workspace for building header values.</param>");
            }

            foreach (var (header, _, fieldName, _) in respHeaders)
            {
                w.WriteLine($"/// <param name=\"{fieldName}\">The value for the <c>{header.HeaderName}</c> response header.</param>");
            }
        }

        string headerCtorArgs = HeaderCtorArgs();
        string requiredParams = RequiredParams();
        string optionalHeaderParams = OptionalHeaderParams();

        // Buffered overload — copies the supplied bytes to the response stream when invoked.
        if (isDefault)
        {
            w.WriteLine("/// <param name=\"statusCode\">The HTTP status code.</param>");
        }

        w.WriteLine("/// <param name=\"body\">The raw binary response body.</param>");
        w.WriteLine("/// <param name=\"contentType\">The content type for the response body.</param>");
        EmitHeaderDocs();
        w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with {statusDoc}.</returns>");
        w.WriteLine($"public static {structName} {factoryName}({statusParam}ReadOnlyMemory<byte> body{requiredParams}, string? contentType = \"{defaultContentType}\"{optionalHeaderParams}) => new({statusArg}, default, contentType{headerCtorArgs}, hasBinaryBody: true, binaryWriter: (stream, cancellationToken) => stream.WriteAsync(body, cancellationToken));");

        w.WriteLine();

        // Streaming overload — invokes the supplied callback to write the body directly.
        w.WriteLine($"/// <summary>Creates a {factoryName} result whose body is streamed directly to the response.</summary>");
        if (isDefault)
        {
            w.WriteLine("/// <param name=\"statusCode\">The HTTP status code.</param>");
        }

        w.WriteLine("/// <param name=\"writeBody\">A callback that writes the response body to the supplied stream.</param>");
        w.WriteLine("/// <param name=\"contentType\">The content type for the response body.</param>");
        EmitHeaderDocs();
        w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with {statusDoc}.</returns>");
        w.WriteLine($"public static {structName} {factoryName}({statusParam}Func<Stream, CancellationToken, ValueTask> writeBody{requiredParams}, string? contentType = \"{defaultContentType}\"{optionalHeaderParams}) => new({statusArg}, default, contentType{headerCtorArgs}, hasBinaryBody: true, binaryWriter: writeBody);");

        if (isTextOnly)
        {
            w.WriteLine();

            // String convenience overload — encodes the text as UTF-8 when the body is written.
            // The UTF-8 bytes overload above is the allocation-conscious path.
            w.WriteLine($"/// <summary>Creates a {factoryName} result from a text body, encoded as UTF-8 when written.</summary>");
            if (isDefault)
            {
                w.WriteLine("/// <param name=\"statusCode\">The HTTP status code.</param>");
            }

            w.WriteLine("/// <param name=\"body\">The text response body.</param>");
            w.WriteLine("/// <param name=\"contentType\">The content type for the response body.</param>");
            EmitHeaderDocs();
            w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with {statusDoc}.</returns>");
            w.WriteLine($"public static {structName} {factoryName}({statusParam}string body{requiredParams}, string? contentType = \"{defaultContentType}\"{optionalHeaderParams}) => new({statusArg}, default, contentType{headerCtorArgs}, hasBinaryBody: true, binaryWriter: (stream, cancellationToken) => stream.WriteAsync(System.Text.Encoding.UTF8.GetBytes(body), cancellationToken));");
        }
    }

    private void EmitServerStreamingResultFactories(
        IndentedWriter w,
        string structName,
        string factoryName,
        List<ContentInfo> streamingContent,
        List<(HeaderInfo Header, string TypeName, string FieldName, string PropertyName)> respHeaders,
        string statusCode,
        string streamTypeName,
        string streamWriterDelegateName)
    {
        bool isDefault = statusCode == "default";
        bool includeMediaTypeSuffix = streamingContent.Count > 1;
        string statusExpr = isDefault ? "statusCode" : statusCode;

        foreach (ContentInfo content in streamingContent)
        {
            string methodName = GetStreamingFactoryName(factoryName, content.MediaType, includeMediaTypeSuffix);
            string contentTypeExpr = SymbolDisplay.FormatLiteral(content.MediaType, quote: true);
            string writerParam = $"{streamWriterDelegateName} writer";
            string contextWriterParam = $"{streamWriterDelegateName}<TContext> writer";

            StringBuilder commonParams = new();
            if (isDefault)
            {
                commonParams.Append("int statusCode, ");
            }

            commonParams.Append(writerParam);
            bool hasHeaders = respHeaders.Count > 0;
            if (hasHeaders)
            {
                commonParams.Append(", JsonWorkspace workspace");
            }

            foreach (var (_, typeName, fieldName, _) in respHeaders)
            {
                commonParams.Append($", {typeName}.Source {fieldName} = default");
            }

            StringBuilder contextParams = new();
            if (isDefault)
            {
                contextParams.Append("int statusCode, ");
            }

            contextParams.Append($"TContext context, {contextWriterParam}");
            if (hasHeaders)
            {
                contextParams.Append(", JsonWorkspace workspace");
            }

            foreach (var (_, typeName, fieldName, _) in respHeaders)
            {
                contextParams.Append($", {typeName}.Source {fieldName} = default");
            }

            if (isDefault)
            {
                w.WriteLine("/// <param name=\"statusCode\">The HTTP status code.</param>");
            }

            w.WriteLine($"/// <param name=\"writer\">The callback that appends items to the <see cref=\"{streamTypeName}\"/>.</param>");
            if (hasHeaders)
            {
                w.WriteLine("/// <param name=\"workspace\">The workspace for building header values.</param>");
            }

            foreach (var (header, _, fieldName, _) in respHeaders)
            {
                w.WriteLine($"/// <param name=\"{fieldName}\">The value for the <c>{header.HeaderName}</c> response header.</param>");
            }

            w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with status {statusCode}.</returns>");
            StringBuilder ctorArgs = new();
            ctorArgs.Append($"{statusExpr}, default, {contentTypeExpr}, streamWriter: static (jsonStreamWriter, context, cancellationToken) => (({streamWriterDelegateName})context!)(new {streamTypeName}(jsonStreamWriter), cancellationToken), streamWriterContext: writer");
            foreach (var (_, typeName, fieldName, _) in respHeaders)
            {
                ctorArgs.Append($", {fieldName}: {fieldName}.IsUndefined ? default : {typeName}.CreateBuilder(workspace, {fieldName}, 30).RootElement");
            }

            w.WriteLine($"public static {structName} {methodName}({commonParams}) => new({ctorArgs});");
            w.WriteLine();
            w.WriteLine($"/// <typeparam name=\"TContext\">The callback context type.</typeparam>");
            if (isDefault)
            {
                w.WriteLine("/// <param name=\"statusCode\">The HTTP status code.</param>");
            }

            w.WriteLine($"/// <param name=\"context\">The callback context.</param>");
            w.WriteLine($"/// <param name=\"writer\">The callback that appends items to the <see cref=\"{streamTypeName}\"/>.</param>");
            if (hasHeaders)
            {
                w.WriteLine("/// <param name=\"workspace\">The workspace for building header values.</param>");
            }

            foreach (var (header, _, fieldName, _) in respHeaders)
            {
                w.WriteLine($"/// <param name=\"{fieldName}\">The value for the <c>{header.HeaderName}</c> response header.</param>");
            }

            w.WriteLine($"/// <returns>A <see cref=\"{structName}\"/> with status {statusCode}.</returns>");
            StringBuilder contextCtorArgs = new();
            contextCtorArgs.Append($"{statusExpr}, default, {contentTypeExpr}, streamWriter: static (jsonStreamWriter, context, cancellationToken) =>");
            w.WriteLine($"public static {structName} {methodName}<TContext>({contextParams}) => new({contextCtorArgs}");
            w.PushIndent();
            w.WriteLine("{");
            w.PushIndent();
            w.WriteLine($"var wrapper = ({streamWriterDelegateName}Context<TContext>)context!;");
            w.WriteLine($"return wrapper.Writer(new {streamTypeName}(jsonStreamWriter), wrapper.Context, cancellationToken);");
            w.PopIndent();
            w.WriteLine("},");
            w.Write($"streamWriterContext: new {streamWriterDelegateName}Context<TContext>(context, writer)");
            foreach (var (_, typeName, fieldName, _) in respHeaders)
            {
                w.Write($", {fieldName}: {typeName}.CreateBuilder(workspace, {fieldName}, 30).RootElement");
            }

            w.WriteLine(");");
            w.PopIndent();
        }
    }

