    private static SecuritySchemeInfo[] PrepareSecuritySchemes(JsonElement specRoot)
    {
        OpenApiDocument doc = specRoot;
        if (doc.ComponentsValue.IsUndefined() || doc.ComponentsValue.SecuritySchemes.IsUndefined())
        {
            return [];
        }

        List<SecuritySchemeInfo> result = [];

        foreach (var schemeProp in doc.ComponentsValue.SecuritySchemes.EnumerateObject())
        {
            OpenApiDocument.SecuritySchemeOrReference schemeOrRef = schemeProp.Value;
            OpenApiDocument.SecurityScheme scheme = OpenApiDocument.SecurityScheme.From(schemeOrRef);

            string schemeName = schemeProp.Name;
            string schemeType = scheme.Type.IsNotUndefined() ? scheme.Type.GetString()! : "unknown";
            bool isDeprecated = scheme.Deprecated.IsNotUndefined() && (bool)scheme.Deprecated;
            string? description = scheme.Description.IsNotUndefined() ? scheme.Description.GetString() : null;

            string? apiKeyName = null;
            string? apiKeyIn = null;
            string? httpScheme = null;
            string? bearerFormat = null;
            string? openIdConnectUrl = null;
            string? oauth2MetadataUrl = null;
            string? deviceAuthorizationUrl = null;

            if (string.Equals(schemeType, "apiKey", StringComparison.Ordinal))
            {
                apiKeyName = scheme.Name.IsNotUndefined() ? scheme.Name.GetString() : null;
                apiKeyIn = scheme.In.IsNotUndefined() ? scheme.In.GetString() : null;
            }
            else if (string.Equals(schemeType, "http", StringComparison.Ordinal))
            {
                httpScheme = scheme.Scheme.IsNotUndefined() ? scheme.Scheme.GetString() : null;
                bearerFormat = scheme.BearerFormat.IsNotUndefined() ? scheme.BearerFormat.GetString() : null;
            }
            else if (string.Equals(schemeType, "openIdConnect", StringComparison.Ordinal))
            {
                openIdConnectUrl = scheme.OpenIdConnectUrl.IsNotUndefined() ? scheme.OpenIdConnectUrl.GetString() : null;
            }
            else if (string.Equals(schemeType, "oauth2", StringComparison.Ordinal))
            {
                oauth2MetadataUrl = scheme.Oauth2MetadataUrl.IsNotUndefined() ? scheme.Oauth2MetadataUrl.GetString() : null;

                if (scheme.Flows.IsNotUndefined() && scheme.Flows.DeviceAuthorization.IsNotUndefined())
                {
                    var deviceFlow = scheme.Flows.DeviceAuthorization;
                    if (deviceFlow.DeviceAuthorizationUrl.IsNotUndefined())
                    {
                        deviceAuthorizationUrl = deviceFlow.DeviceAuthorizationUrl.GetString();
                    }
                }

                // Extract tokenUrl and authorizationUrl from the first flow that has them
                string? tokenUrl = null;
                string? authorizationUrl = null;
                HashSet<string> allScopes = [];

                if (scheme.Flows.IsNotUndefined())
                {
                    ExtractOAuth2FlowDetails(scheme.Flows, ref tokenUrl, ref authorizationUrl, allScopes);
                }

                result.Add(new SecuritySchemeInfo(
                    schemeName,
                    schemeType,
                    isDeprecated,
                    description,
                    apiKeyName,
                    apiKeyIn,
                    httpScheme,
                    bearerFormat,
                    openIdConnectUrl,
                    oauth2MetadataUrl,
                    deviceAuthorizationUrl,
                    tokenUrl,
                    authorizationUrl,
                    allScopes.Count > 0 ? [.. allScopes.Order(StringComparer.Ordinal)] : null));
                continue;
            }

            result.Add(new SecuritySchemeInfo(
                schemeName,
                schemeType,
                isDeprecated,
                description,
                apiKeyName,
                apiKeyIn,
                httpScheme,
                bearerFormat,
                openIdConnectUrl,
                oauth2MetadataUrl,
                deviceAuthorizationUrl));
        }

        return [.. result];
    }

    private static void ExtractOAuth2FlowDetails(
        OpenApiDocument.OauthFlows flows,
        ref string? tokenUrl,
        ref string? authorizationUrl,
        HashSet<string> allScopes)
    {
        // AuthorizationCode flow
        if (flows.AuthorizationCode.IsNotUndefined())
        {
            var flow = flows.AuthorizationCode;
            tokenUrl ??= flow.TokenUrl.IsNotUndefined() ? flow.TokenUrl.GetString() : null;
            authorizationUrl ??= flow.AuthorizationUrl.IsNotUndefined() ? flow.AuthorizationUrl.GetString() : null;
            CollectScopes(flow.Scopes, allScopes);
        }

        // ClientCredentials flow
        if (flows.ClientCredentials.IsNotUndefined())
        {
            var flow = flows.ClientCredentials;
            tokenUrl ??= flow.TokenUrl.IsNotUndefined() ? flow.TokenUrl.GetString() : null;
            CollectScopes(flow.Scopes, allScopes);
        }

        // Implicit flow
        if (flows.Implicit.IsNotUndefined())
        {
            var flow = flows.Implicit;
            authorizationUrl ??= flow.AuthorizationUrl.IsNotUndefined() ? flow.AuthorizationUrl.GetString() : null;
            CollectScopes(flow.Scopes, allScopes);
        }

        // Password flow
        if (flows.Password.IsNotUndefined())
        {
            var flow = flows.Password;
            tokenUrl ??= flow.TokenUrl.IsNotUndefined() ? flow.TokenUrl.GetString() : null;
            CollectScopes(flow.Scopes, allScopes);
        }

        // DeviceAuthorization flow
        if (flows.DeviceAuthorization.IsNotUndefined())
        {
            var flow = flows.DeviceAuthorization;
            tokenUrl ??= flow.TokenUrl.IsNotUndefined() ? flow.TokenUrl.GetString() : null;
            CollectScopes(flow.Scopes, allScopes);
        }
    }

    private static void CollectScopes(OpenApiDocument.MapOfStrings scopes, HashSet<string> allScopes)
    {
        if (scopes.IsNotUndefined())
        {
            foreach (var scopeProp in scopes.EnumerateObject())
            {
                allScopes.Add(scopeProp.Name);
            }
        }
    }

    private static OperationSecurityRequirementSet[]? ExtractSecurityRequirements(
        OpenApiDocument.Operation operation,
        JsonElement specRoot)
    {
        OpenApiDocument doc = specRoot;
        Dictionary<string, string> schemeTypes = BuildSecuritySchemeTypeLookup(specRoot);

        // Operation-level security overrides document-level
        if (operation.Security.IsNotUndefined())
        {
            return ParseSecurityRequirements(operation.Security, schemeTypes);
        }

        // Fall back to document-level security
        if (doc.Security.IsNotUndefined())
        {
            return ParseSecurityRequirements(doc.Security, schemeTypes);
        }

        return null;
    }

    /// <summary>
    /// Builds a map of security-scheme name to its OpenAPI <c>type</c> by reading
    /// <c>components.securitySchemes</c> directly from the raw document. Reading raw JSON keeps this
    /// version-agnostic and tolerant of the differing typed models across OpenAPI versions.
    /// </summary>
    private static Dictionary<string, string> BuildSecuritySchemeTypeLookup(JsonElement specRoot)
    {
        Dictionary<string, string> lookup = new(StringComparer.Ordinal);

        if (specRoot.ValueKind != JsonValueKind.Object
            || !specRoot.TryGetProperty("components"u8, out JsonElement components)
            || components.ValueKind != JsonValueKind.Object
            || !components.TryGetProperty("securitySchemes"u8, out JsonElement schemes)
            || schemes.ValueKind != JsonValueKind.Object)
        {
            return lookup;
        }

        foreach (var scheme in schemes.EnumerateObject())
        {
            if (scheme.Value.ValueKind == JsonValueKind.Object
                && scheme.Value.TryGetProperty("type"u8, out JsonElement schemeType)
                && schemeType.ValueKind == JsonValueKind.String)
            {
                lookup[scheme.Name] = schemeType.GetString()!;
            }
        }

        return lookup;
    }

    private static OperationSecurityRequirementSet[]? ParseSecurityRequirements(
        OpenApiDocument.Operation.SecurityRequirementArray securityArray,
        Dictionary<string, string> schemeTypes)
    {
        List<OperationSecurityRequirementSet> sets = [];

        // Each element of the array is an alternative (OR); the schemes within it are AND'd.
        foreach (OpenApiDocument.SecurityRequirement requirement in securityArray.EnumerateArray())
        {
            sets.Add(ParseSecurityRequirementSet(requirement, schemeTypes));
        }

        return sets.Count > 0 ? [.. sets] : null;
    }

    private static OperationSecurityRequirementSet[]? ParseSecurityRequirements(
        OpenApiDocument.SecurityRequirementArray securityArray,
        Dictionary<string, string> schemeTypes)
    {
        List<OperationSecurityRequirementSet> sets = [];

        foreach (OpenApiDocument.SecurityRequirement requirement in securityArray.EnumerateArray())
        {
            sets.Add(ParseSecurityRequirementSet(requirement, schemeTypes));
        }

        return sets.Count > 0 ? [.. sets] : null;
    }

    private static OperationSecurityRequirementSet ParseSecurityRequirementSet(
        OpenApiDocument.SecurityRequirement requirement,
        Dictionary<string, string> schemeTypes)
    {
        List<OperationSecurityRequirement> requirements = [];

        // Each property is one scheme: { "schemeName": ["scope1", "scope2"] }. An empty object marks
        // anonymous access as an accepted alternative.
        foreach (var schemeProp in requirement.EnumerateObject())
        {
            string schemeName = schemeProp.Name;
            List<string> scopes = [];

            foreach (var scope in schemeProp.Value.EnumerateArray())
            {
                scopes.Add(scope.GetString()!);
            }

            requirements.Add(new OperationSecurityRequirement(
                schemeName,
                [.. scopes],
                schemeTypes.TryGetValue(schemeName, out string? schemeType) ? schemeType : null));
        }

        return new OperationSecurityRequirementSet([.. requirements], requirements.Count == 0);
    }

    private static ServerInfo? ExtractServerInfo(OpenApiDocument.Server server)
    {
        if (server.Url.IsUndefined())
        {
            return null;
        }

        string urlTemplate = server.Url.GetString()!;
        List<ServerVariableInfo> variables = [];

        if (server.Variables.IsNotUndefined())
        {
            foreach (var kvp in server.Variables.EnumerateObject())
            {
                string varName = kvp.Name;
                OpenApiDocument.ServerVariable variable = kvp.Value;
                string defaultValue = variable.Default.IsNotUndefined()
                    ? (string)variable.Default
                    : string.Empty;

                string[]? allowedValues = null;
                if (variable.Enum.IsNotUndefined())
                {
                    List<string> values = [];
                    foreach (var item in variable.Enum.EnumerateArray())
                    {
                        values.Add((string)item);
                    }

                    allowedValues = [.. values];
                }

                variables.Add(new ServerVariableInfo(varName, defaultValue, allowedValues));
            }
        }

        return new ServerInfo(urlTemplate, [.. variables]);
    }

    private static ServerInfo? ResolveEffectiveServer(
        OpenApiDocument.Operation operation,
        OpenApiDocument.PathItem pathItem,
        ServerInfo? rootServer)
    {
        // OAS precedence: operation > path > root
        if (operation.Servers.IsNotUndefined())
        {
            foreach (var server in operation.Servers.EnumerateArray())
            {
                return ExtractServerInfo(server);
            }
        }

        if (pathItem.Servers.IsNotUndefined())
        {
            foreach (var server in pathItem.Servers.EnumerateArray())
            {
                return ExtractServerInfo(server);
            }
        }

        return rootServer;
    }

