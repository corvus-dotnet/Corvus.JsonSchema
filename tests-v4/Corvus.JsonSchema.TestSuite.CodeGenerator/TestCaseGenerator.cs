using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.Extensions.Configuration;
using TestUtilities.JsonSchemaTestSuite;

namespace Corvus.JsonSchema.TestSuite.CodeGenerator;

/// <summary>
/// Generates MSTest test classes for the JSON Schema Test Suite
/// using the V4 runtime Roslyn compilation driver.
/// </summary>
internal static class TestCaseGenerator
{
    private static readonly IConfiguration Config;

    static TestCaseGenerator()
    {
        Config = new ConfigurationBuilder()
            .AddJsonFile("appsettings.json", optional: false, reloadOnChange: false)
            .Build();
    }

    public static void GenerateTests(Action<string> fileCallback)
    {
        StringBuilder builder = new();

        string defaultOutputPath = Config["outputPath"] ?? throw new InvalidOperationException("You must provide an <outputPath> in app settings.");
        defaultOutputPath = Path.GetFullPath(defaultOutputPath);

        // Collect all test groups first to determine which output directories to clean
        List<TestGroup> allGroups = [.. ProvideTestGroups()];

        // Determine the set of distinct output directories
        HashSet<string> outputDirectories = [];
        foreach (TestGroup group in allGroups)
        {
            string dir = group.OutputDirectory is not null
                ? Path.GetFullPath(group.OutputDirectory)
                : defaultOutputPath;
            outputDirectories.Add(dir);
        }

        // Delete each output directory before regenerating
        foreach (string dir in outputDirectories)
        {
            if (Directory.Exists(dir))
            {
                Directory.Delete(dir, true);
            }
        }

        foreach (TestGroup testGroup in allGroups)
        {
            string namespaceGroup = ToPascalCase(testGroup.Name);
            string outputPath = testGroup.OutputDirectory is not null
                ? Path.GetFullPath(testGroup.OutputDirectory)
                : defaultOutputPath;
            string namespaceRoot = testGroup.NamespacePrefix ?? "JsonSchemaTestSuite";

            foreach (TestFile testFile in testGroup.Files)
            {
                HashSet<string> suiteNames = [];

                string relativePath = Path.ChangeExtension(testFile.RelativePath, ".cs");
                string outputFile = Path.Combine(outputPath, relativePath);

                string namespaceSuffix = GetNamespaceFromPath(testFile.NamespaceRelativePath);
                string namespaceValue = $"{namespaceRoot}.{namespaceGroup}{(namespaceSuffix.Length > 0 ? "." : string.Empty)}{namespaceSuffix}";

                // The featureName passed to the V4 driver becomes a namespace prefix via
                // "{featureName}Feature.{scenarioName}". Using the dotted namespaceValue
                // creates intermediate namespace segments (e.g. "Uri") that can collide with
                // generated type names. Flatten it to a single identifier to avoid this.
                string flatFeatureName = namespaceValue.Replace(".", string.Empty);
                fileCallback(relativePath);

                // Work on a new test file
                builder.Clear();

                // Always emit the auto-generated marker first (before any #if),
                // so StyleCop recognizes the file and skips analysis.
                builder.AppendLine("// <auto-generated/>");

                if (testFile.TfmCondition is not null)
                {
                    builder.AppendLine($"#if {testFile.TfmCondition}");
                }

                builder
                    .AppendLine("#nullable enable")
                    .AppendLine()
                    .AppendLine("using System.Text.Json;")
                    .AppendLine("using Corvus.Json;")
                    .AppendLine("using Corvus.Json.Specs.Tests.Infrastructure;")
                    .AppendLine("using Drivers;")
                    .AppendLine("using Microsoft.VisualStudio.TestTools.UnitTesting;")
                    .AppendLine()
                    .AppendLine($"namespace {namespaceValue};");

                foreach (TestSuite testSuite in testFile.TestSuites)
                {
                    string pascalSuiteName = GetUniqueName(ToPascalCase(testSuite.SuiteName), suiteNames);
                    builder
                        .AppendLine()
                        .AppendLine($"[TestCategory(\"{namespaceGroup}\")]")
                        .AppendLine("[TestClass]")
                        .AppendLine($"public class Suite{pascalSuiteName}")
                        .AppendLine("{")
                        .AppendLine("    private static Fixture? s_fixture;")
                        .AppendLine()
                        .AppendLine("    [ClassInitialize]")
                        .AppendLine($"    public static async Task ClassInit(TestContext _)")
                        .AppendLine("    {")
                        .AppendLine("        s_fixture = new Fixture();")
                        .AppendLine("        await s_fixture.InitializeAsync();")
                        .AppendLine("    }")
                        .AppendLine()
                        .AppendLine("    [ClassCleanup]")
                        .AppendLine("    public static void ClassCleanupMethod()")
                        .AppendLine("    {")
                        .AppendLine("        if (s_fixture is not null)")
                        .AppendLine("        {")
                        .AppendLine("            s_fixture.Dispose();")
                        .AppendLine("            s_fixture = null;")
                        .AppendLine("        }")
                        .AppendLine("    }");

                    HashSet<string> testNames = [];

                    foreach (TestSpecification test in testSuite.TestSpecifications)
                    {
                        string testName = GetUniqueName(ToPascalCase(test.TestDescription), testNames);

                        builder
                            .AppendLine()
                            .AppendLine("    [TestMethod]")
                            .AppendLine($"    public void Test{testName}()")
                            .AppendLine("    {")
                            .AppendLine($"        using var doc = JsonDocument.Parse({SymbolDisplay.FormatLiteral(test.Instance, true)});")
                            .AppendLine($"        IJsonValue instance = JsonSchemaBuilderDriver.CreateInstance(s_fixture!.GeneratedType, doc.RootElement);")
                            .AppendLine($"        Assert.{(test.Expectation ? "IsTrue" : "IsFalse")}(instance.Validate(ValidationContext.ValidContext).IsValid);")
                            .AppendLine("    }");
                    }

                    builder
                        .AppendLine()
                        .AppendLine("    public class Fixture : IDisposable")
                        .AppendLine("    {")
                        .AppendLine("        private JsonSchemaBuilderDriver? _driver;")
                        .AppendLine()
                        .AppendLine("        public global::System.Type GeneratedType { get; private set; } = null!;")
                        .AppendLine()
                        .AppendLine("        public async Task InitializeAsync()")
                        .AppendLine("        {")
                        .AppendLine($"            _driver = DriverFactory.{GetFactoryMethodName(testGroup.DriverSettingsKey)}();")
                        .AppendLine($"            GeneratedType = await _driver.GenerateTypeForJsonSchemaTestSuite(")
                        .AppendLine($"                {SymbolDisplay.FormatLiteral(testFile.NamespaceRelativePath, true)},")
                        .AppendLine($"                {SymbolDisplay.FormatLiteral(testSuite.SchemaPath, true)},")
                        .AppendLine($"                {SymbolDisplay.FormatLiteral(flatFeatureName, true)},")
                        .AppendLine($"                {SymbolDisplay.FormatLiteral(pascalSuiteName, true)},")
                        .AppendLine($"                validateFormat: {(testSuite.ValidateFormat ? "true" : "false")},")
                        .AppendLine("                optionalAsNullable: false,")
                        .AppendLine(testSuite.ExternalSchemasPath is null ? "                useImplicitOperatorString: false);" : "                useImplicitOperatorString: false,")
                        .AppendLineIf(testSuite.ExternalSchemasPath is not null, () => $"                externalSchemasPath: {SymbolDisplay.FormatLiteral(testSuite.ExternalSchemasPath!, true)});")
                        .AppendLine("        }")
                        .AppendLine()
                        .AppendLine("        public void Dispose()")
                        .AppendLine("        {")
                        .AppendLine("            _driver?.Dispose();")
                        .AppendLine("        }")
                        .AppendLine("    }")
                        .AppendLine("}");
                }

                if (testFile.TfmCondition is not null)
                {
                    builder.AppendLine("#endif");
                }

                Directory.CreateDirectory(Path.GetDirectoryName(outputFile)!);
                File.WriteAllText(outputFile, builder.ToString());
            }
        }
    }

    private static string GetFactoryMethodName(string driverSettingsKey) => driverSettingsKey switch
    {
        "jsonSchemaBuilder4DriverSettings" => "CreateDraft4Driver",
        "jsonSchemaBuilder6DriverSettings" => "CreateDraft6Driver",
        "jsonSchemaBuilder7DriverSettings" => "CreateDraft7Driver",
        "jsonSchemaBuilder201909DriverSettings" => "CreateDraft201909Driver",
        "jsonSchemaBuilder202012DriverSettings" => "CreateDraft202012Driver",
        "jsonSchemaBuilderOpenApi30DriverSettings" => "CreateOpenApi30Driver",
        "jsonSchemaBuilderAdditional4DriverSettings" => "CreateAdditionalDraft4Driver",
        "jsonSchemaBuilderAdditional6DriverSettings" => "CreateAdditionalDraft6Driver",
        "jsonSchemaBuilderAdditional7DriverSettings" => "CreateAdditionalDraft7Driver",
        "jsonSchemaBuilderAdditional201909DriverSettings" => "CreateAdditionalDraft201909Driver",
        "jsonSchemaBuilderAdditional202012DriverSettings" => "CreateAdditionalDraft202012Driver",
        "jsonSchemaBuilderAdditionalOpenApi30DriverSettings" => "CreateAdditionalOpenApi30Driver",
        "jsonSchemaBuilderOpenApi20DriverSettings" => "CreateOpenApi20Driver",
        "jsonSchemaBuilderAdditionalOpenApi20DriverSettings" => "CreateAdditionalOpenApi20Driver",
        _ => throw new InvalidOperationException($"Unknown driver settings key: {driverSettingsKey}"),
    };

    public static IEnumerable<TestGroup> ProvideTestGroups()
    {
        TestConfiguration jsonSchemaTestSuite = new();
        Config.Bind("jsonSchemaTestSuite", jsonSchemaTestSuite);

        // Always work with the full path
        string baseDirectory = Path.GetFullPath(jsonSchemaTestSuite.BaseDirectory);
        foreach (TestCollection collection in jsonSchemaTestSuite.Collections)
        {
            // Allow per-collection baseDirectory override (for additional schema tests
            // that live outside the JSON-Schema-Test-Suite submodule)
            string effectiveBaseDirectory = collection.BaseDirectory is not null
                ? Path.GetFullPath(collection.BaseDirectory)
                : baseDirectory;
            string currentDirectory = Path.Combine(effectiveBaseDirectory, collection.Directory);
            List<TestFile> testFiles = [];

            foreach (string file in Directory.EnumerateFiles(currentDirectory, "*.json", SearchOption.AllDirectories).OrderBy(f => f, StringComparer.Ordinal))
            {
                List<TestSuite> testSuites = [];

                string relativePath = Path.GetRelativePath(currentDirectory, file).Replace('\\', '/');
                string baseRelativePath = Path.GetRelativePath(effectiveBaseDirectory, file).Replace('\\', '/');

                if (collection.ExcludedDirectories?.Any(d => relativePath.StartsWith(d.TrimEnd('/') + "/", StringComparison.Ordinal)) == true)
                {
                    continue;
                }

                if (collection.Release is int)
                {
                    // The unified suite holds every dialect in one tree, so keep the generated tree
                    // as tests/<dialect>/<file>, as it was when the suite had one directory per dialect.
                    baseRelativePath = $"tests/{collection.Name}/{relativePath}";
                }

                PathOptions? pathOptions = collection.Options?.FirstOrDefault(fe => IsInPath(relativePath, fe.Path));
                FileExclusions? fileExclusions = collection.Exclusions?.FirstOrDefault(fe => EqualsPath(fe.File, relativePath));

                if (fileExclusions is FileExclusions f && f.Suites is null)
                {
                    // Entire file excluded
                    continue;
                }

                string json = File.ReadAllText(file);
                using JsonDocument doc = JsonDocument.Parse(json);
                if (doc.RootElement.ValueKind != JsonValueKind.Array)
                {
                    // Not a test file: a schema that other tests load by path (e.g. issue957-swagger.json).
                    continue;
                }

                // The unified layout is an object whose "tests" array holds the test cases, each
                // with a "compatibility" range; the legacy layout is a bare array of test cases.
                bool unified = collection.Release is int;

                if (!unified && doc.RootElement.ValueKind != JsonValueKind.Array)
                {
                    // Not a test file: a schema that other tests load by path (e.g. issue957-swagger.json).
                    continue;
                }

                JsonElement testCases = unified ? doc.RootElement.GetProperty("tests") : doc.RootElement;
                string testCasesPointer = unified ? "#/tests" : "#";

                int suiteIndex = 0;
                foreach (JsonElement testSuiteElement in testCases.EnumerateArray())
                {
                    if (collection.Release is int release)
                    {
                        string? compatibility = testSuiteElement.TryGetProperty("compatibility", out JsonElement compatibilityElement)
                            ? compatibilityElement.GetString()
                            : null;

                        if (!SuiteCompatibility.IsCompatible(compatibility, release))
                        {
                            suiteIndex++;
                            continue;
                        }

                        bool isFormatAnnotation = testSuiteElement.TryGetProperty("tags", out JsonElement caseTags) &&
                            caseTags.EnumerateArray().Any(t => t.ValueEquals("format-annotation"));

                        // Where the dialect asserts format by default (draft4 to draft7 in this
                        // implementation, which the specification allows), a "format-annotation" case
                        // describes behaviour the implementation does not provide, so it does not apply.
                        if (isFormatAnnotation && collection.FormatAssertedByDefault)
                        {
                            suiteIndex++;
                            continue;
                        }
                    }

                    List<TestSpecification> testList = [];
                    string suiteName = testSuiteElement.GetProperty("description").GetString()!;
                    string schemaPath = $"{testCasesPointer}/{suiteIndex}/schema";
                    string? externalSchemasPath = testSuiteElement.TryGetProperty("externalSchemas", out _)
                        ? $"{testCasesPointer}/{suiteIndex}/externalSchemas"
                        : null;

                    SuiteExclusions? suiteExclusions = null;
                    if (fileExclusions is FileExclusions fe)
                    {
                        suiteExclusions = fe.Suites?.FirstOrDefault(s => s.Name == suiteName);
                    }

                    // If the entire suite is excluded (no individual tests specified), skip it
                    if (suiteExclusions is SuiteExclusions se2 && se2.Tests is null)
                    {
                        suiteIndex++;
                        continue;
                    }

                    foreach (JsonElement test in testSuiteElement.GetProperty("tests").EnumerateArray())
                    {
                        string testDescription = test.GetProperty("description").GetString()!;

                        if (suiteExclusions is SuiteExclusions se)
                        {
                            if (se.Tests is List<TestExclusion> te &&
                                te.Any(t => t.Name == testDescription))
                            {
                                continue;
                            }
                        }

                        string data = test.GetProperty("data").GetRawText();
                        bool valid = test.GetProperty("valid").GetBoolean();

                        testList.Add(new TestSpecification(testDescription, data, valid));
                    }

                    if (testList.Count > 0)
                    {
                        // Check for validateFormat at suite level (in the JSON element itself),
                        // then fall back to path-level options
                        bool validateFormat = pathOptions?.ValidateFormat ?? false;
                        if (testSuiteElement.TryGetProperty("validateFormat", out JsonElement vfElement) &&
                            vfElement.ValueKind == JsonValueKind.True)
                        {
                            validateFormat = true;
                        }

                        // In the unified layout, a "format-assertion" tag means the case expects
                        // format to be asserted; "format-annotation" (or no tag) means the default.
                        if (testSuiteElement.TryGetProperty("tags", out JsonElement tags) &&
                            tags.EnumerateArray().Any(t => t.ValueEquals("format-assertion")))
                        {
                            validateFormat = true;
                        }

                        testSuites.Add(new TestSuite(suiteName, schemaPath, testList, validateFormat, externalSchemasPath));
                    }

                    suiteIndex++;
                }

                if (testSuites.Count > 0)
                {
                    // Detect TFM-specific files by suffix convention:
                    // *-net80.json → #if NET (only .NET 8+)
                    // *-netstandard20.json → #if !NET (only net481/netstandard2.0)
                    string? tfmCondition = null;
                    string fileNameNoExt = Path.GetFileNameWithoutExtension(file);
                    if (fileNameNoExt.EndsWith("-net80", StringComparison.OrdinalIgnoreCase))
                    {
                        tfmCondition = "NET";
                    }
                    else if (fileNameNoExt.EndsWith("-netstandard20", StringComparison.OrdinalIgnoreCase))
                    {
                        tfmCondition = "!NET";
                    }

                    testFiles.Add(new TestFile(collection.BaseDirectory ?? jsonSchemaTestSuite.BaseDirectory, baseRelativePath, relativePath, testSuites, tfmCondition));
                }
            }

            if (testFiles.Count > 0)
            {
                yield return new(collection.Name, collection.DriverSettingsKey, testFiles, collection.OutputDirectory, collection.NamespacePrefix);
            }
        }
    }

    internal static string ToPascalCase(string s)
    {
        if (string.IsNullOrEmpty(s))
        {
            return s;
        }

        StringBuilder result = new();
        bool nextUpper = true;

        foreach (char c in s)
        {
            if (c == ' ' || c == '-' || c == '_' || c == '/' || c == '\\' || c == '.')
            {
                nextUpper = true;
            }
            else if (char.IsLetterOrDigit(c))
            {
                result.Append(nextUpper ? char.ToUpperInvariant(c) : c);
                nextUpper = false;
            }
            else
            {
                nextUpper = true;
            }
        }

        // Ensure the result starts with a letter
        if (result.Length > 0 && char.IsDigit(result[0]))
        {
            result.Insert(0, '_');
        }

        return result.ToString();
    }

    private static string GetNamespaceFromPath(string path)
    {
        string namespacePath = Path.GetDirectoryName(path)!;
        string fileNameWithoutExtension = Path.GetFileNameWithoutExtension(path)!;
        string[] segments = namespacePath.Split([Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar], StringSplitOptions.RemoveEmptyEntries);
        string fileNameSegment = ToPascalCase(fileNameWithoutExtension);
        if (segments.Length > 0)
        {
            return $"{string.Join('.', segments.Select(p => ToPascalCase(p)))}.{fileNameSegment}";
        }

        return fileNameSegment;
    }

    private static string GetUniqueName(string v, HashSet<string> names)
    {
        if (names.Add(v))
        {
            return v;
        }

        int index = 1;
        while (true)
        {
            string name = $"{v}{index++}";
            if (names.Add(name))
            {
                return name;
            }
        }
    }

    private static bool IsInPath(string currentPath, string basePath)
    {
        return NormalizePath(currentPath).StartsWith(NormalizePath(basePath));
    }

    private static bool EqualsPath(string currentPath, string basePath)
    {
        return NormalizePath(currentPath).Equals(NormalizePath(basePath));
    }

    private static string NormalizePath(string path)
    {
        return path.Replace('\\', '/').TrimEnd('/');
    }
}

public record TestGroup(string Name, string DriverSettingsKey, List<TestFile> Files, string? OutputDirectory = null, string? NamespacePrefix = null);
public record TestFile(string BaseDirectory, string RelativePath, string NamespaceRelativePath, List<TestSuite> TestSuites, string? TfmCondition = null);
public record TestSuite(string SuiteName, string SchemaPath, List<TestSpecification> TestSpecifications, bool ValidateFormat, string? ExternalSchemasPath = null);
public record TestSpecification(string TestDescription, string Instance, bool Expectation);

public class TestConfiguration
{
    public string BaseDirectory { get; set; }
    public List<TestCollection> Collections { get; set; }
}

public class TestCollection
{
    public string Name { get; set; }
    public string DriverSettingsKey { get; set; }
    public string Directory { get; set; }
    public string? BaseDirectory { get; set; }
    public string? OutputDirectory { get; set; }
    public string? NamespacePrefix { get; set; }
    public int? Release { get; set; }
    public bool FormatAssertedByDefault { get; set; }
    public List<string>? ExcludedDirectories { get; set; }
    public bool UseVirtualFile { get; set; }
    public List<PathOptions>? Options { get; set; }
    public List<FileExclusions>? Exclusions { get; set; }
}

public class PathOptions
{
    public string Path { get; set; }
    public bool? ValidateFormat { get; set; }
}

public class FileExclusions
{
    public string File { get; set; }
    public string? Reason { get; set; }
    public List<SuiteExclusions>? Suites { get; set; }
}

public class SuiteExclusions
{
    public string Name { get; set; }
    public string? Reason { get; set; }
    public List<TestExclusion>? Tests { get; set; }
}

public class TestExclusion
{
    public string Name { get; set; }
    public string? Reason { get; set; }
}

/// <summary>
/// Helpers for conditionally emitting generated source lines.
/// </summary>
internal static class StringBuilderExtensions
{
    /// <summary>
    /// Appends a line only when the condition holds.
    /// </summary>
    /// <param name="builder">The builder.</param>
    /// <param name="condition">Whether to append the line.</param>
    /// <param name="line">Produces the line to append.</param>
    /// <returns>The builder.</returns>
    public static StringBuilder AppendLineIf(this StringBuilder builder, bool condition, Func<string> line)
        => condition ? builder.AppendLine(line()) : builder;
}