using System.Collections.Immutable;
using System.Text;
using Corvus.Json.SourceGenerator;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace Corvus.Text.Json.SourceGenerator.Tests;

/// <summary>
/// Locks the Roslyn behaviour that keeps analyzers off generated code: the generator's trees are classified as
/// generated, analyzers that opt out of generated code never execute on them, and the two configuration shapes the
/// repository uses (a section over checked-in generated folders, and a global severity of none restored per tree for
/// files on disk) stop analyzers that opt in from executing where intended while leaving compiler diagnostics alone.
/// </summary>
[TestClass]
public class GeneratedCodeAnalysisTests
{
    private const string SchemaFileName = "generated-code-analysis-schema.json";

    private const string Schema = """
        {
          "$schema": "https://json-schema.org/draft/2020-12/schema",
          "type": "object",
          "properties": {
            "name": { "type": "string" },
            "age": { "type": "integer" }
          },
          "required": ["name"]
        }
        """;

    private static readonly string TestDirectory = Path.Combine(Path.GetTempPath(), "corvus-generated-code-analysis-tests");

    private static readonly string HandWrittenPath = Path.Combine(TestDirectory, "Person.cs");

    private static readonly string Source = $$"""
        using Corvus.Text.Json;

        namespace AnalysisTests;

        [JsonSchemaTypeGenerator("{{SchemaFileName}}")]
        public readonly partial struct Person;
        """;

    /// <summary>
    /// Rule R1: every generator tree has a hint name ending in .g.cs and starts with the single-line auto-generated
    /// header, which is what the analyzer driver's generated-code classification keys on.
    /// </summary>
    [TestMethod]
    public void GeneratedTrees_AreClassifiedAsGenerated()
    {
        GeneratorRunResult result = RunGenerator(out _);
        Assert.IsTrue(result.GeneratedSources.Length > 1, "The generator should produce the attribute stub and the generated types.");
        foreach (GeneratedSourceResult source in result.GeneratedSources)
        {
            Assert.IsTrue(source.HintName.EndsWith(".g.cs", StringComparison.Ordinal), $"Hint name {source.HintName} should end in .g.cs.");
            string firstLine = source.SourceText.Lines[0].ToString();
            Assert.AreEqual("// <auto-generated/>", firstLine, $"Generated file {source.HintName} should start with the auto-generated header.");
        }
    }

    /// <summary>
    /// Rule 5: an analyzer that opts out of generated code (GeneratedCodeAnalysisFlags.None) gets no tree, node or
    /// operation callbacks for generator trees, and no symbol callbacks for symbols declared only in them.
    /// </summary>
    [TestMethod]
    public async Task OptOutAnalyzer_DoesNotExecuteOnGeneratorTrees()
    {
        RunGenerator(out Compilation compilation);
        RecordingAnalyzer analyzer = new(GeneratedCodeAnalysisFlags.None, report: false);
        CompilationWithAnalyzers withAnalyzers = compilation.WithAnalyzers([analyzer], new CompilationWithAnalyzersOptions(new AnalyzerOptions([]), onAnalyzerException: null, concurrentAnalysis: false, logAnalyzerExecutionTime: false));
        await withAnalyzers.GetAnalyzerDiagnosticsAsync(CancellationToken.None);

        Assert.IsTrue(compilation.SyntaxTrees.Count() > 2, "The compilation should hold the hand-written tree and the generator trees.");
        CollectionAssert.AreEquivalent(new[] { HandWrittenPath }, analyzer.TreeCallbacks.Distinct().ToArray(), "Tree actions should run only on the hand-written tree.");
        CollectionAssert.AreEquivalent(new[] { HandWrittenPath }, analyzer.NodeCallbacks.Distinct().ToArray(), "Node actions should run only on the hand-written tree.");
        Assert.AreEqual(0, analyzer.OperationCallbacks.Count, "Operation actions should not run: the hand-written tree has no operations.");
        CollectionAssert.AreEquivalent(new[] { "Person" }, analyzer.SymbolCallbacks.Distinct().ToArray(), "Symbol actions should run for the type with a hand-written declaration and for nothing declared only in generator trees.");
    }

    /// <summary>
    /// Rule R3: for checked-in generator output, an .editorconfig section that marks the folder as generated code,
    /// hides analyzer diagnostics in bulk and sets each diagnostic of an analyzer that analyses generated code to none
    /// stops that analyzer executing on those files, keeps it on the hand-written file, and leaves compiler diagnostics
    /// in the generated files reported.
    /// </summary>
    [TestMethod]
    public async Task GeneratedFolderSection_SkipsOptInAnalyzerAndKeepsCompilerDiagnostics()
    {
        string root = OperatingSystem.IsWindows() ? @"C:\repo" : "/repo";
        string handWritten = Path.Combine(root, "src", "Project", "Hand.cs");
        string generated = Path.Combine(root, "src", "Project", "Generated", "Gen.cs");
        AnalyzerConfig config = AnalyzerConfig.Parse(
            """
            root = true

            [{src/*/Generated,tests/*/Generated}/**.cs]
            generated_code = true
            dotnet_analyzer_diagnostic.severity = none
            dotnet_diagnostic.TEST001.severity = none
            """,
            Path.Combine(root, ".editorconfig"));
        AnalyzerConfigSet configSet = AnalyzerConfigSet.Create(ImmutableArray.Create(config));

        SyntaxTree handTree = CSharpSyntaxTree.ParseText(HandWrittenText, path: handWritten);
        SyntaxTree generatedTree = CSharpSyntaxTree.ParseText(GeneratedText, path: generated);
        (CSharpCompilation compilation, AnalyzerOptions options) = CreateConfiguredCompilation(configSet, [handTree, generatedTree], [handTree, generatedTree]);
        RecordingAnalyzer analyzer = new(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics, report: true);
        ImmutableArray<Diagnostic> analyzerDiagnostics = await compilation.WithAnalyzers([analyzer], new CompilationWithAnalyzersOptions(options, onAnalyzerException: null, concurrentAnalysis: false, logAnalyzerExecutionTime: false)).GetAnalyzerDiagnosticsAsync(CancellationToken.None);

        CollectionAssert.AreEquivalent(new[] { handWritten }, analyzer.TreeCallbacks.Distinct().ToArray(), "Tree actions should run only on the hand-written tree.");
        CollectionAssert.AreEquivalent(new[] { handWritten }, analyzer.NodeCallbacks.Distinct().ToArray(), "Node actions should run only on the hand-written tree.");
        CollectionAssert.AreEquivalent(new[] { handWritten }, analyzer.OperationCallbacks.Distinct().ToArray(), "Operation actions should run only on the hand-written tree.");
        CollectionAssert.AreEquivalent(new[] { handWritten }, analyzerDiagnostics.Select(d => d.Location.SourceTree?.FilePath).ToArray(), "TEST001 should be reported for the hand-written struct only.");
        CollectionAssert.AreEquivalent(new[] { "TEST001" }, analyzerDiagnostics.Select(d => d.Id).ToArray());
        AssertNullableWarningInGeneratedTree(compilation, generated);
    }

    /// <summary>
    /// Rule 18 (R5): a global severity of none for an analyzer's diagnostics, restored by an .editorconfig section for
    /// files on disk, stops the analyzer executing on a source generator tree (which, as in csc, has no per-tree
    /// options), keeps it executing and reporting on the hand-written tree, and leaves compiler diagnostics in the
    /// generator tree reported.
    /// </summary>
    [TestMethod]
    public async Task GlobalNoneRestoredPerTree_SkipsOptInAnalyzerOnGeneratorTrees()
    {
        string root = OperatingSystem.IsWindows() ? @"C:\repo" : "/repo";
        string handWritten = Path.Combine(root, "src", "Project", "Hand.cs");
        string generated = Path.Combine(root, "src", "Project", "obj", "Debug", "net10.0", "generated", "Corvus.Text.Json.SourceGenerator", "Corvus.Json.SourceGenerator.IncrementalSourceGenerator", "Gen.g.cs");
        AnalyzerConfig globalConfig = AnalyzerConfig.Parse(
            """
            is_global = true
            dotnet_diagnostic.TEST001.severity = none
            """,
            Path.Combine(root, "analyzers", "generated-code.globalconfig"));
        AnalyzerConfig editorConfig = AnalyzerConfig.Parse(
            """
            root = true

            [*.cs]
            dotnet_diagnostic.TEST001.severity = warning
            """,
            Path.Combine(root, ".editorconfig"));
        AnalyzerConfigSet configSet = AnalyzerConfigSet.Create(ImmutableArray.Create(globalConfig, editorConfig));

        SyntaxTree handTree = CSharpSyntaxTree.ParseText(HandWrittenText, path: handWritten);
        SyntaxTree generatedTree = CSharpSyntaxTree.ParseText(GeneratedText, path: generated);

        // As in csc, only the trees on disk have per-tree options; the generator tree is added afterwards and falls
        // back to the global value.
        (CSharpCompilation compilation, AnalyzerOptions options) = CreateConfiguredCompilation(configSet, [handTree], [handTree, generatedTree]);
        RecordingAnalyzer analyzer = new(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics, report: true);
        ImmutableArray<Diagnostic> analyzerDiagnostics = await compilation.WithAnalyzers([analyzer], new CompilationWithAnalyzersOptions(options, onAnalyzerException: null, concurrentAnalysis: false, logAnalyzerExecutionTime: false)).GetAnalyzerDiagnosticsAsync(CancellationToken.None);

        CollectionAssert.AreEquivalent(new[] { handWritten }, analyzer.TreeCallbacks.Distinct().ToArray(), "Tree actions should run only on the hand-written tree.");
        CollectionAssert.AreEquivalent(new[] { handWritten }, analyzer.NodeCallbacks.Distinct().ToArray(), "Node actions should run only on the hand-written tree.");
        CollectionAssert.AreEquivalent(new[] { handWritten }, analyzer.OperationCallbacks.Distinct().ToArray(), "Operation actions should run only on the hand-written tree.");
        CollectionAssert.AreEquivalent(new[] { handWritten }, analyzerDiagnostics.Select(d => d.Location.SourceTree?.FilePath).ToArray(), "TEST001 should be reported for the hand-written struct only.");
        CollectionAssert.AreEquivalent(new[] { DiagnosticSeverity.Warning }, analyzerDiagnostics.Select(d => d.Severity).ToArray(), "The restored severity should apply on the hand-written tree.");
        AssertNullableWarningInGeneratedTree(compilation, generated);
    }

    private const string HandWrittenText = """
        namespace AnalysisTests;

        public partial struct Hand
        {
            public static int Length(string value) => value.Length + 1;
        }
        """;

    private const string GeneratedText = """
        // <auto-generated/>
        #nullable enable
        namespace AnalysisTests;

        public partial struct Gen
        {
            public static int Length(string? value) => value.Length + 1;
        }
        """;

    private static void AssertNullableWarningInGeneratedTree(CSharpCompilation compilation, string generatedPath)
    {
        Diagnostic[] compilerDiagnostics = compilation.GetDiagnostics().Where(d => d.Severity >= DiagnosticSeverity.Warning).ToArray();
        CollectionAssert.AreEquivalent(new[] { "CS8602" }, compilerDiagnostics.Select(d => d.Id).ToArray(), "The dereference of a maybe-null value in the generated file should still be reported by the compiler.");
        Assert.AreEqual(generatedPath, compilerDiagnostics[0].Location.SourceTree?.FilePath);
    }

    private static GeneratorRunResult RunGenerator(out Compilation outputCompilation)
    {
        SyntaxTree tree = CSharpSyntaxTree.ParseText(Source, path: HandWrittenPath);
        CSharpCompilation compilation = CreateCompilation([tree], nullableContext: NullableContextOptions.Disable);
        GeneratorDriver driver = CSharpGeneratorDriver.Create(
            [new IncrementalSourceGenerator().AsSourceGenerator()],
            additionalTexts: [new InMemoryAdditionalText(Path.Combine(TestDirectory, SchemaFileName), Schema)]);
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out outputCompilation, out ImmutableArray<Diagnostic> diagnostics);
        GeneratorRunResult result = driver.GetRunResult().Results[0];
        Assert.IsNull(result.Exception, result.Exception?.ToString());
        Assert.AreEqual(0, diagnostics.Count(d => d.Severity == DiagnosticSeverity.Error), string.Join(Environment.NewLine, diagnostics));
        return result;
    }

    private static (CSharpCompilation Compilation, AnalyzerOptions Options) CreateConfiguredCompilation(AnalyzerConfigSet configSet, SyntaxTree[] treesOnDisk, SyntaxTree[] allTrees)
    {
        ImmutableDictionary<SyntaxTree, AnalyzerConfigOptionsResult>.Builder results = ImmutableDictionary.CreateBuilder<SyntaxTree, AnalyzerConfigOptionsResult>();
        foreach (SyntaxTree tree in treesOnDisk)
        {
            results.Add(tree, configSet.GetOptionsForSourcePath(tree.FilePath));
        }

        TestSyntaxTreeOptionsProvider provider = new(results.ToImmutable(), configSet.GlobalConfigOptions);
        CSharpCompilation compilation = CreateCompilation(allTrees, NullableContextOptions.Enable).WithOptions(
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable)
                .WithSyntaxTreeOptionsProvider(provider));
        return (compilation, new AnalyzerOptions([], new TestAnalyzerConfigOptionsProvider(provider)));
    }

    private static CSharpCompilation CreateCompilation(SyntaxTree[] trees, NullableContextOptions nullableContext)
    {
        IEnumerable<MetadataReference> references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
            .Split(Path.PathSeparator)
            .Where(p => Path.GetFileName(p) is "System.Runtime.dll" or "System.Private.CoreLib.dll" or "netstandard.dll" or "mscorlib.dll")
            .Select(p => MetadataReference.CreateFromFile(p));

        return CSharpCompilation.Create(
            "GeneratedCodeAnalysisTests",
            trees,
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: nullableContext));
    }

    /// <summary>
    /// The shape csc builds: per-tree options for the trees it parsed from disk, the global options for everything,
    /// and generated_code from the per-tree analyzer options.
    /// </summary>
    private sealed class TestSyntaxTreeOptionsProvider(ImmutableDictionary<SyntaxTree, AnalyzerConfigOptionsResult> results, AnalyzerConfigOptionsResult globalOptions) : SyntaxTreeOptionsProvider
    {
        public ImmutableDictionary<SyntaxTree, AnalyzerConfigOptionsResult> Results { get; } = results;

        public AnalyzerConfigOptionsResult GlobalOptions { get; } = globalOptions;

        public override GeneratedKind IsGenerated(SyntaxTree tree, CancellationToken cancellationToken)
        {
            if (this.Results.TryGetValue(tree, out AnalyzerConfigOptionsResult result) && result.AnalyzerOptions.TryGetValue("generated_code", out string? value))
            {
                return string.Equals(value, "true", StringComparison.OrdinalIgnoreCase) ? GeneratedKind.MarkedGenerated : GeneratedKind.NotGenerated;
            }

            return GeneratedKind.Unknown;
        }

        public override bool TryGetDiagnosticValue(SyntaxTree tree, string diagnosticId, CancellationToken cancellationToken, out ReportDiagnostic severity)
        {
            if (this.Results.TryGetValue(tree, out AnalyzerConfigOptionsResult result))
            {
                return result.TreeOptions.TryGetValue(diagnosticId, out severity);
            }

            severity = ReportDiagnostic.Default;
            return false;
        }

        public override bool TryGetGlobalDiagnosticValue(string diagnosticId, CancellationToken cancellationToken, out ReportDiagnostic severity)
        {
            return this.GlobalOptions.TreeOptions.TryGetValue(diagnosticId, out severity);
        }
    }

    private sealed class TestAnalyzerConfigOptionsProvider(TestSyntaxTreeOptionsProvider provider) : AnalyzerConfigOptionsProvider
    {
        public override AnalyzerConfigOptions GlobalOptions { get; } = new DictionaryAnalyzerConfigOptions(provider.GlobalOptions.AnalyzerOptions);

        public override AnalyzerConfigOptions GetOptions(SyntaxTree tree)
        {
            return provider.Results.TryGetValue(tree, out AnalyzerConfigOptionsResult result)
                ? new DictionaryAnalyzerConfigOptions(result.AnalyzerOptions)
                : new DictionaryAnalyzerConfigOptions(ImmutableDictionary<string, string>.Empty);
        }

        public override AnalyzerConfigOptions GetOptions(AdditionalText textFile) => new DictionaryAnalyzerConfigOptions(ImmutableDictionary<string, string>.Empty);
    }

    private sealed class DictionaryAnalyzerConfigOptions(ImmutableDictionary<string, string> values) : AnalyzerConfigOptions
    {
        public override bool TryGetValue(string key, [System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out string? value) => values.TryGetValue(key, out value);
    }

    [DiagnosticAnalyzer(LanguageNames.CSharp)]
    private sealed class RecordingAnalyzer(GeneratedCodeAnalysisFlags flags, bool report) : DiagnosticAnalyzer
    {
        private static readonly DiagnosticDescriptor Descriptor = new("TEST001", "Test", "Struct {0}", "Test", DiagnosticSeverity.Warning, isEnabledByDefault: true);

        public List<string> TreeCallbacks { get; } = [];

        public List<string> NodeCallbacks { get; } = [];

        public List<string> OperationCallbacks { get; } = [];

        public List<string> SymbolCallbacks { get; } = [];

        public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => [Descriptor];

        public override void Initialize(AnalysisContext context)
        {
            context.ConfigureGeneratedCodeAnalysis(flags);
            context.RegisterSyntaxTreeAction(c => this.TreeCallbacks.Add(c.Tree.FilePath));
            context.RegisterSyntaxNodeAction(
                c =>
                {
                    this.NodeCallbacks.Add(c.Node.SyntaxTree.FilePath);
                    if (report)
                    {
                        c.ReportDiagnostic(Diagnostic.Create(Descriptor, ((StructDeclarationSyntax)c.Node).Identifier.GetLocation(), ((StructDeclarationSyntax)c.Node).Identifier.Text));
                    }
                },
                SyntaxKind.StructDeclaration);
            context.RegisterOperationAction(c => this.OperationCallbacks.Add(c.Operation.Syntax.SyntaxTree.FilePath), OperationKind.Binary);
            context.RegisterSymbolAction(c => this.SymbolCallbacks.Add(c.Symbol.Name), SymbolKind.NamedType);
        }
    }

    private sealed class InMemoryAdditionalText(string path, string text) : AdditionalText
    {
        private readonly SourceText sourceText = SourceText.From(text, Encoding.UTF8);

        public override string Path => path;

        public override SourceText? GetText(CancellationToken cancellationToken = default) => this.sourceText;
    }
}